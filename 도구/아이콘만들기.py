# -*- coding: utf-8 -*-
"""
바탕화면 아이콘 다시 짓기 —  python3 도구/아이콘만들기.py

── 왜 이렇게까지 하나 (2026-09-11) ────────────────────────────

무무 님이 바탕화면 아이콘이 **뿌옇다**고 하셨습니다. 두 번 봤습니다.

【첫 번째 짐작 — 반만 맞았습니다】
  .ico 안의 열 장이 전부 PNG 로 눌려 있었고, 125%·150% 배율에서 쓰는
  20·40·96 이 없었습니다. 그래서 BMP 로 다시 굽고 크기도 채웠습니다.
  **그런데도 그대로 뿌옜습니다.**

【진짜 까닭 — exe 안의 「아이콘 목차」였습니다】
  bun 이 exe 에 아이콘을 넣을 때, 그림 열 장은 1~10 번으로 제대로
  넣습니다. 그런데 **bun 본체가 원래 갖고 있던 목차**(IDI_MYICON)를
  지우지 않고 그대로 둡니다. 그 목차에는 이렇게 적혀 있습니다 —

      「그림 한 장뿐. 256×256. 번호는 1번.」

  윈도는 exe 에서 아이콘을 고를 때 **이름 붙은 목차를 번호 목차보다
  먼저** 봅니다. 그래서 IDI_MYICON 을 집어 들고, 거기 적힌 대로
  **1번 그림**을 꺼냅니다. 1번은 크기 순서로 넣었으니 — **16×16.**

  즉 윈도는 여태 **16×16 한 장을 48 로, 96 으로 늘려서** 그리고
  있었습니다. .ico 를 아무리 잘 구워도 소용이 없던 까닭입니다.

【고친 법 — 큰 것을 1번에 놓습니다】
  exe 를 나중에 손대는 것은 못 합니다. bun 이 만든 exe 는 뒤에 프로그램
  본체가 통째로 붙어 있어서, 윈도의 리소스 고치기 API 를 쓰면 그 붙은
  덩어리가 날아갑니다.

  그럴 필요도 없습니다. **.ico 에 큰 것부터 담으면** 1번이 256×256 이
  되고, IDI_MYICON 이 적어 둔 「256×256, 1번」과 **그대로 맞습니다.**
  번호 목차(열 장 전부)도 맞으니, 윈도가 둘 중 어느 것을 집어도 됩니다.

  ★ 그래서 아래 크기 줄은 **내림차순이라야 합니다.** 오름차순으로
    되돌리면 아이콘이 다시 16×16 을 늘린 모양으로 돌아갑니다.
    (아이콘시험.ts 가 이것을 셉니다.)

【남은 한 가지 — .ico 를 배포본에도 넣습니다】
  install.ps1 은 바로가기에 `도구\아이콘.ico` 를 대려고 합니다. 그런데
  build.ps1 이 그 파일을 배포본에 안 담고 있어서, 그 줄은 여태 **한 번도
  돌지 않았습니다.** 담도록 고쳤습니다. 이제 바로가기는 exe 목차를 안
  거치고 .ico 를 곧장 씁니다.

원본은 `도구/아이콘-1024.png` 한 장입니다. 이것만 있으면 언제든 다시
지을 수 있습니다.
"""
import pathlib, struct, io
from PIL import Image, ImageFilter

뿌리 = pathlib.Path(__file__).parent
원본길 = 뿌리 / "아이콘-1024.png"
나갈길 = 뿌리 / "아이콘.ico"

# ★ 큰 것부터. 이 차례가 곧 exe 안의 번호가 됩니다 —
#   1번이 256×256 이라야 윈도가 늘려 그리지 않습니다. 위 설명 참조.
크기들 = [256, 128, 96, 64, 48, 40, 32, 24, 20, 16]

원본 = Image.open(원본길).convert("RGBA")
print(f"  원본  {원본길.name}  {원본.size[0]}×{원본.size[1]}")


def 줄이기(크기: int) -> Image.Image:
    im = 원본.resize((크기, 크기), Image.LANCZOS)
    # 작은 크기는 가장자리가 흐려집니다. 살짝만 세웁니다 —
    # 세게 하면 테두리에 흰 띠가 생겨 더 이상해집니다.
    if 크기 <= 48:
        im = im.filter(ImageFilter.UnsharpMask(radius=0.6, percent=55, threshold=0))
    return im


def bmp칸(im: Image.Image) -> bytes:
    """ICO 안에 들어가는 BMP 한 장 (32비트 + AND 마스크)."""
    w, h = im.size
    화소 = im.load()
    몸 = bytearray()
    # BMP 는 **아래에서 위로** 씁니다.
    for y in range(h - 1, -1, -1):
        for x in range(w):
            r, g, b, a = 화소[x, y]
            몸 += bytes((b, g, r, a))
    # AND 마스크 — 32비트에서는 안 쓰지만 **자리는 있어야** 합니다.
    한줄 = ((w + 31) // 32) * 4
    몸 += b"\x00" * (한줄 * h)
    머리 = struct.pack("<IiiHHIIiiII",
                       40, w, h * 2, 1, 32, 0, len(몸), 0, 0, 0, 0)
    return bytes(머리 + 몸)


칸들 = []
for 크기 in 크기들:
    im = 줄이기(크기)
    if 크기 == 256:
        통 = io.BytesIO(); im.save(통, format="PNG", optimize=True)
        칸들.append((크기, 통.getvalue(), "PNG"))
    else:
        칸들.append((크기, bmp칸(im), "BMP"))

머리 = struct.pack("<HHH", 0, 1, len(칸들))
자리 = 6 + 16 * len(칸들)
목차, 몸 = bytearray(), bytearray()
for 크기, 바이트, 꼴 in 칸들:
    목차 += struct.pack("<BBBBHHII",
                        0 if 크기 == 256 else 크기,
                        0 if 크기 == 256 else 크기,
                        0, 0, 1, 32, len(바이트), 자리 + len(몸))
    몸 += 바이트
    print(f"   {크기:3d}×{크기:<3d} {꼴}  {len(바이트):7,}바이트")

나갈길.write_bytes(머리 + bytes(목차) + bytes(몸))
print(f"\n  {나갈길.name}  —  {나갈길.stat().st_size:,}바이트")
