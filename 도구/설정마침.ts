/** 이 자료함은 필수 설정을 마친 것으로 칩니다. */
export function 설정마쳤다고(): void {
  try {
    db.run(
      "UPDATE organization SET setup_done_at = COALESCE(setup_done_at, ?) WHERE id = 1",
      [new Date().toISOString()]);
  } catch { /* 옛 자료함이면 그 칸이 없습니다 — 그러면 막지도 않습니다 */ }
}
