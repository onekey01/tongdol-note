/**
 * 서비스별 월 한도 — A-2 (7-사).
 *
 *   bun 월한도시험.ts
 *
 * 편람: 가사 월 12시간 · 식사 월 8회 · **동행 월 6시간과 2회** · 이미용 월 1회.
 *
 * 여기서 보는 것:
 *   1) 시간제는 **인정된 분**으로 잰다 (실제 분이 아니라 — 돈과 같은 기준)
 *   2) 횟수제는 건수로 잰다
 *   3) **동행지원은 둘 다 걸린다** — 시간이 남아도 세 번째는 안 됩니다
 *   4) 달이 바뀌면 0 으로 돌아간다
 *   5) 0 은 「한도를 안 봅니다」 (「복지부 지침 표준」이 그렇습니다)
 *   6) 미제공은 안 센다
 *   7) 분을 안 적은 옛 실적은 **한 번 = 한 시간** (정산과 같은 셈)
 */
import { randomUUID } from "node:crypto";
import { db, initDb } from "./server/db";
initDb();
import { 월사용, 시간말 } from "./server/한도";

let 통과수 = 0, 실패수 = 0;
function 통과해야(무엇: string, 참: unknown, 덧말 = "") {
  if (참) { 통과수++; console.log(`  통과  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
}

const 사람 = randomUUID();
const 프로필: any = db.query(
  `SELECT rp.* FROM region_profile rp JOIN organization o ON o.profile_id = rp.id WHERE o.id = 1`
).get();
const 만든것: number[] = [];

function 서비스(name: string, unit: string, 한도분: number, 한도횟수: number) {
  const i = db.run(
    `INSERT INTO service (profile_id, code, cat_l, cat_m, cat_s, name, unit, unit_price,
                          holiday_price, record_type, lifetime_cap, outside_annual_cap,
                          monthly_cap_minutes, monthly_cap_count, sort_order, active, custom)
     VALUES (?,?,'시험','시험','시험',?,?,10000,NULL,'time',NULL,0,?,?,900,1,1)`,
    [프로필.id, `MCAP-${randomUUID().slice(0, 8)}`, name, unit, 한도분, 한도횟수]);
  const id = Number(i.lastInsertRowid); 만든것.push(id); return id;
}
function 실적(svc: number, 날: string, 분: number | null, outcome = "제공") {
  db.run(
    `INSERT INTO delivery (recipient_id, service_id, served_on, outcome, is_holiday, minutes, created_at)
     VALUES (?,?,?,?,0,?,'x')`, [사람, svc, 날, outcome, 분]);
}
const 줄 = (m: string, svc: number) => 월사용(사람, m).find((x) => x.serviceId === svc);

try {
  db.run(
    `INSERT INTO recipient (id, payload, dong, status, created_at, updated_at)
     VALUES (?,?,?,?,?,?)`,
    [사람, JSON.stringify({ name: "월한도시험" }), "해남읍", "이용", "2026-09-01", "x"]);

  const 가사 = 서비스("시험가사", "hour", 720, 0);     // 월 12시간
  const 식사 = 서비스("시험식사", "meal", 0, 8);       // 월 8회
  const 동행 = 서비스("시험동행", "hour", 360, 2);     // 월 6시간 **과** 2회
  const 무한 = 서비스("시험무한", "hour", 0, 0);       // 한도 없음

  // ── 1. 시간제 — 인정된 분으로 잽니다 ───────────────────────
  console.log("\n── 1. 시간제는 **인정된 분**으로 잽니다 ─────────────────\n");
  실적(가사, "2026-09-01", 40);    // 실제 40 → 인정 30
  실적(가사, "2026-09-02", 50);    // 실제 50 → 인정 60
  let g = 줄("2026-09", 가사)!;
  통과해야("실제로 있었던 분은 90분", g.쓴분 === 90, `${g.쓴분}분`);
  통과해야("**한도는 인정된 90분으로 잽니다**", g.인정분합 === 90, `${g.인정분합}분`);
  통과해야("아직 안 넘음 (12시간 중 1시간 30분)", !g.넘었나, 시간말(g.인정분합));

  // 10분짜리는 인정이 안 되므로 한도도 안 깎습니다.
  실적(가사, "2026-09-03", 10);
  g = 줄("2026-09", 가사)!;
  통과해야("**15분을 못 넘긴 방문은 한도도 안 깎는다**", g.인정분합 === 90, `${g.인정분합}분`);
  통과해야("다녀간 횟수는 그래도 3번", g.쓴횟수 === 3, `${g.쓴횟수}번`);

  // ── 2. 경계 ───────────────────────────────────────────────
  console.log("\n── 2. 12시간 경계 ──────────────────────────────────────\n");
  for (let i = 4; i <= 13; i++) 실적(가사, `2026-09-${String(i).padStart(2, "0")}`, 60);
  g = 줄("2026-09", 가사)!;   // 90 + 600 = 690
  통과해야("11시간 30분 — 아직 안 넘음", !g.분넘었나, 시간말(g.인정분합));
  실적(가사, "2026-09-14", 30);   // 720 정각
  g = 줄("2026-09", 가사)!;
  통과해야("**12시간 정각은 넘은 것이 아니다**",
    g.인정분합 === 720 && !g.분넘었나, 시간말(g.인정분합));
  실적(가사, "2026-09-15", 30);   // 750
  g = 줄("2026-09", 가사)!;
  통과해야("**30분 더 가면 넘는다**", g.분넘었나, 시간말(g.인정분합));

  // ── 3. 횟수제 ─────────────────────────────────────────────
  console.log("\n── 3. 횟수제는 건수로 ──────────────────────────────────\n");
  for (let i = 1; i <= 8; i++) 실적(식사, `2026-09-${String(i).padStart(2, "0")}`, null);
  let m = 줄("2026-09", 식사)!;
  통과해야("8회 정각은 안 넘음", m.쓴횟수 === 8 && !m.넘었나, `${m.쓴횟수}회`);
  통과해야("**끼는 분을 안 셉니다**", m.쓴분 === 0 && m.인정분합 === 0);
  실적(식사, "2026-09-09", null);
  m = 줄("2026-09", 식사)!;
  통과해야("**9회째에 넘는다**", m.횟수넘었나, `${m.쓴횟수}회`);

  // ── 4. 동행 — 둘 다 걸립니다 ──────────────────────────────
  console.log("\n── 4. 동행지원은 **시간과 횟수 둘 다** ─────────────────\n");
  실적(동행, "2026-09-01", 60);
  실적(동행, "2026-09-08", 60);
  let d = 줄("2026-09", 동행)!;
  통과해야("2시간 · 2회 — 둘 다 안 넘음", !d.넘었나, `${시간말(d.인정분합)} · ${d.쓴횟수}회`);
  실적(동행, "2026-09-15", 60);
  d = 줄("2026-09", 동행)!;
  통과해야("**시간은 3시간뿐인데(6시간 한도) 3회째라 넘는다**",
    !d.분넘었나 && d.횟수넘었나 && d.넘었나,
    `${시간말(d.인정분합)} / 6시간 · ${d.쓴횟수}회 / 2회`);
  통과해야("무엇 때문에 넘었는지 갈라 보인다 — 횟수",
    d.횟수넘었나 && !d.분넘었나, "시간은 아직 남았습니다");

  // ── 5. 달이 바뀌면 ────────────────────────────────────────
  console.log("\n── 5. 달이 바뀌면 0 으로 ───────────────────────────────\n");
  통과해야("**10월에는 아무것도 안 쓴 것**", 줄("2026-10", 가사) === undefined);
  실적(가사, "2026-10-01", 60);
  const 시월 = 줄("2026-10", 가사)!;
  통과해야("10월 것만 셉니다", 시월.인정분합 === 60, 시간말(시월.인정분합));
  통과해야("9월 것은 그대로", 줄("2026-09", 가사)!.인정분합 === 750);

  // ── 6. 한도 0 · 미제공 ────────────────────────────────────
  console.log("\n── 6. 한도 0 은 「안 봅니다」 · 미제공은 안 셉니다 ──────\n");
  for (let i = 1; i <= 30; i++)
    실적(무한, `2026-09-${String(i).padStart(2, "0")}`, 600);
  const u = 줄("2026-09", 무한)!;
  통과해야("**한도가 0 이면 아무리 써도 안 넘었다고 한다**", !u.넘었나 && !u.봄,
    시간말(u.인정분합));

  실적(동행, "2026-09-20", 60, "미제공");
  const d2 = 줄("2026-09", 동행)!;
  통과해야("미제공은 안 센다", d2.쓴횟수 === 3, `${d2.쓴횟수}회`);

  // ── 7. 분을 안 적은 옛 실적 ───────────────────────────────
  console.log("\n── 7. 분을 안 적었으면 한 번 = 한 시간 (정산과 같은 셈) ─\n");
  const 옛가사 = 서비스("시험옛가사", "hour", 720, 0);
  실적(옛가사, "2026-11-01", null);
  실적(옛가사, "2026-11-02", null);
  const o = 줄("2026-11", 옛가사)!;
  통과해야("**두 번 갔으면 2시간**", o.인정분합 === 120, 시간말(o.인정분합));
  통과해야("정산이 세는 것과 같습니다 (두 화면이 다른 말을 하면 안 됩니다)",
    o.쓴분 === 120);

  // ── 8. 사람이 읽는 말 ─────────────────────────────────────
  console.log("\n── 8. 사람이 읽는 말로 ─────────────────────────────────\n");
  통과해야("720분은 「12시간」", 시간말(720) === "12시간", 시간말(720));
  통과해야("90분은 「1시간 30분」", 시간말(90) === "1시간 30분", 시간말(90));
  통과해야("30분은 「30분」", 시간말(30) === "30분", 시간말(30));
  통과해야("0분은 「0분」", 시간말(0) === "0분", 시간말(0));
} catch (e: any) {
  실패수++;
  console.log(`\n✗ 시험 도중 터졌습니다 — ${e?.message ?? e}`);
  if (e?.stack) console.log(String(e.stack).split("\n").slice(1, 4).join("\n"));
} finally {
  db.run("DELETE FROM delivery WHERE recipient_id = ?", [사람]);
  db.run("DELETE FROM recipient WHERE id = ?", [사람]);
  for (const s of 만든것) db.run("DELETE FROM service WHERE id = ?", [s]);
  console.log(`\n${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
  process.exit(실패수 ? 1 : 0);
}
