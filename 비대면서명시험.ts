/**
 * 비대면 배달 — 서명과 사진 —  bun 비대면서명시험.ts
 *
 * ═══════════════════════════════════════════════════════════
 *  왜 이 시험이 있나
 * ═══════════════════════════════════════════════════════════
 *
 * (2026-09-05 무무 — 「식사지원 시 비대면배달은 서명을 받을 수 없어!」
 *                    「비대면이어도 식사 전달 사진은 있어야 해.
 *                     마루 및 현관 등에 놓고 온 증빙용으로 필요」)
 *
 * 현장앱은 **시작 → 끝 → 서명 → 보내기** 한 줄로 돕니다. 그런데
 * 비대면 배달은 어르신을 못 뵈니 서명을 받을 수가 없습니다.
 * 그래서 **서명 화면에서 더 갈 데가 없었습니다.** 제공인력이 할 수
 * 있는 일은 둘뿐이었습니다 —
 *
 *   ① 그냥 안 보낸다        → 그날 실적이 사무실에 안 갑니다
 *   ② 자기가 대신 긋는다    → **이용자 확인서명 위조**입니다
 *
 * 지금은 비대면이면 서명을 건너뛰고, 대신 **놓아 둔 자리를 찍은 사진**을
 * 받습니다. 사진이 서명의 자리를 대신합니다 — 그것마저 없으면 「두고
 * 왔습니다」라는 말만 남고 기관이 댈 것이 없습니다.
 *
 * ── 무는지 확인했습니다 ───────────────────────────────────
 *
 * `서명받을수있나` 를 늘 true 로 되돌리면 2가지가, `사진이꼭있어야하나` 를
 * 늘 false 로 되돌리면 1가지가 실패합니다. ②의 것들은 화면 글을 보는
 * 시험이라 함수 속을 바꿔도 안 걸립니다 — 두 갈래를 **함께** 두는
 * 까닭이 그것입니다.
 */
import { chromium } from "playwright";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const 뿌리 = fileURLToPath(new URL(".", import.meta.url));
const 글 = readFileSync(뿌리 + "현장앱/올릴것/index.html", "utf8");

let 통과 = 0, 실패 = 0;
function 본다(무엇: string, ok: unknown, 덧말 = "") {
  if (ok) { 통과++; console.log(`  통과  ${무엇}${덧말 ? "  — " + 덧말 : ""}`); }
  else { 실패++; console.log(`✗ 실패  ${무엇}${덧말 ? "  — " + 덧말 : ""}`); }
}

/*
 * ★ localhost 로 띄웁니다 — 앱이 WebCrypto 를 쓰는데
 *   file:// 에서는 `crypto.subtle` 이 아예 없습니다.
 */
const 서버 = Bun.serve({
  port: 0,
  fetch: () => new Response(글, { headers: { "content-type": "text/html; charset=utf-8" } }),
});
const 주소 = `http://localhost:${서버.port}/`;

const 브라우저 = await chromium.launch({
  executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome",
  args: ["--no-sandbox"],
});
const 쪽 = await (await 브라우저.newContext()).newPage();

try {
  await 쪽.goto(주소, { waitUntil: "domcontentloaded" });
  await 쪽.waitForTimeout(400);

  // ══════════════════════════════════════════════════════════
  //  ① 서명을 받을 수 있는 건인가 ★
  // ══════════════════════════════════════════════════════════
  console.log("\n── ① **비대면이면 서명을 안 묻는다** ★ ───────────\n");

  const 물어보기 = (갈래: string, 형태: string | null) =>
    쪽.evaluate(([g, f]: any) => {
      const p = { id: "x", 갈래: g };
      const 기 = { 적은것: f ? { 제공형태: f } : {} };
      return {
        서명: (window as any).서명받을수있나(p, 기),
        사진: (window as any).사진이꼭있어야하나(p, 기),
      };
    }, [갈래, 형태]);

  {
    const a = await 물어보기("식사", "비대면배달");
    본다("★ 식사 · 비대면이면 서명을 못 받는다", a.서명 === false);
    본다("★ 그 대신 사진이 꼭 있어야 한다", a.사진 === true,
      "사진이 서명의 자리를 대신합니다");

    const b = await 물어보기("식사", "대면배달");
    본다("식사 · 대면이면 서명을 받는다", b.서명 === true);
    본다("대면은 사진을 막지 않는다", b.사진 === false,
      "서명이 이미 근거입니다 — 사진 못 찍었다고 그날 실적을 통째로 막으면 더 나쁩니다");

    /*
     * ★ 아직 안 고른 것은 **대면으로 봅니다.**
     *   원칙이 대면이고, 비대면은 일부러 고르는 것입니다.
     *   여기가 뒤집히면 안 고른 건이 죄다 서명 없이 나갑니다.
     */
    const c = await 물어보기("식사", null);
    본다("★ 형태를 안 골랐으면 서명을 받는다", c.서명 === true,
      "원칙이 대면입니다 — 안 고른 것을 비대면으로 보면 서명 없이 나갑니다");

    const d = await 물어보기("가사", "비대면배달");
    본다("★ 가사는 비대면이라는 것이 없다", d.서명 === true,
      "식사지원만 묻는 것입니다");
    본다("가사는 사진을 안 막는다", d.사진 === false);
  }

  // ══════════════════════════════════════════════════════════
  //  ② 화면에 그 길이 있는가 ★
  // ══════════════════════════════════════════════════════════
  console.log("\n── ② **빠져나갈 길**이 화면에 있는가 ★ ───────────\n");
  {
    const 소스 = await 쪽.content();
    본다("★ 서명 화면에 「문 앞에 두고 왔습니다」 곁길이 있다",
      소스.includes("비대면이라서명못받음"),
      "이 길이 없으면 제공인력이 자기 손으로 어르신 성함을 긋습니다");
    본다("★ 그 길이 제공형태를 「비대면배달」로 적는다",
      /비대면이라서명못받음[\s\S]{0,900}적기\(p\.id, "제공형태", "비대면배달"\)/.test(소스),
      "그냥 건너뛰기만 하면 왜 서명이 없는지 아무 데도 안 남습니다");
    본다("★ 사진이 없으면 보내기 대신 「사진 찍으러 가기」가 뜬다",
      소스.includes("사진 찍으러 가기"));
    본다("★ 보낼 때 서명이 없는 까닭을 같이 싣는다",
      소스.includes('서명없음:') && 소스.includes('"비대면배달"'),
      "빈 칸만 가면 사무실이 「받아야 하는데 안 받았구나」로 읽습니다");
    본다("★ 상태 줄이 「사진이 없습니다」를 말한다",
      소스.includes("사진이 없습니다"));
    본다("보낸 뒤에는 잠긴다 (서명이 없어도)",
      소스.includes("(!!기.서명 || !!기.보냄)"),
      "서명만 보고 잠그면 비대면은 영영 안 잠깁니다");
  }

} catch (e: any) {
  실패++;
  console.log(`\n✗ 실패  시험 도중 터짐 — ${e?.message ?? e}`);
  if (e?.stack) console.log(String(e.stack).split("\n").slice(1, 4).join("\n"));
} finally {
  await 브라우저.close();
  서버.stop(true);
  console.log(`\n${통과 + 실패}가지 중 ${통과}가지 통과, ${실패}가지 실패\n`);
  process.exit(실패 ? 1 : 0);
}
