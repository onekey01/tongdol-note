/**
 * 이름표 뒤에 **값만** 얹기 — B-1 의 새 연장.
 *
 *   bun 서식채우기시험.ts
 *
 * **함수보다 이 시험이 먼저 나왔습니다.**
 *
 * ── 왜 새 연장이 필요한가 ────────────────────────────────────
 *
 * 지금까지 서식을 채우는 방법은 **칸을 통째로 갈아 끼우는 것**이었습니다.
 * 기록지(서식9)는 표가 잘게 나뉘어 있어 그것으로 됐습니다.
 *
 * 서식7(영수증)은 다릅니다. 한 칸 안에 문단 열두 개가 들어 있고,
 * **이름표와 값이 같은 줄**에 있습니다 —
 *
 *     거래번호 :
 *     이용자명 :                (서명)
 *     금    액 : 서비스 가격                       원
 *
 * 칸을 갈아 끼우면 **「거래번호 :」라는 이름표까지 지웁니다.**
 * 서식을 고치는 것이 되고, 그건 하면 안 되는 일입니다.
 *
 * ── 그래서 이렇게 합니다 ─────────────────────────────────────
 *
 * **빈칸(공백)에 값을 얹습니다. 글자 수는 그대로 둡니다.**
 * 그러면 뒤따르는 「원」·「(서명)」이 제자리에 남습니다.
 *
 * ── 못 찾으면 터뜨립니다 ─────────────────────────────────────
 *
 * 이름표를 못 찾았는데 조용히 넘어가면 **빈 영수증이 어르신께 갑니다.**
 * 서식이 개정되어 글자가 바뀌면 **그 자리에서 알아야** 합니다.
 */
import { 얹기, 자리바꾸기, 날짜얹기, 금액말 } from "./server/서식채우기";

let 통과수 = 0, 실패수 = 0;
function 같아야(무엇: string, 실제: unknown, 바람: unknown) {
  if (실제 === 바람) { 통과수++; console.log(`  통과  ${무엇}\n          ${JSON.stringify(실제)}`); }
  else {
    실패수++;
    console.log(`✗ 실패  ${무엇}\n          나온 것 ${JSON.stringify(실제)}\n          바란 것 ${JSON.stringify(바람)}`);
  }
}
function 참이어야(무엇: string, 참: unknown, 덧말 = "") {
  if (참) { 통과수++; console.log(`  통과  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
}

console.log("\n── 1. 이름표로 끝나는 줄 — 뒤에 붙입니다 ───────────────\n");

같아야("거래번호", 얹기("거래번호 :", "거래번호 :", "2026-0001"),
  "거래번호 : 2026-0001");
같아야("이름표 뒤에 이미 한 칸이 있으면 그 칸을 씁니다",
  얹기("서비스명 : ", "서비스명 :", "가사지원"), "서비스명 : 가사지원");

console.log("\n── 2. 빈칸에 얹기 — **글자 수를 지킵니다** ─────────────\n");

const 이용자 = "이용자명 :                (서명)";
const 채운것 = 얹기(이용자, "이용자명 :", "김순자")!;
같아야("이용자명", 채운것, "이용자명 : 김순자            (서명)");
같아야("**길이가 그대로라 「(서명)」이 제자리에 있습니다**",
  채운것.length, 이용자.length);

console.log("\n── 3. 오른쪽으로 붙이기 — 금액은 「원」 앞에 ───────────\n");

const 가격 = "서비스 가격                       원";
const 가격채움 = 얹기(가격, "서비스 가격", "11,000", "오른쪽")!;
같아야("금액이 「원」 바로 앞에 붙습니다", 가격채움,
  "서비스 가격                 11,000원");
같아야("길이 그대로", 가격채움.length, 가격.length);

console.log("\n── 4. 한 줄에 이름표가 여럿 — 각각 제자리에 ────────────\n");

let 줄 = "금    액 : 서비스 가격                       원정부 지원금                       원";
줄 = 얹기(줄, "서비스 가격", "11,000", "오른쪽")!;
줄 = 얹기(줄, "정부 지원금", "8,800", "오른쪽")!;
같아야("둘 다 들어갔습니다", 줄,
  "금    액 : 서비스 가격                 11,000원정부 지원금                  8,800원");
같아야("길이 그대로",
  줄.length,
  "금    액 : 서비스 가격                       원정부 지원금                       원".length);

console.log("\n── 5. 괄호 안의 빈칸 ───────────────────────────────────\n");

같아야("본인부담금(     원)", 얹기("본인부담금(        원)", "본인부담금(", "2,200", "오른쪽"),
  "본인부담금(   2,200원)");

console.log("\n── 6. 값이 빈칸보다 길면 — **자르지 않습니다** ─────────\n");

const 긴것 = 얹기("이용자명 :   (서명)", "이용자명 :", "박병섭님")!;
참이어야("**글자가 잘리지 않습니다** — 종이가 조금 밀려도 값이 먼저입니다",
  긴것.includes("박병섭님"), 긴것);
참이어야("꼬리도 살아 있습니다", 긴것.includes("(서명)"), 긴것);

console.log("\n── 7. **못 찾으면 알려 줍니다** ────────────────────────\n");

같아야("없는 이름표는 null — 조용히 넘어가지 않습니다",
  얹기("거래번호 :", "영수증번호 :", "x"), null);
참이어야("빈 영수증이 어르신께 가는 것을 막습니다", 얹기("아무 글", "이름표", "값") === null);

console.log("\n── 7-나. 자리 표시(◯◯◯◯)는 **그 자리를 바꿉니다** ───────\n");

같아야("기관 이름이 동그라미 자리를 대신합니다",
  자리바꾸기("◯◯◯◯제공기관 대표 (인)", "◯◯◯◯", "해남돌봄센터"),
  "해남돌봄센터제공기관 대표 (인)");
참이어야("**(인) 은 남습니다** — 도장 찍는 자리입니다",
  자리바꾸기("◯◯◯◯제공기관 대표 (인)", "◯◯◯◯", "해남돌봄센터")!.includes("(인)"));
같아야("짧으면 빈칸으로 메워 길이를 지킵니다",
  자리바꾸기("◯◯◯◯대표", "◯◯◯◯", "가나")!.length, "◯◯◯◯대표".length);
같아야("없으면 null", 자리바꾸기("아무 글", "◯◯◯◯", "x"), null);

console.log("\n── 8. 날짜 틀 ──────────────────────────────────────────\n");

/*
 * 「20」이 이미 인쇄된 틀은 뒤 두 자리만 채웁니다.
 * **길이를 지키느라** 「년」 앞에 한 칸이 남습니다 — 종이가 안 밀립니다.
 */
같아야("「20   년    월     일」 — 20 은 서식에 이미 있습니다",
  날짜얹기("을 20   년    월     일", 2026, 9, 1),
  "을 2026 년   9월    1일");
같아야("「 년     월      일」 — 해를 통째로",
  날짜얹기(" 년     월      일", 2026, 9, 1),
  "2026년    9월     1일");
같아야("날짜 틀이 아니면 null", 날짜얹기("아무 글", 2026, 9, 1), null);

console.log("\n── 9. 돈은 세 자리마다 쉼표 ────────────────────────────\n");

같아야("11000", 금액말(11000), "11,000");
같아야("0", 금액말(0), "0");
같아야("1234567", 금액말(1234567), "1,234,567");

console.log(`\n${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
process.exit(실패수 ? 1 : 0);
