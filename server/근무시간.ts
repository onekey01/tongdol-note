/**
 * 사무실 PC 를 **언제 켜고 언제 끌 것인가.**
 *
 * ═══════════════════════════════════════════════════════════
 *  왜 필요한가 — 관리자가 늘 자리에 있지는 않습니다
 * ═══════════════════════════════════════════════════════════
 *
 * 이 프로그램이 꺼져 있으면 —
 *
 *   · 제공인력 폰이 새 휴대폰으로 로그인할 때 열쇠를 못 받습니다
 *   · 폰이 보낸 보고가 안 내려옵니다 (우편함에서 14일 기다립니다)
 *   · 바뀐 일정이 안 올라갑니다
 *
 * 관리자가 오전 반차면 오후에나 켜집니다. 그동안 현장은 「왜 안 되지」
 * 입니다. (2026-09-05 무무)
 *
 * ═══════════════════════════════════════════════════════════
 *  둘은 **성질이 다릅니다**
 * ═══════════════════════════════════════════════════════════
 *
 *   ① 켜기 — **상시 설정.** 한 번 켜 두면 계속 그렇습니다.
 *      PC 를 켜면 통돌 Note 도 같이 켜집니다. 사무실 동료가
 *      **컴퓨터만 켜 주면** 됩니다. 동료는 관리자 계정을 모르니
 *      어르신 자료는 못 봅니다 — **켜는 것과 보는 것이 갈립니다.**
 *
 *   ② 끄기 — **그날그날의 예약.** 늘 몇 시간 뒤에 꺼지면 안 됩니다.
 *      반차라 일찍 나가는 날, 「6시간 뒤에 꺼 줘」 하고 거는 것입니다.
 *      컴퓨터를 다시 켜면 예약은 없습니다.
 *      (2026-09-05 무무 — 「켜는것은 상시이지만 끄는 것은 일시적
 *       이벤트로 필요할때만 시간 설정해서 끄도록 해줘야 해.」)
 *
 *   처음에 ②를 「몇 시간 뒤에 끌까요」라는 상시 설정으로 만들었는데
 *   그건 틀린 모양이었습니다.
 *
 * ═══════════════════════════════════════════════════════════
 *  「창을 닫으면 꺼짐」은 그대로입니다
 * ═══════════════════════════════════════════════════════════
 *
 * 한때 「예약을 걸면 창을 닫아도 안 꺼지게」 해 볼까 했습니다.
 * **무무가 곧바로 물렸습니다** — 「일반 이용자가 백그라운드에서
 * 돌아가고 있는 상황을 인지할 수 있는 방법이 없어.」
 *
 * 맞는 말입니다. 모르는 채 도는 프로그램이, 창이 닫혀 잠깐 멈추는
 * 것보다 나쁩니다. 멈춘 동안 온 것은 우편함이 **14일** 들고 있다가
 * 다음에 켜면 내려 줍니다 — 잃지 않습니다.
 *
 * ★ 종료 예약은 **윈도우가 들고 있습니다.** 그래서 통돌 Note 창을
 *   닫아도 컴퓨터는 예약한 시각에 꺼집니다. 반차 나가시면서 예약을
 *   걸고 창을 닫으셔도 됩니다.
 */
import { metaGet, metaSet } from "./db";
import { join } from "node:path";
import { existsSync } from "node:fs";

/** 지금부터 몇 시간 뒤에 끌 것인가 — 고를 수 있는 것들. */
export const 예약시간들 = [
  { 값: 1,  이름: "1시간 뒤" },
  { 값: 2,  이름: "2시간 뒤" },
  { 값: 3,  이름: "3시간 뒤" },
  { 값: 4,  이름: "4시간 뒤" },
  { 값: 6,  이름: "6시간 뒤" },
  { 값: 8,  이름: "8시간 뒤" },
] as const;

/** 컴퓨터를 끄기 **몇 분 전**에 알릴 것인가. 윈도우가 제 창으로 알려 줍니다. */
export const 미리알림분 = 5;
/* ── PC 를 켜면 저절로 켜지게 ────────────────────────────── */

/**
 * 윈도우 **시작프로그램**에 바로가기를 넣고 뺍니다.
 *
 * 하는 일은 `autostart.ps1` 이 다 합니다. 여기서는 부르기만 합니다.
 *
 * ★ 왜 경로를 안 넘기나 —
 *   기관 폴더 이름에 한글이 섞이면(실제로 흔합니다) 명령줄로 넘기는
 *   사이에 깨집니다. `autostart.ps1` 은 **자기가 있는 자리**를 스스로
 *   알기 때문에(`$PSScriptRoot`) 넘길 것이 없습니다.
 */
const 뿌리 = process.cwd();
const 켜기스크립트 = join(뿌리, "autostart.ps1");

export function 자동시작인가(): boolean {
  return metaGet("auto_start") === "1";
}

export async function 자동시작정하기(켤까: boolean): Promise<boolean> {
  if (process.platform !== "win32")
    throw new Error("윈도우에서만 됩니다.");
  if (!existsSync(켜기스크립트))
    throw new Error("autostart.ps1 이 없습니다. 프로그램을 다시 받아 주세요.");

  const p = Bun.spawn(
    ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
     "-File", 켜기스크립트, 켤까 ? "-On" : "-Off"],
    { stdout: "pipe", stderr: "pipe" });
  const 났나 = await p.exited;
  if (났나 !== 0) {
    const 말 = (await new Response(p.stderr).text()).trim();
    throw new Error(말 || "시작프로그램을 고치지 못했습니다.");
  }
  metaSet("auto_start", 켤까 ? "1" : "0");
  return 켤까;
}

/* ── 그날그날의 종료 예약 ────────────────────────────────── */

/**
 * 언제 꺼지기로 되어 있나 (ISO). 예약이 없으면 null.
 *
 * ★ 왜 자료함에 적어 두나 —
 *   예약은 **윈도우가** 들고 있습니다. 우리 쪽에 안 적어 두면
 *   프로그램을 껐다 켰을 때 「지금 예약이 걸려 있나」를 알 길이
 *   없어져서, 화면이 아무 말도 못 합니다.
 *   지난 예약은 읽을 때 스스로 지웁니다.
 */
export function 예약된때(): string | null {
  const v = metaGet("shutdown_at");
  if (!v) return null;
  if (new Date(v).getTime() <= Date.now()) {   // 이미 지난 것
    metaSet("shutdown_at", "");
    return null;
  }
  return v;
}

export const 예약중인가 = () => !!예약된때();

/**
 * **지금부터 몇 시간 뒤에 컴퓨터를 끕니다.**
 *
 * ★ 우리가 직접 끄지 않고 `shutdown /s /t` 를 쓰는 까닭 —
 *   윈도우가 **제 창으로 미리 알려 주고**, 다른 프로그램에게도
 *   저장할 틈을 줍니다. 무엇보다 사람이 되물릴 수 있습니다.
 *   우리가 곧바로 끄면 옆자리 사람이 적던 문서가 날아갑니다.
 *
 *   그리고 **윈도우가 들고 있으니** 통돌 Note 창을 닫아도 예약은
 *   그대로 남습니다. 반차 나가시면서 걸고 닫으셔도 됩니다.
 */
export function 종료예약(시간: unknown): string {
  const v = Number(시간);
  if (!예약시간들.some((x) => x.값 === v))
    throw new Error("고를 수 없는 시간입니다.");
  if (process.platform !== "win32")
    throw new Error("윈도우에서만 됩니다.");

  const 몇초 = Math.round(v * 3600);
  const 언제 = new Date(Date.now() + 몇초 * 1000).toISOString();

  // 앞서 걸어 둔 것이 있으면 물리고 새로 겁니다 (두 개는 못 겁니다).
  try { Bun.spawn(["shutdown", "/a"], { stdout: "ignore", stderr: "ignore" }); } catch { }

  Bun.spawn(["shutdown", "/s", "/t", String(몇초), "/c",
             "통돌 Note: 예약하신 시각이 되어 컴퓨터를 끕니다."],
            { stdout: "ignore", stderr: "ignore" });

  metaSet("shutdown_at", 언제);
  return 언제;
}

/**
 * 걸어 둔 종료를 되물립니다.
 *
 * ★ 이름을 `예약취소` 가 아니라 `종료예약취소` 로 둡니다 —
 *   `server/backup.ts` 에 **되돌리기 예약**을 무르는 `예약취소` 가
 *   이미 있습니다. 같은 이름 둘이 한 파일로 불려 들어오면 조용히
 *   엉뚱한 것이 불립니다. 이 프로젝트에서 이미 한 번 크게 데었습니다
 *   (현장앱의 `잠그기`).
 */
export function 종료예약취소(): void {
  if (process.platform === "win32") {
    try { Bun.spawn(["shutdown", "/a"], { stdout: "ignore", stderr: "ignore" }); } catch { }
  }
  metaSet("shutdown_at", "");
}

/** 설정 화면과 띠에 내려 줄 것. */
export function 근무시간정보() {
  return {
    자동시작: 자동시작인가(),
    자동시작됨: process.platform === "win32",
    예약된때: 예약된때(),
    예약시간들,
    미리알림분,
  };
}
