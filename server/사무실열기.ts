/**
 * 사무실 안 **다른 컴퓨터**에서 들어오게 잠깐 열어 둡니다.
 *
 * ═══════════════════════════════════════════════════════════
 *  왜 필요한가
 * ═══════════════════════════════════════════════════════════
 *
 * 통돌 Note 는 `127.0.0.1` 에만 귀를 엽니다 — **그 컴퓨터 안에서만**
 * 열리는 주소입니다. 그래서 방화벽 경고가 한 번도 안 떴고, 그게
 * 설계 원칙이었습니다.
 *
 * 그런데 사무보조원이 자기 자리에서 대상자를 등록하고 서식을 뽑아야
 * 하는 일이 생겼습니다. 지금은 관리자 PC 앞에 가서 앉아야 합니다.
 * (2026-09-05 무무 — 「사무보조원은 접근할 권한이 있을 필요가 있겠네…
 *  관리자가 한시적 승인으로 접근할 수 있는 url 을 오픈해주는 방법」)
 *
 * ═══════════════════════════════════════════════════════════
 *  ★ 어떻게 여는가 — 세 겹입니다 ★
 * ═══════════════════════════════════════════════════════════
 *
 *   ① **잠깐만** 엽니다. 몇 시간짜리로 열고 저절로 닫힙니다.
 *      프로그램을 껐다 켜면 **닫힌 채로** 시작합니다.
 *
 *   ② **여섯 자리 번호**를 물어봅니다. 주소만 열면 사무실 와이파이에
 *      붙은 아무 기기(손님 폰까지)가 로그인 화면을 봅니다. 로그인
 *      화면이 보이면 비밀번호를 맞혀 볼 수 있습니다. 번호가 한 겹입니다.
 *
 *   ③ 그다음 **자기 아이디·비밀번호**로 들어갑니다. 그래서 누가 무엇을
 *      했는지 계정으로 남습니다 — 링크 하나로 여는 것과 다른 점입니다.
 *
 * ── 왜 포트를 따로 쓰나 ────────────────────────────────────
 *
 * 5757 은 `127.0.0.1` 이 잡고 있어 같은 포트를 두 번 열 수 없습니다.
 * 그래서 여는 동안만 **다른 포트**에 두 번째 귀를 엽니다. 닫으면 그것만
 * 멈추고, 본래 화면은 아무 일 없이 그대로 돕니다.
 *
 * ── ★ 방화벽 경고는 못 막습니다 ★ ─────────────────────────
 *
 * 처음 열 때 윈도우가 「이 앱의 일부 기능을 차단했습니다」를 띄웁니다.
 * 우리가 막을 수 있는 창이 아닙니다. **미리 알려 주는 것**이 우리가
 * 할 수 있는 전부입니다 — 화면이 그렇게 안내합니다
 * (무무: 한글 경고창은 「고객 입장에서는 굉장히 무서울 일」).
 */
import { networkInterfaces } from "node:os";
import { 랜이름정하기 } from "./문지기";

export type 열린상태 = {
  열림: boolean;
  주소?: string;          // http://192.168.0.12:5758
  번호?: string;          // 여섯 자리
  닫힐때?: string;        // ISO
  몇시간?: number;
};

/** 고를 수 있는 시간. 근무시간 예약과 같은 결로 맞춥니다. */
export const 열시간들 = [
  { 값: 2, 이름: "2시간" },
  { 값: 4, 이름: "4시간" },
  { 값: 6, 이름: "6시간" },
  { 값: 8, 이름: "8시간" },
];

let 서버: any = null;
let 번호: string | null = null;
let 닫힐때: number = 0;
let 몇시간: number = 0;
let 시계: any = null;

/**
 * 이 컴퓨터의 **사무실 안 주소**.
 *
 * 랜선이나 와이파이로 받은 사설 주소를 찾습니다(192.168.x · 10.x ·
 * 172.16~31.x). 바깥 인터넷 주소는 여기서 안 씁니다 — 사무실 안에서만
 * 쓰는 길이기 때문입니다.
 */
export function 사무실주소(): string | null {
  /*
   * ★ `TONGDOL_LAN_IP` — **시험에서만** 씁니다.
   *
   *   시험을 돌리는 자리(컨테이너·가상머신)는 사설 대역이 아닌 주소를
   *   쓸 때가 있습니다. 그렇다고 사설 대역 검사를 무르게 하면 안 됩니다 —
   *   **공인 주소에 문을 열면 인터넷 전체가 들어옵니다.** 그래서 검사는
   *   그대로 두고, 시험만 따로 우회합니다 (`TONGDOL_버전흉내` 와 같은 결).
   *
   *   ★ 이름을 **영문으로** 둡니다. 환경변수 이름에 한글을 넣으면
   *     셸이 「command not found」로 받습니다 — `.bat` 에 한글을 안 쓰는
   *     것과 같은 갈래입니다.
   */
  const 흉내 = process.env.TONGDOL_LAN_IP?.trim();
  if (흉내) return 흉내;

  const 것들 = networkInterfaces();
  const 후보: string[] = [];
  for (const 줄 of Object.values(것들)) {
    for (const x of 줄 ?? []) {
      if (x.family !== "IPv4" || x.internal) continue;
      if (/^192\.168\./.test(x.address) || /^10\./.test(x.address) ||
          /^172\.(1[6-9]|2\d|3[01])\./.test(x.address))
        후보.push(x.address);
    }
  }
  /*
   * 여럿이면 192.168 을 먼저 고릅니다 — 사무실 공유기가 가장 흔히
   * 쓰는 대역이라, 사람이 보고 「우리 사무실 것」이라고 알아봅니다.
   */
  return 후보.find((x) => x.startsWith("192.168.")) ?? 후보[0] ?? null;
}

/** 여섯 자리. 사람이 옆자리에 불러 주는 번호라 숫자만 씁니다. */
function 새번호(): string {
  const b = crypto.getRandomValues(new Uint32Array(1))[0];
  return String(b % 1_000_000).padStart(6, "0");
}

export function 상태(): 열린상태 {
  if (!서버 || Date.now() >= 닫힐때) return { 열림: false };
  const ip = 사무실주소();
  return {
    열림: true,
    주소: ip ? `http://${ip}:${서버.port}` : undefined,
    번호: 번호 ?? undefined,
    닫힐때: new Date(닫힐때).toISOString(),
    몇시간,
  };
}

/**
 * 엽니다. 이미 열려 있으면 **시간만 다시 셉니다** — 번호는 그대로 둡니다.
 * 옆자리에 이미 불러 준 번호가 바뀌면 그 사람이 다시 물어봐야 합니다.
 */
export function 열기(시간: number, 만들기: (포트: number) => any): 열린상태 {
  const h = Number(시간);
  if (!열시간들.some((x) => x.값 === h))
    throw new Error(`고를 수 있는 시간은 ${열시간들.map((x) => x.이름).join(" · ")} 입니다.`);

  if (!사무실주소())
    throw new Error(
      "사무실 네트워크에 붙어 있지 않습니다. 랜선이나 와이파이를 확인해 주세요.");

  if (!서버) {
    /*
     * 5757 다음 포트부터 찾습니다. `0.0.0.0` 은 「이 컴퓨터의 모든 길」이라
     * 사무실 안 다른 컴퓨터가 들어올 수 있게 됩니다.
     */
    let 마지막오류: unknown = null;
    for (const p of [5858, 5859, 5860, 5861]) {
      try { 서버 = 만들기(p); break; }
      catch (e) { 마지막오류 = e; }
    }
    if (!서버) throw 마지막오류 ?? new Error("귀를 열지 못했습니다.");
    번호 = 새번호();
  }

  몇시간 = h;
  닫힐때 = Date.now() + h * 3600_000;

  /*
   * 시간이 되면 스스로 닫습니다. 관리자가 잊고 퇴근해도 밤새 열려
   * 있지 않게 하는 것이 이 기능의 절반입니다.
   */
  clearTimeout(시계);
  시계 = setTimeout(() => {
    console.log("사무실 열기: 정한 시각이 되어 닫았습니다");
    닫기();
  }, h * 3600_000);

  const s = 상태();
  랜이름정하기(s.주소 ?? null);      // 문지기가 이 주소도 받게
  console.log(`사무실 열기: ${s.주소} · 번호 ${번호} · ${h}시간`);
  return s;
}

export function 닫기(): void {
  랜이름정하기(null);        // 닫으면 그 주소도 다시 막습니다
  clearTimeout(시계); 시계 = null;
  if (서버) { try { 서버.stop(true); } catch { } 서버 = null; }
  번호 = null; 닫힐때 = 0; 몇시간 = 0;
}

/**
 * 들어온 요청이 **번호를 냈는가.**
 *
 * 로컬(127.0.0.1)로 들어온 것은 안 묻습니다 — 그건 관리자 PC 본인입니다.
 * 두 번째 귀로 들어온 것만 묻습니다.
 */
export function 번호맞나(쿠키글: string | null): boolean {
  if (!번호) return false;
  const m = String(쿠키글 ?? "").match(/(?:^|;\s*)ck_lan=([0-9]{6})/);
  return !!m && m[1] === 번호;
}

export function 지금번호(): string | null { return 번호; }
