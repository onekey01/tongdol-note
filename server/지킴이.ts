/**
 * 창을 닫으면 프로그램도 꺼집니다.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────
 * 일이 끝나면 사람은 **브라우저 창을 닫습니다.** 검은 창은 눈에 안 들어오고,
 * 닫아도 프로그램은 뒤에서 계속 살아 있습니다. 그러면 다음 날 또 켜서
 * **두 개가 돌고**, 어느 쪽에 자료가 들어갔는지 헷갈립니다.
 *
 * 무엇보다 **검은 창이 남아 있으면 기관이 못 씁니다.** 「이게 뭐지」 하고
 * 손을 못 댑니다. Ctrl+C 를 아는 사람은 만든 사람뿐입니다.
 * (2026-09-05 무무 — 「대다수의 수행기관에선 이게 뭐지 하고 못쓴단 말이야.」)
 *
 * ── 꺼져도 자료를 안 잃는 까닭 ────────────────────────────
 *
 * 한동안 이걸 껐던 적이 있습니다. 「프로그램이 꺼지면 폰과의 왕복이
 * 멈춘다」고 봤기 때문입니다. **그것은 과장이었습니다.**
 *
 * 폰과 이 PC 사이에는 **우편함(Supabase)**이 있습니다. 애초에 서로
 * 못 받는 때를 대비해 둔 자리이고, 보관 기간은 **14일**입니다
 * (`우편함/001_기틀.sql` — job·report·photo 모두 `now() + 14 days`).
 *
 *   · 프로그램이 꺼져 있는 동안 폰이 보낸 보고는 **우편함에서 기다립니다.**
 *     다음에 켜면 6초 뒤에 다 받아 옵니다.
 *   · 일정은 사무실이 저장하는 그 순간 올라갑니다. 프로그램이 꺼져
 *     있으면 애초에 저장할 사람도 없습니다.
 *
 * 곧 꺼지는 것은 **늦어지는 것**이지 잃는 것이 아닙니다.
 * 14일을 넘겨 프로그램을 한 번도 안 켜는 기관이라면 그건 다른 문제입니다.
 *
 * ── 두 개가 도는 것은 켤 때도 막습니다 ────────────────────
 *
 * 이것만으로는 모자랍니다 — 검은 창을 그대로 둔 채 아이콘을 또 누르는
 * 일이 있습니다. 그래서 켤 때도 봅니다(`server/index.ts` 의
 * `이미돌고있나()`). 이미 돌고 있으면 새로 안 켜고 그 화면만 엽니다.
 *
 * ── 어떻게 아는가 ──────────────────────────────────────────
 * 화면이 열려 있는 동안 **가느다란 줄 하나(WebSocket)**를 붙들고 있습니다.
 * 창을 닫으면 그 줄이 끊어집니다. 줄이 **하나도 안 남고**, 한동안
 * 아무도 안 돌아오면 프로그램이 스스로 꺼집니다.
 *
 * ── 「한동안」이 핵심입니다 ────────────────────────────────
 * **새로고침(F5)도 줄이 한 번 끊깁니다.** 곧바로 끄면 새로고침할 때마다
 * 프로그램이 죽습니다. 그래서 끊긴 뒤 잠시 기다렸다가, 그때도 아무도
 * 안 돌아왔을 때만 끕니다. 탭을 두 개 열어 두신 경우는 세기로 풀립니다.
 *
 * ── 일하는 중에는 안 끕니다 ────────────────────────────────
 * 기록지 PDF 는 한글을 불러서 도는 일이라 몇 초 걸립니다. 그 사이 창을
 * 닫았다고 꺼지면 **반쯤 만든 파일**이 남습니다. 그래서 일감이 도는 동안은
 * 시계를 다시 미룹니다.
 */

/*
 * 시간 두 가지는 **환경변수로 줄일 수 있게** 해 두었습니다.
 * 시험에서 그대로 기다리면 한 번 돌리는 데 몇 분씩 걸립니다.
 * 재는 방식은 똑같고 숫자만 바뀝니다 — 그래서 시험이 실제 동작을 봅니다.
 */
const 숫자 = (이름: string, 기본: number) => {
  const v = Number(process.env[이름]);
  return Number.isFinite(v) && v >= 200 ? v : 기본;
};

/**
 * 새로고침을 견디는 시간. 이보다 빨리 돌아오면 안 끕니다.
 *
 * ── 왜 3초인가 ─────────────────────────────────────────────
 * 견뎌야 하는 것은 **새로고침(F5) 하나뿐**입니다. 그런데 화면은 이 컴퓨터
 * 안에서 오는 것이라, 느린 사무실 PC 에서도 새로고침 뒤 줄이 다시 붙는 데
 * **1초가 안 걸립니다.** 3초면 세 배 넘게 잡아 둔 셈입니다.
 *
 * 처음에는 25초로 두었는데, 창을 닫고 검은 창이 사라질 때까지 **30초를
 * 기다려야** 했습니다. 끝내고 일어서는 사람에게 30초는 「안 꺼지네」입니다.
 */
const 유예 = 숫자("TONGDOL_유예", 3_000);

/**
 * 켤 때 브라우저가 **아예 안 열리는 경우**가 있습니다(기본 브라우저가 없거나,
 * 백신이 막거나). 그때 금방 꺼지면 사람은 「눌러도 아무 일이 없다」만
 * 겪습니다. 그래서 첫 연결을 기다리는 동안은 넉넉히 둡니다.
 */
const 첫유예 = 숫자("TONGDOL_첫유예", 3 * 60_000);

let 줄수 = 0;
let 일감 = 0;
let 시계: ReturnType<typeof setTimeout> | null = null;
let 한번은붙었나 = false;
let 켜짐 = false;
let 끌때: (() => void) | null = null;

/** 지킴이를 켭니다. 끄는 일을 어떻게 할지는 부르는 쪽이 정합니다. */
export function 지킴이켜기(끄기: () => void) {
  켜짐 = true;
  끌때 = 끄기;
  미루기(첫유예);
}

function 미루기(얼마: number) {
  if (!켜짐) return;
  if (시계) clearTimeout(시계);
  시계 = setTimeout(() => {
    // 시계가 울렸어도 그새 누가 돌아왔거나 일감이 돌면 다시 미룹니다.
    if (줄수 > 0) return;
    if (일감 > 0) return 미루기(유예);
    끌때?.();
  }, 얼마);
}

function 멈추기() {
  if (시계) { clearTimeout(시계); 시계 = null; }
}

export function 붙음() {
  줄수++;
  한번은붙었나 = true;
  멈추기();
}

export function 떨어짐() {
  줄수 = Math.max(0, 줄수 - 1);
  /*
   * 한 번도 안 붙었다가 떨어지는 일은 없습니다. 다만 **처음 붙기 전**에는
   * 첫유예가 돌고 있어야 하므로, 여기서는 줄이 다 빠졌을 때만 짧게 겁니다.
   */
  if (줄수 === 0) 미루기(한번은붙었나 ? 유예 : 첫유예);
}

/** 오래 걸리는 일 — 도는 동안에는 안 끕니다. */
export function 일감시작() { 일감++; }
export function 일감끝() {
  일감 = Math.max(0, 일감 - 1);
  if (일감 === 0 && 줄수 === 0) 미루기(유예);
}

/** 지금 화면이 몇 개 열려 있나. 검은 창에 찍을 때 씁니다. */
export function 열린창수() { return 줄수; }
