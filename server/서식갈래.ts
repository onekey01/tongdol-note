/**
 * 이 서비스는 **어느 제공기록지**로 나가는가.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────
 *
 * 편람의 제공기록지는 서비스마다 다릅니다. 현장앱이 어르신 댁에서
 * 물어볼 것도 그래서 다릅니다.
 *
 *   서식3  가사지원        목욕보조·청소·세탁… 열한 가지 중 한 것에 표시
 *   서식4  식사 관리       제공형태(대면/비대면) · **식단** (「식단 포함 필수」)
 *   서식5  병원동행·이미용  제공장소 · 서비스내용 여러 줄
 *
 * ── 왜 서비스 **이름**으로 안 가르나 ───────────────────────
 *
 * 서비스 이름은 **기관이 설정에서 고칠 수 있습니다.** 「가사지원」을
 * 「가사돌봄」으로 바꾼 기관에서 앱이 이름을 맞춰 보고 있으면,
 * 그날부터 확인사항 화면이 통째로 안 뜹니다. 그것도 **조용히** 안 뜹니다.
 *
 * 그래서 자료함이 이미 들고 있는 두 가지로 가릅니다.
 *   · `record_type`  time | meal | work   — 셈하는 방식
 *   · 중분류(`cat_m`) 가사지원·식사지원·이동지원·방문이미용
 *
 * ── 모르는 서비스는 ───────────────────────────────────────
 *
 * 「기타」로 보냅니다. 기관이 나중에 저희가 모르는 서비스를 만들 수 있고,
 * 그때 앱이 **아무 화면도 못 띄우는 것**이 제일 나쁩니다.
 * 기타는 「무엇을 했는지 적는 칸 + 특이사항」으로 받습니다.
 */

/** 현장앱이 아는 갈래. 이 다섯 가지 말고는 없습니다. */
export type 갈래 = "가사" | "식사" | "동행" | "이미용" | "기타";

export type 서비스생김새 = {
  record_type?: string | null;
  cat_m?: string | null;
  cat_s?: string | null;
  name?: string | null;
};

export function 서식갈래(sv: 서비스생김새): 갈래 {
  const 중 = (sv.cat_m ?? "").replace(/\s/g, "");
  const 소 = (sv.cat_s ?? "").replace(/\s/g, "");

  /*
   * 식사가 먼저입니다. 「도시락 배달」은 중분류가 식사지원이지만,
   * 기관에 따라 다른 데 넣어 두었을 수 있습니다. 셈하는 방식이
   * meal 이면 그것은 틀림없이 식사입니다.
   */
  if (sv.record_type === "meal" || 중.includes("식사")) return "식사";

  /*
   * 공사형(안전생활환경개선)은 **현장앱이 다룰 일이 아닙니다.**
   * 외부 업체가 들어가고, 서식도 6-1·6-2(사전협의·추진결과 보고서)라
   * 그 자리에서 체크할 것이 아닙니다. 「기타」로 보냅니다.
   */
  if (sv.record_type === "work") return "기타";

  if (중.includes("이미용") || 소.includes("이미용")) return "이미용";
  if (중.includes("이동") || 소.includes("동행")) return "동행";
  if (중.includes("가사")) return "가사";

  return "기타";
}

/** 그 갈래가 어느 서식으로 나가는지. 화면에 적어 줍니다. */
export function 서식이름(g: 갈래): string {
  return g === "가사" ? "서식3"
       : g === "식사" ? "서식4"
       : g === "동행" || g === "이미용" ? "서식5"
       : "";
}
