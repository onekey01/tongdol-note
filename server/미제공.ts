/**
 * ── 못 간 날의 갈래 ───────────────────────────────────────────
 *
 * 지금까지 「미제공」은 갈래가 하나뿐이었습니다. 부재도 미제공, 입원도
 * 미제공, 기관 차가 고장 난 것도 미제공. 그런데 **계약서(서식2) 4조**가
 * 그 안에 선을 그어 놓았습니다 —
 *
 *   「이용자가 **사전 취소 없이** … 서비스를 이용하지 않으셨더라도
 *    비용이 지출되며, 1인당 연간 지원한도액에서 차감됩니다.」
 *
 * 어르신이 미리 「내일은 병원에 갑니다」라고 알리셨으면 돈이 안 나갑니다.
 * 아무 말 없이 문이 잠겨 있어서 제공인력이 헛걸음을 했으면 **돈이 나갑니다.**
 * 같은 「미제공」인데 **돈과 한도가 정반대**입니다.
 *
 * ── 네 갈래 ──────────────────────────────────────────────────
 *
 *   노쇼       사전 취소 없이 못 감      → 돈이 나가고 한도에서 깎입니다
 *   사전취소   예정일 하루 전까지 알림   → 돈도 한도도 안 갑니다
 *   기관사정   기관·제공인력 쪽 사정     → 안 갑니다 (이용자 잘못이 아닙니다)
 *   기타       기상·재해 등              → 안 갑니다 (아무도 잘못이 없습니다)
 *
 * ── 옛 자료는 「기타」입니다 ──────────────────────────────────
 *
 * 이 칸이 오늘 처음 생겼으니 지난 미제공에는 갈래가 없습니다.
 * 그것을 **지어내지 않습니다.** 비어 있으면 「기타」로 보아
 * 지금까지와 똑같이 셉니다 — 그래야 **지난 청구서가 안 흔들립니다.**
 *
 * ── 막지 않습니다 ────────────────────────────────────────────
 *
 * 사전취소라고 골라 놓고 알린 날이 당일이면 **알려만 줍니다.**
 * 계약서가 그은 선은 저희가 아니라 군과 어르신 사이의 것입니다.
 */

export const 갈래들 = ["노쇼", "사전취소", "기관사정", "기타"] as const;
export type 갈래 = (typeof 갈래들)[number];

export const 갈래설명: Record<갈래, string> = {
  노쇼: "사전 취소 없이 이용하지 않으심 — 비용이 나가고 한도에서 깎입니다",
  사전취소: "예정일 하루 전까지 알려 오심 — 비용도 한도도 안 갑니다",
  기관사정: "기관·제공인력 쪽 사정 — 비용도 한도도 안 갑니다",
  기타: "기상·재해 등 — 비용도 한도도 안 갑니다",
};

/**
 * 자료함에 든 값을 갈래로 읽습니다.
 *
 * **비어 있거나 모르는 값이면 「기타」**입니다. 옛 실적에는 이 칸이
 * 없으므로, 없는 것을 노쇼로 읽으면 지난 청구서에 없던 돈이 생깁니다.
 */
export function 갈래읽기(v: unknown): 갈래 {
  const s = String(v ?? "").trim();
  return (갈래들 as readonly string[]).includes(s) ? (s as 갈래) : "기타";
}

/**
 * **이 갈래는 돈이 드나.**
 *
 * 온 프로그램에서 이 물음에 답하는 곳은 여기 한 곳입니다.
 * 청구서·연간한도·월한도·생애한도가 모두 이것을 봅니다 —
 * 갈라 놓으면 언젠가 두 화면이 다른 금액을 말합니다.
 */
export function 돈이드나(k: 갈래): boolean {
  return k === "노쇼";
}

/**
 * SQL 안에서도 같은 물음을 합니다.
 *
 * 실적 표를 `d` 로 부르는 질의에 그대로 끼웁니다.
 * TypeScript 쪽 `돈이드나` 와 **같은 뜻이어야** 합니다 — 한쪽만 고치면
 * 화면과 청구서가 어긋납니다.
 */
export const 돈드는실적SQL =
  "(d.outcome = '제공' OR (d.outcome = '미제공' AND d.miss_kind = '노쇼'))";

/** 예정일 하루 전 날짜. 계약서 4조가 그은 선입니다. */
export function 사전취소선(servedOn: string): string {
  const [y, m, d] = servedOn.split("-").map(Number);
  const t = new Date(Date.UTC(y, m - 1, d - 1));
  const p = (n: number) => String(n).padStart(2, "0");
  return `${t.getUTCFullYear()}-${p(t.getUTCMonth() + 1)}-${p(t.getUTCDate())}`;
}

/**
 * 사전취소라기에는 **늦게 알린 것인가.**
 *
 * 안 알렸으면 늦은 것입니다. 당일에 알렸어도 늦은 것입니다 —
 * 계약서가 「하루 전」이라고 적어 두었습니다.
 */
export function 늦게알렸나(servedOn: string, notifiedOn?: string | null): boolean {
  const n = String(notifiedOn ?? "").trim();
  if (!n) return true;
  return n > 사전취소선(servedOn);
}

/**
 * 사유를 고르면 갈래를 **미리 골라 둡니다.** 고칠 수 있습니다.
 *
 * 자동으로 정하지 않는 이유 — 입원이라고 늘 미리 알리는 것이 아니고,
 * 부재라고 늘 안 알린 것이 아닙니다. **미리 알렸나**가 갈래를 정하는데
 * 그건 사람만 압니다. 프로그램은 손이 덜 가게 거들 뿐입니다.
 *
 * ── `노쇼쓰나` (2026-09-01 바로잡음) ─────────────────────────
 *
 * **해남 현장은 노쇼를 안 씁니다.** 가사·동행·이미용은 이용자 사정이면
 * **일정을 사전 조율**해 다시 잡고, 식사는 「대면/비대면」(`대면배달.ts`)이
 * 그 자리를 대신합니다 — 비대면 배달은 미제공이 아니라 **제공**입니다.
 *
 * 그래도 기능을 없애지는 않았습니다. 계약서 4조가 **어르신께 인쇄되어
 * 나가는 종이**(서식2)에 그대로 적혀 있어서, 그 종이를 뽑으면서 적을 데가
 * 없으면 **프로그램이 제가 뽑은 종이와 어긋납니다.** 다른 지자체는 쓸 수도
 * 있습니다. 그래서 **서비스마다 켜고 끄고, 기본은 꺼짐**입니다.
 */
export function 기본갈래(reason?: string | null, 노쇼쓰나 = false): 갈래 {
  const r = String(reason ?? "").trim();
  if (r === "기관사정") return "기관사정";
  if (r === "기상·재해") return "기타";
  if (r === "입원" || r === "본인요청") return "사전취소";
  if (r === "부재" || r === "거부") return 노쇼쓰나 ? "노쇼" : "기타";
  return "기타";
}
