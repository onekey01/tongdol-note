/**
 * 돈 계산.
 *
 * 반올림은 기관·지자체마다 다릅니다.
 * - 복지부 지침 표준 : 10원 단위 반올림
 * - 해남군           : 100원 단위 절삭(내림)  ← 2026.8 확인
 * 그래서 규칙을 코드에 박지 않고 설정에서 꺼내 씁니다.
 */

export type Rounding = { unit: number; mode: "round" | "ceil" | "floor" };

export function applyRounding(amount: number, r: Rounding): number {
  const unit = r.unit > 0 ? r.unit : 1;
  const q = amount / unit;
  const n = r.mode === "ceil" ? Math.ceil(q) : r.mode === "floor" ? Math.floor(q) : Math.round(q);
  return n * unit;
}

export const won = (n: number) => n.toLocaleString("ko-KR");

/** 서비스 줄 하나. 건수 × 단가 = 비용, 비용 × 부담률 = 본인부담금. */
export type Line = {
  name: string;
  from: string;
  to?: string;
  count: number;
  unitPrice: number;
};

export function calcLines(lines: Line[], copayRate: number, r: Rounding) {
  const rows = lines.map((l) => {
    const amount = l.count * l.unitPrice;
    return { ...l, amount, copay: applyRounding(amount * copayRate, r) };
  });
  const total = rows.reduce((s, x) => s + x.amount, 0);
  return {
    rows,
    total,
    count: rows.reduce((s, x) => s + x.count, 0),
    // 총액에 한 번 적용합니다. 줄마다 잘라 더하면 합계가 어긋납니다.
    copayTotal: applyRounding(total * copayRate, r),
  };
}

