/**
 * 실제 제공한 분 → **인정되는 분.**
 *
 *   15분 미만        미산정 (0)
 *   15분 ~ 45분 미만  30분
 *   45분 이상        1시간
 *
 * ── 1시간을 넘으면 ────────────────────────────────────────────
 * 편람은 세 줄만 적어 두고 그 뒤를 말하지 않습니다. 그래서 이 규칙을
 * **30분마다 되풀이되는 것**으로 읽습니다 — 1시간 15분은 1시간 30분,
 * 1시간 45분은 2시간.
 *
 * **이 해석이 맞습니다** (2026-09-03 무무 님 확인) — 「30분 단위로 계산.
 * 30분 / 1시간 / 1시간30분 / 2시간 / 2시간30분 / 3시간」.
 * 3시간에서 멈추는 것은 편람의 다른 줄 때문입니다 —
 * 「○ (제 공 기 준) **1일 최대 3시간**(평일 오전 9시 ~오후 6시)」.
 * 그 상한은 여기가 아니라 `billing.실적줄들` 이 겁니다 —
 * **환산과 상한을 한 함수에 섞으면** 나중에 어느 쪽이 걸렸는지 못 봅니다.
 *
 * ── 왜 함수가 하나뿐인가 ──────────────────────────────────────
 * 실적·정산·청구서·영수증·기록지·서식8 이 **전부 이 함수 하나만** 봅니다.
 * 두 군데서 따로 셈하면 반드시 어긋나고, 어긋난 쪽이 어르신께 갑니다.
 *
 * ── 시간제에만 씁니다 ────────────────────────────────────────
 * 가사·동행은 시간이라 여기를 지나갑니다.
 * **식사는 끼, 이미용은 회**라 분을 재지 않습니다 — 그쪽은 부르지 마십시오.
 */
/**
 * 시간을 어떻게 셈하나 — **서비스마다 다를 수 있습니다** (v28).
 *
 *   단위    30 또는 60 (분)
 *   반올림  true 면 절반부터 올림, false 면 미달은 버림
 *
 * (2026-09-06 무무 — 「30분 규칙에서 계산 구간 선택하되 30분 1시간
 *  이렇게만 구성하면 되고 반올림 구간(15분)은 선택할 수 있도록」)
 *
 * ★ 안 주면 **지금까지 돌던 값**입니다 (30분 · 올림 = 해남 편람).
 *   그래야 이 규칙을 안 건드린 자리는 어제와 똑같이 셈합니다.
 */
export type 셈규칙 = { 단위?: number; 반올림?: boolean };

/** 자료함의 서비스 줄에서 규칙을 꺼냅니다. 없으면 편람 값. */
export function 셈규칙읽기(sv: any): 셈규칙 {
  const u = Number(sv?.round_unit);
  return {
    단위: u === 60 ? 60 : 30,
    반올림: sv?.round_half === undefined || sv?.round_half === null
      ? true : Number(sv.round_half) === 1,
  };
}

export function 인정분(분: number, 규칙: 셈규칙 = {}): number {
  const m = Math.floor(Number(분));
  if (!Number.isFinite(m) || m <= 0) return 0;

  const 단위 = 규칙.단위 === 60 ? 60 : 30;
  const 반올림 = 규칙.반올림 !== false;

  /*
   * ── 올림 ──────────────────────────────────────────────
   * 단위의 **절반**이 한 칸의 문턱입니다.
   *   30분 단위 → 15분부터 한 칸 (해남 편람 그대로)
   *     14분 → (29/30)=0 칸 → 0
   *     15분 → (30/30)=1 칸 → 30
   *     44분 → (59/30)=1 칸 → 30
   *     45분 → (60/30)=2 칸 → 60
   *   1시간 단위 → 30분부터 한 칸
   *     29분 → 0 · 30분 → 60 · 89분 → 60 · 90분 → 120
   *
   * ── 버림 ──────────────────────────────────────────────
   * 단위를 못 채우면 안 셉니다.
   *   30분 단위 → 29분 → 0 · 30분 → 30 · 59분 → 30
   *   1시간 단위 → 59분 → 0 · 60분 → 60
   */
  return 반올림
    ? Math.floor((m + 단위 / 2) / 단위) * 단위
    : Math.floor(m / 단위) * 단위;
}

/** 인정 분을 **시간**으로. 단가를 곱하는 자리에서 씁니다. */
export function 인정시간(분: number, 규칙: 셈규칙 = {}): number {
  return 인정분(분, 규칙) / 60;
}

