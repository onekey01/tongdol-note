import { today, parseSlots, 주소한줄 } from "./util";
import { 우편함, type 할일 } from "./우편함";
import { 서식갈래 } from "./서식갈래";
import { 지금목록 } from "./확인사항";
import { 그날가나 } from "./가는날";
import { 그날계획분 } from "./계획시간";

/**
 * 할 일 번호를 **늘 같게** 만듭니다.
 *
 * 배정과 날짜가 같으면 언제 다시 만들어도 같은 번호가 나옵니다.
 * 그래서 10분마다 올려도 줄이 늘지 않고 덮어써집니다.
 * 무작위로 만들면 하루에 백 줄씩 쌓입니다.
 */
function 할일번호(assignmentId: number, 날: string): string {
  const h = new Bun.CryptoHasher("sha256")
    .update(`통돌:할일:${assignmentId}:${날}`)
    .digest("hex");
  return [h.slice(0, 8), h.slice(8, 12), "5" + h.slice(13, 16),
          ((parseInt(h.slice(16, 17), 16) & 0x3) | 0x8).toString(16) + h.slice(17, 20),
          h.slice(20, 32)].join("-");
}

/**
 * 시간에 따라 값이 달라지는 서비스인가 — 가사지원 · 이동지원.
 *
 * **서비스 이름으로 가르지 않습니다.** 기관마다 이름을 바꿔 부르기
 * 때문입니다(까닭은 server/서식갈래.ts 에 길게 적어 두었습니다).
 * 편람이 정한 `record_type` 이 「time」인 것이 시간제입니다.
 */
function 시간제인가(sv: { record_type?: string | null }): boolean {
  return sv.record_type === "time";
}

export type 보낸결과 = {
  날: string; 올린수: number; 건너뛴수: number; 치운수?: number; 까닭?: string;
};

/**
 * 그날 갈 곳을 모읍니다. 아직 잠그기 전의 날것입니다.
 *
 * `배정번호`와 `사람`은 **이 PC 안에서만** 씁니다 — 우편함에 올릴 때
 * 떼어 냅니다. 배정번호는 보고가 돌아왔을 때 **어느 배정의 실적인지**
 * 찾는 데 씁니다(할일번호는 한쪽으로만 가는 셈이라 되돌릴 수 없습니다).
 */
export function 그날갈곳(날 = today()): (할일 & { 사람: string; 배정번호: number })[] {
  const 요일 = new Date(날 + "T00:00:00").getDay();

  const 줄들 = db.query<any, [string, string, string]>(
    `SELECT a.id AS aid, a.weekly_plan, a.period_from, a.period_to, a.monthly_times,
            a.service_id,
            r.id AS rid, r.payload AS rpayload, r.status AS rstatus,
            r.visit_code AS 집표,
            sv.name AS service,
            sv.record_type, sv.cat_m, sv.cat_s,
            u.mailbox_worker_id AS 폰번호,
            (SELECT fr.token FROM field_reset fr
              WHERE fr.assignment_id = a.id AND fr.served_on = ?) AS 되돌림표
       FROM assignment a
       JOIN recipient r  ON r.id  = a.recipient_id
       JOIN service   sv ON sv.id = a.service_id
       JOIN worker    w  ON w.id  = a.worker_id
       JOIN app_user  u  ON u.id  = w.user_id
      WHERE (a.period_from IS NULL OR a.period_from <= ?)
        AND (a.period_to   IS NULL OR a.period_to   >= ?)
        AND u.status = 'active'
      ORDER BY a.id`
  ).all(날, 날, 날);

  /*
   * ── 확인사항 항목을 **짐에 실어 보냅니다** ──────────────────
   *
   * (2026-09-06 무무 — 설정에서 항목을 고칠 수 있게 하기로 한 것)
   *
   * 앱에 목록을 박아 두면, 기관이 항목 하나를 더할 때마다 **앱을 다시
   * 올리고 제공인력 폰마다 새로 받아야** 합니다. 그건 못 할 일입니다.
   * 그래서 목록을 그날 갈 곳 짐에 함께 실어 보냅니다 — 사무실에서
   * 저장하면 다음 올림(10분 안)에 폰에 그대로 반영됩니다.
   *
   * `버전` 도 같이 보냅니다. 보고가 돌아올 때 이 번호가 함께 오고,
   * 그 번호가 실적에 남아 **그때 목록으로 서식을 뽑습니다.**
   */
  const 확인 = 지금목록();

  const 나온것: (할일 & { 사람: string; 배정번호: number })[] = [];
  for (const r of 줄들) {
    // 기기 등록을 안 한 사람에게는 보낼 곳이 없습니다.
    if (!r.폰번호) continue;
    /*
     * **「이용」 중인 분만.**
     * 상태는 이용 · 중단 · 종결 · 취소 · 직권중단 다섯 가지입니다(api.ts STATUSES).
     * 「중단」은 잠시 멈춘 것이라 그날 갈 곳에서도 빠져야 합니다 —
     * 멈춘 집에 제공인력이 찾아가면 안 됩니다.
     */
    if (r.rstatus !== "이용") continue;
    /*
     * ★ 그 날에 가는 배정만 — **`가는날.ts` 가 답합니다** (v34).
     *
     *   여기가 **제일 중요한 자리**입니다. 사무실 달력과 이 줄이 다른 날을
     *   말하면, 제공인력 폰에 안 뜨는 날에 어르신이 기다리시거나 그 반대가
     *   됩니다. 그래서 요일을 여기서 따로 세지 않고 한 곳에 묻습니다.
     */
    const 요일들 = parseSlots(r.weekly_plan).map((s) => s.dow);
    if (요일들.length && !그날가나(r, 날)) continue;

    const p = JSON.parse(r.rpayload || "{}");
    나온것.push({
      id: 할일번호(r.aid, 날),
      worker_id: String(r.폰번호),
      served_on: 날,
      사람: p.name ?? "",
      배정번호: r.aid,
      짐: {
        이름: p.name ?? "",
        주소: 주소한줄(p),
        연락처: p.phone ?? p.phoneHome ?? "",
        서비스: r.service ?? "",
        메모: p.visitNote ?? p.note ?? "",
        /*
         * 문에 붙은 종이의 값입니다. 이것이 있어야 현장앱이
         * 「지금 읽은 QR 이 이 집 것인가」를 대조할 수 있습니다.
         * 아직 인쇄를 안 한 집은 비어 있습니다 — 그런 집은 그냥
         * 예전처럼 손으로 적습니다. 인쇄가 밀렸다고 일이 멈추면 안 됩니다.
         */
        집표: r.집표 ?? "",
        /*
         * 어느 제공기록지로 나갈 것인가 — 현장앱의 **확인사항 화면이
         * 이것으로 갈립니다.** 서비스 이름을 앱에서 맞춰 보지 않는
         * 까닭은 server/서식갈래.ts 에 적어 두었습니다.
         */
        갈래: 서식갈래(r),
        /*
         * ── 그날 몇 분 하기로 했나 ──────────────────────────
         *
         * **시간에 따라 값이 달라지는 서비스**(가사지원 · 이동지원)에만
         * 뜻이 있습니다. 현장앱은 이보다 짧게 끝내려 할 때
         * 「계획된 서비스 제공시간을 충족하지 못하였습니다」라고
         * 한 번 물어봅니다 (2026-09-05 무무 지시).
         *
         * **막지는 않습니다.** 어르신이 「오늘은 그만하자」고 하시는 날이
         * 실제로 있고, 그때 앱이 못 끝내게 하면 현장은 앱을 버립니다.
         * 다만 모르고 지나가면 안 되는 일이라 한 번 묻습니다.
         *
         * ── 무엇을 그날의 계획 시간으로 보나 ────────────────
         *
         *   ① 배정의 **주간계획에 그 요일 분**이 적혀 있으면 그 값
         *   ② 없으면 **설정 · 계산규칙의 「하루 최대 서비스 시간」**
         *      (지금 해남은 180분)
         *
         * 설정 화면이 이미 「사람마다 다르면 주간 계획에 적으세요,
         * 그 값이 이것보다 앞섭니다」라고 적어 두었습니다. 그 순서 그대로입니다.
         * 둘 다 없으면(설정이 0이면) null — 그때만 안 묻습니다.
         */
        계획분: 시간제인가(r) ? 그날계획분(r.weekly_plan, 요일) : null,
        /*
         * ── 사무실이 되돌렸다는 표 ──────────────────────────
         *
         * 사무실이 제공실적에서 「제공」을 「계획」으로 되돌리면 여기에
         * 새 표가 생깁니다. 폰은 자기가 들고 있는 표와 다르면 그 건의
         * 기록(시작·끝·서명·사진·적은 것)을 **처음으로 되돌립니다.**
         *
         * 되돌린 적이 없으면 빈 글자입니다.
         * (2026-09-05 무무 지시)
         */
        되돌림표: r.되돌림표 ?? "",
        /*
         * 가사 화면의 「오늘 해 드린 것」 목록. 갈래가 가사일 때만
         * 뜻이 있지만 **갈래를 안 가리고 보냅니다** — 앱이 갈래를
         * 판단하는 자리와 여기가 갈라지면 목록이 안 오는 건이 생기고,
         * 그때 현장은 아무것도 못 누릅니다. 몇 줄 더 가는 편이 낫습니다.
         */
        확인사항: 확인.항목,
        확인버전: 확인.버전,
      },
    });
  }
  return 나온것;
}

/**
 * 모아서 잠가서 올립니다. 우편함을 안 쓰는 기관이면 조용히 넘어갑니다.
 *
 * ★ 올리기만 하지 않고 **맞춥니다.**
 *
 *   올리는 것만 하면 한 번 올라간 것이 스스로 안 없어집니다.
 *   대상자를 「중단」으로 바꿔도, 배정을 지워도, 요일을 고쳐도
 *   제공인력 폰에는 그대로 떠 있습니다 — 멈춘 집에 찾아가게 됩니다.
 *   (2026-09-05 에 찾았습니다. 자세한 것은 우편함.할일맞추기 에.)
 *
 *   그래서 **갈 곳이 없을 때도 돕니다.** 오히려 그때가 전부 치워야
 *   하는 때입니다. 예전에는 여기서 그냥 돌아갔습니다.
 */
/**
 * ── 며칠치를 올리나 ────────────────────────────────────────
 *
 * **오늘부터 이번 달 말까지**, 다만 **적어도 14일**은 채웁니다.
 *
 * 제공인력이 「이번 주엔 어디를 가나」·「이번 달에 몇 번 가나」를 폰에서
 * 봐야 하기 때문입니다. 지금까지는 오늘치만 올라가서, 내일 일정을
 * 알려면 사무실에 전화해야 했습니다.
 * (2026-09-05 무무 — 「본인에게 할당 된 당일일정과 주간일정, 월간일정」)
 *
 * ★ 말일이 가까우면 14일로 늘리는 까닭 —
 *   9월 28일에 「이번 달」을 보면 사흘치뿐입니다. 그런데 다음 주 일정은
 *   그때가 제일 알고 싶습니다. 달이 바뀐다고 앞이 안 보이면 안 됩니다.
 *
 * ★ **지난 날은 안 올립니다.** 이미 다녀온 집의 주소를 폰이 계속
 *   들고 있을 까닭이 없습니다. 폰을 잃어버렸을 때 든 것이 적을수록 좋습니다.
 */
export const 며칠치 = 14;

export function 보낼범위(날 = today()): { 첫날: string; 끝날: string } {
  const d = new Date(`${날}T00:00:00`);
  const 말일 = new Date(d.getFullYear(), d.getMonth() + 1, 0);
  const 열나흘 = new Date(d.getTime() + (며칠치 - 1) * 86400_000);
  const 끝 = 말일 > 열나흘 ? 말일 : 열나흘;
  const 글 = (x: Date) =>
    `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, "0")}-` +
    `${String(x.getDate()).padStart(2, "0")}`;
  return { 첫날: 날, 끝날: 글(끝) };
}

export async function 오늘갈곳보내기(날 = today()): Promise<보낸결과> {
  const 설정 = 우편함.설정읽기();
  if (!설정) return { 날, 올린수: 0, 건너뛴수: 0, 까닭: "우편함이 설정되지 않았습니다" };

  const 함 = new 우편함(설정);
  const { 첫날, 끝날 } = 보낼범위(날);

  // 하루씩 모읍니다 — 그날갈곳 이 요일·상태·기간을 다 봅니다.
  const 갈곳: ReturnType<typeof 그날갈곳> = [];
  for (let d = new Date(`${첫날}T00:00:00`);
       d <= new Date(`${끝날}T00:00:00`);
       d = new Date(d.getTime() + 86400_000)) {
    const 하루 =
      `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-` +
      `${String(d.getDate()).padStart(2, "0")}`;
    갈곳.push(...그날갈곳(하루));
  }

  // ① 먼저 없어져야 할 것을 치웁니다 (그 범위 전체를 목록과 맞춥니다)
  const 치운수 = await 함.범위맞추기(첫날, 끝날, 갈곳.map((j) => j.id));

  // ② 그다음 올립니다 (같은 줄은 덮어쓰기)
  const 올린수 = 갈곳.length
    ? await 함.할일올리기(갈곳.map(({ 사람, 배정번호, ...j }) => { void 사람; void 배정번호; return j; }))
    : 0;

  return {
    날, 올린수, 치운수, 건너뛴수: 0,
    까닭: 갈곳.length ? undefined : "그날 갈 곳이 없습니다",
  };
}

/**
 * 켤 때 한 번, 그 뒤 10분마다.
 *
 * 왜 10분인가 — 관리자가 배정을 고치면 현장에도 곧 보여야 하는데,
 * 사람이 「보내기」를 누르는 것에 기대면 언젠가 안 누릅니다.
 * 그렇다고 1분마다 두드리면 무료 등급의 내보내는 양을 갉아먹습니다.
 */
export function 보내기시작(): void {
  if (!우편함.설정읽기()) return;      // 우편함을 안 쓰는 기관이면 아무 일도 안 합니다

  const 한번 = async () => {
    try {
      const r = await 오늘갈곳보내기();
      if (r.올린수) console.log(`우편함: 오늘 갈 곳 ${r.올린수}곳을 올렸습니다`);
      if (r.치운수) console.log(`우편함: 더는 안 가는 ${r.치운수}곳을 치웠습니다`);
    } catch (e) {
      // 신호가 잠깐 없을 수도 있습니다. 다음 차례에 다시 합니다.
      console.error("우편함: 오늘 갈 곳 올리기 실패 —", (e as Error).message);
    }
  };

  setTimeout(한번, 3000);                       // 켜고 3초 뒤 (다른 준비가 끝나고)
  setInterval(한번, 10 * 60 * 1000);            // 그 뒤 10분마다
}
