/**
 * 오늘 갈 곳을 우편함에 올립니다.
 *
 * 이것이 없으면 현장앱은 늘 「오늘은 갈 곳이 없습니다」입니다.
 * (실제로 그랬습니다 — 올리는 자리를 안 만들어 두었습니다.)
 *
 * 무엇을 올리나 —
 *   그날 갈 예정인 배정 하나가 **할 일 한 줄**이 됩니다.
 *   사람에 관한 것(성명·주소·연락처·서비스명)은 전부 `payload_enc` 한 칸에
 *   **잠겨서** 나갑니다. 우편함은 그 덩어리를 보관만 하고 열지 못합니다.
 *
 * 언제 올리나 —
 *   · 프로그램을 켤 때 한 번
 *   · 그 뒤 10분마다
 *   · 관리자가 「지금 보내기」를 눌렀을 때
 *
 *   10분마다 다시 올려도 괜찮습니다. 할 일 번호가 **늘 같게** 나오도록
 *   만들어서, 같은 줄은 덮어쓰기만 합니다 (아래 `할일번호`).
 */
