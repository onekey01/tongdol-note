/**
 * **그날 몇 분 하기로 했나** — 이 물음의 답은 여기 한 곳에만 있습니다.
 *
 * ═══════════════════════════════════════════════════════════
 *  규칙 (아주 오래전에 확정된 것입니다. 임의로 바꾸지 마세요.)
 *
 *    ① 배정의 **주간계획에 그 요일 분**이 적혀 있으면  → 그 값
 *    ② 없으면 **설정 · 계산규칙의 「하루 최대 서비스 시간」**
 *    ③ 그것도 0 이면                                  → 없음(null)
 *
 *  설정 화면(web/src/pages/Settings.tsx)이 사람에게 하는 말과 같습니다 —
 *    「사람마다 다르면 배정 화면의 주간 계획에 요일별 시간을 적어 주세요.
 *      그 값이 이것보다 앞섭니다. 0 을 넣으면 안 봅니다.」
 * ═══════════════════════════════════════════════════════════
 *
 * ── 왜 파일을 따로 뺐나 ────────────────────────────────────
 *
 * 이 규칙이 **두 군데에 따로 적혀 있었습니다** — 청구(billing.ts)와
 * 현장앱으로 내보내는 자리(할일보내기.ts). 청구는 규칙대로 하고 있었는데,
 * 현장앱 쪽을 새로 만들면서 제가 설정값을 안 보고 「요일에 안 적었으면
 * 견줄 값이 없다」로 두었습니다. 그래서 **계획 시간 미달 경고가 아예
 * 안 떴습니다.** 설정에 180분이 버젓이 들어 있는데도요.
 * (2026-09-05 무무가 짚었습니다 — 「왜 이 내용을 빼먹는거야.」)
 *
 * 같은 규칙이 두 곳에 있으면 반드시 한 쪽만 고쳐집니다.
 * 그래서 **한 곳으로 모읍니다.** 다음에 이 규칙이 궁금하면 여기를
 * 보시면 되고, 고칠 일이 있으면 여기만 고치면 됩니다.
 */
import { db } from "./db";
import { parseSlots } from "./util";

/**
 * 설정 · 계산규칙의 **하루 최대 서비스 시간**(분).
 * 안 정했거나 0 이면 null — 「안 봅니다」라는 뜻입니다.
 */
export function 하루최대분(): number | null {
  const org = db.query<{ profile_id: number | null }, []>(
    "SELECT profile_id FROM organization WHERE id = 1").get();
  if (!org?.profile_id) return null;
  const p = db.query<{ daily_cap_minutes: number | null }, [number]>(
    "SELECT daily_cap_minutes FROM region_profile WHERE id = ?").get(org.profile_id);
  const 분 = Number(p?.daily_cap_minutes ?? 0);
  return Number.isFinite(분) && 분 > 0 ? 분 : null;
}

/**
 * **계획을 잴 때** 「1회 서비스 시간」을 안 적었으면 한 번에 몇 분으로 보나.
 *
 * ── 왜 하루 최대를 안 쓰나 (2026-09-09 무무 「안 적었을 때 1시간으로 정하자」) ──
 *
 * 예전에는 안 적으면 **설정의 하루 최대(편람 3시간)**로 셌습니다.
 * 그런데 하루 최대는 **넘지 말라는 천장**이지 「보통 이만큼 한다」가
 * 아닙니다. 그 둘을 같은 값으로 쓰니 이런 일이 났습니다 —
 *
 *   가사지원 · 의뢰 그대로 주 2회 → 한 달 9번 × 3시간 = 27시간
 *   가사지원 월 한도 12시간  →  **225%. 저장이 막힙니다.**
 *
 * 관리자는 군이 보낸 의뢰를 그대로 옮겨 적었을 뿐인데 첫 배정에서
 * 막혔습니다 (2026-09-08 파일럿 예행에서 걸렸습니다).
 *
 * ★ 이 값은 **계획을 미리 재는 자리에서만** 씁니다.
 *   청구(billing)와 현장앱 「계획 시간 미달」은 그대로 `그날계획분()` —
 *   즉 적었으면 그 값, 안 적었으면 하루 최대 — 을 봅니다. 그쪽은
 *   「얼마까지 인정하나」를 묻는 자리라 천장이 맞습니다.
 */
export const 기본계획분 = 60;

/**
 * 그 서비스의 **1회 서비스 시간(분)** — 설정 · 계산 규칙에서 정합니다 (v36).
 *
 * 안 정했으면(0) `기본계획분`(60분)을 씁니다.
 *
 * ── 하루 최대와 무엇이 다른가 ──────────────────────────────
 *
 *   하루 최대   **천장.** 실적이 이보다 길어도 청구는 여기까지.
 *   1회 시간    **보통 이만큼 한다.** 계획을 잴 때 쓰는 값.
 *
 * 이 둘을 같은 값으로 쓰다가 2026-09-09 에 주 2회 배정이 통째로
 * 막혔습니다. 다른 값이라 칸도 따로입니다.
 */
export function 서비스1회분(serviceId: number): number {
  try {
    const r = db.query<{ m: number }, [number]>(
      "SELECT once_minutes AS m FROM service WHERE id = ?").get(serviceId);
    const 분 = Number(r?.m ?? 0);
    return Number.isFinite(분) && 분 > 0 ? 분 : 기본계획분;
  } catch { return 기본계획분; }   // 옛 자료함이면 그 칸이 없습니다
}

/** 그 요일에 몇 분 하기로 적어 두었나. 안 적었으면 null. */
export function 그요일분(weekly_plan: unknown, 요일: number): number | null {
  const 칸 = parseSlots(weekly_plan).find((s) => s.dow === 요일);
  return 칸?.minutes ?? null;
}

/**
 * **그날의 계획 시간(분).** 위의 ①②③ 그대로입니다.
 *
 * 쓰는 곳 —
 *   · 할일보내기 — 폰에 실어 보내 「계획 시간 미달」 경고의 기준이 됩니다
 *   · billing    — 하루에 인정할 수 있는 분의 상한
 *
 * 둘이 **같은 값을 봐야** 합니다. 경고는 안 뜨는데 청구는 깎이거나,
 * 그 반대가 되면 현장도 사무실도 못 믿습니다.
 */
export function 그날계획분(weekly_plan: unknown, 요일: number): number | null {
  return 그요일분(weekly_plan, 요일) ?? 하루최대분();
}
