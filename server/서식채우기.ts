/**
 * ── 이름표 뒤에 **값만** 얹기 ─────────────────────────────────
 *
 * 지금까지 서식을 채우는 방법은 **칸을 통째로 갈아 끼우는 것**이었습니다.
 * 기록지(서식9)는 표가 잘게 나뉘어 있어 그것으로 됐습니다.
 *
 * 서식7(영수증)은 다릅니다. 한 칸에 문단이 열두 개 들어 있고
 * **이름표와 값이 같은 줄**에 있습니다 —
 *
 *     거래번호 :
 *     이용자명 :                (서명)
 *     금    액 : 서비스 가격                       원
 *
 * 칸을 갈아 끼우면 **「거래번호 :」라는 이름표까지 지웁니다.**
 * 그건 서식을 고치는 일이고, 제출 서식에는 하면 안 되는 일입니다.
 *
 * ── 그래서 이렇게 합니다 ─────────────────────────────────────
 *
 * **빈칸(공백)에 값을 얹고 글자 수를 그대로 둡니다.**
 * 그러면 뒤따르는 「원」·「(서명)」이 제자리에 그대로 남습니다.
 * 기록지에서 「○ 를 ☑ 로만 바꾼」 것과 같은 생각입니다 —
 * **서식이 적어 둔 글자는 건드리지 않습니다.**
 *
 * ── 못 찾으면 `null` 을 돌려줍니다 ───────────────────────────
 *
 * 이름표를 못 찾았는데 조용히 넘어가면 **빈 영수증이 어르신께 갑니다.**
 * 서식이 개정되어 글자가 바뀌면 **그 자리에서 알아야** 합니다.
 * 부르는 쪽이 `null` 을 보고 터뜨립니다.
 *
 * ── B-2·B-3 에서도 씁니다 ────────────────────────────────────
 * 계약서(서식2)와 비용총괄(서식8)도 같은 모양이라 이 연장을 그대로 씁니다.
 */

/** 돈을 세 자리마다 끊어서. 서식에 적히는 모양입니다. */
export function 금액말(n: number): string {
  return Math.round(Number(n) || 0).toLocaleString("ko-KR");
}

/**
 * 이름표 **바로 뒤 빈칸**에 값을 얹습니다.
 *
 *   얹기("이용자명 :                (서명)", "이용자명 :", "김순자")
 *     → "이용자명 : 김순자          (서명)"      ← 길이가 같습니다
 *
 *   얹기("서비스 가격            원", "서비스 가격", "11,000", "오른쪽")
 *     → "서비스 가격      11,000원"              ← 「원」 앞에 붙습니다
 *
 * **왼쪽**은 이름표 쪽에 붙이고, **오른쪽**은 빈칸 끝(다음 글자 앞)에 붙입니다.
 * 금액은 오른쪽이 자연스럽습니다 — 종이에서 「원」 바로 앞에 오니까요.
 *
 * 빈칸이 없으면(이름표로 줄이 끝나면) 한 칸 띄우고 뒤에 붙입니다.
 * 값이 빈칸보다 길면 **자르지 않고 넘겨 씁니다** — 종이가 조금 밀려도
 * 값이 먼저입니다. 잘린 이름은 아무 쓸모가 없습니다.
 *
 * 못 찾으면 **`null`**. 조용히 넘어가지 않습니다.
 */
export function 얹기(
  글: string, 이름표: string, 값: string, 정렬: "왼쪽" | "오른쪽" = "왼쪽"
): string | null {
  const 원문 = String(글 ?? "");
  const i = 원문.indexOf(이름표);
  if (i < 0) return null;

  const 뒤부터 = i + 이름표.length;
  // 이름표 바로 뒤로 이어지는 공백이 **빈칸**입니다.
  let 끝 = 뒤부터;
  while (끝 < 원문.length && 원문[끝] === " ") 끝++;
  const 빈칸수 = 끝 - 뒤부터;

  const 값글 = String(값 ?? "");

  // 빈칸이 없으면 — 줄이 이름표로 끝난 경우입니다. 한 칸 띄우고 붙입니다.
  if (빈칸수 === 0) {
    return 원문.slice(0, 뒤부터) + " " + 값글 + 원문.slice(뒤부터);
  }

  /*
   * 값이 빈칸보다 길면 넘겨 씁니다. 이때 **꼬리는 살립니다** —
   * 「(서명)」이나 「원」이 사라지면 그건 서식을 고친 것이 됩니다.
   * 대신 한 칸은 띄워 둡니다. 값과 꼬리가 들러붙으면 못 읽습니다.
   */
  if (값글.length >= 빈칸수) {
    return 원문.slice(0, 뒤부터) + " " + 값글 + (끝 < 원문.length ? " " : "")
         + 원문.slice(끝);
  }

  const 남는칸 = 빈칸수 - 값글.length;
  const 채움 = 정렬 === "오른쪽"
    ? " ".repeat(남는칸) + 값글
    : " " + 값글 + " ".repeat(남는칸 - 1);
  return 원문.slice(0, 뒤부터) + 채움 + 원문.slice(끝);
}

/**
 * **자리 표시**를 값으로 바꿉니다.
 *
 *   자리바꾸기("◯◯◯◯제공기관 대표 (인)", "◯◯◯◯", "해남돌봄센터")
 *     → "해남돌봄센터제공기관 대표 (인)"
 *
 * 「◯◯◯◯」·「○○○」처럼 **여기 쓰라고 그려 둔 표시**는 빈칸과 같습니다.
 * 뒤에 붙이면 「◯◯◯◯ 해남돌봄센터」가 되어 종이가 우스워집니다.
 * 그러니 **그 자리를 값이 대신**합니다 — 기록지에서 「○ 를 ☑ 로」 바꾼 것과
 * 같은 생각이고, 서식이 적어 둔 **말**은 하나도 안 건드립니다.
 *
 * 값이 표시보다 짧으면 **빈칸으로 메워 길이를 지킵니다.**
 * 길면 그냥 넘겨 씁니다 — 기관 이름을 자르면 안 됩니다.
 *
 * 못 찾으면 **`null`**.
 */
export function 자리바꾸기(글: string, 자리: string, 값: string): string | null {
  const 원문 = String(글 ?? "");
  const i = 원문.indexOf(자리);
  if (i < 0) return null;
  const 값글 = String(값 ?? "");
  const 채움 = 값글.length < 자리.length
    ? 값글 + " ".repeat(자리.length - 값글.length)
    : 값글;
  return 원문.slice(0, i) + 채움 + 원문.slice(i + 자리.length);
}

/**
 * 「20   년    월     일」 같은 **날짜 틀**을 채웁니다.
 *
 * 서식마다 모양이 조금씩 다릅니다 —
 *   「을 20   년    월     일」   앞에 「20」이 이미 인쇄되어 있음
 *   「 년     월      일」        해를 통째로 적어야 함
 *
 * 둘 다 **글자 수를 지킵니다.** 숫자는 각 빈칸의 **오른쪽 끝**에 붙입니다 —
 * 종이에서 「년」·「월」·「일」 바로 앞에 오는 것이 자연스럽습니다.
 *
 * 날짜 틀이 아니면 **`null`**.
 */
export function 날짜얹기(글: string, 해: number, 달: number, 날: number): string | null {
  const 원문 = String(글 ?? "");
  if (!/년/.test(원문) || !/월/.test(원문) || !/일/.test(원문)) return null;

  /*
   * 「20」이 이미 인쇄되어 있으면 뒤 두 자리만 적습니다.
   * 「20  26년」처럼 벌어지면 안 되므로 **「20」에 딱 붙여** 씁니다.
   */
  /*
   * ── 해가 **이미 통째로 인쇄된** 틀 ────────────────────────
   *
   * 계약서(서식2)의 서명란은 「2026년    월     일」입니다. 해가 이미
   * 네 자리로 찍혀 있으니 **그 자리를 실제 해로 바꾸고** 월·일만 채웁니다.
   * 이걸 몰라 「20262026년」이 된 적이 있습니다 (2026-09-02).
   * 네 자리 → 네 자리라 길이는 그대로입니다.
   */
  const 통째해 = /(\d{4})(\s*)년/.exec(원문);
  if (통째해) {
    let 나온것 = 원문.replace(/(\d{4})(\s*)년/, String(해).padStart(4, "0") + 통째해[2] + "년");
    나온것 = 오른쪽채움(나온것, /(\s+)월/, String(달));
    나온것 = 오른쪽채움(나온것, /(\s+)일/, String(날));
    return 나온것;
  }

  const 스무해 = /20(\s+)년/.exec(원문);
  let 나온것 = 원문;
  if (스무해) {
    const 두자리 = String(해).slice(-2);
    const 빈칸 = 스무해[1].length;
    const 채움 = 두자리.length >= 빈칸
      ? 두자리
      : 두자리 + " ".repeat(빈칸 - 두자리.length);
    나온것 = 나온것.replace(/20\s+년/, "20" + 채움 + "년");
  } else {
    나온것 = 오른쪽채움(나온것, /(\s*)년/, String(해));
  }
  나온것 = 오른쪽채움(나온것, /(\s+)월/, String(달));
  나온것 = 오른쪽채움(나온것, /(\s+)일/, String(날));
  return 나온것;
}

/**
 * 「2025.   .     . ~ 2025.   .     .」 같은 **기간 틀**을 채웁니다.
 *
 * ── 인쇄된 해가 묵었습니다 ──────────────────────────────────
 *
 * 계약서(서식2)의 이 칸만 **2025** 로 인쇄돼 있습니다. 2026년 편람인데
 * 맨 아래 서명란은 「2026년」이라 군의 오타로 보입니다. 그대로 두면
 * 2026년에 맺은 계약서에 2025 가 찍혀 나갑니다.
 *
 * `해고침` 이 참이면 실제 해로 바꾸고, 거짓이면 **인쇄된 해를 그대로**
 * 둡니다. 서식에 인쇄된 글자를 고치는 일이라 **기관이 설정에서 정합니다**.
 *
 * 길이를 지킵니다 — 숫자는 「.」 바로 앞에 붙습니다.
 * 기간 틀이 아니면 `null`.
 */
export function 기간얹기(
  글: string,
  시작: { 해: number; 달: number; 날: number },
  끝: { 해: number; 달: number; 날: number },
  해고침: boolean
): string | null {
  const 원문 = String(글 ?? "");
  const 틀 = /(\d{4})\.(\s*)\.(\s*)\./g;   // 「YYYY. (빈칸) . (빈칸) .」
  const 값들 = [시작, 끝];
  let 몇번째 = 0;
  let 찾았나 = false;

  const 나온것 = 원문.replace(틀, (통째, 해글: string, 달칸: string, 날칸: string) => {
    const v = 값들[몇번째++];
    if (!v) return 통째;
    찾았나 = true;
    const 해 = 해고침 && v.해 ? String(v.해) : 해글;
    return 해 + "." + 오른쪽붙임(String(v.달 || ""), 달칸.length)
             + "." + 오른쪽붙임(String(v.날 || ""), 날칸.length) + ".";
  });
  return 찾았나 ? 나온것 : null;
}

/** 빈칸 폭을 지키며 오른쪽 끝에 붙입니다. 값이 더 길면 그냥 넘겨 씁니다. */
function 오른쪽붙임(값: string, 폭: number): string {
  return 값.length >= 폭 ? 값 : " ".repeat(폭 - 값.length) + 값;
}

/** 「빈칸 + 글자」 자리에서 빈칸 **오른쪽 끝**에 값을 붙입니다. 길이는 지킵니다. */
function 오른쪽채움(글: string, 틀: RegExp, 값: string): string {
  const m = 틀.exec(글);
  if (!m) return 글;
  const 빈칸 = m[1].length;
  const 꼬리 = m[0].slice(빈칸);
  const 채움 = 값.length >= 빈칸
    ? 값
    : " ".repeat(빈칸 - 값.length) + 값;
  return 글.slice(0, m.index) + 채움 + 꼬리 + 글.slice(m.index + m[0].length);
}
