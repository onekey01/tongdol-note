const 원 = (n: number) => Math.round(n).toLocaleString("ko-KR");

/** 「12시간」·「1시간 30분」처럼. */
export function 시간말(분: number): string {
  const m = Math.max(0, Math.round(분));
  const h = Math.floor(m / 60), 나머지 = m % 60;
  if (h && 나머지) return `${h}시간 ${나머지}분`;
  if (h) return `${h}시간`;
  return `${나머지}분`;
}

/** 「…을 / …를」 을 받침에 맞춰. 괄호가 화면에 보이면 기계가 쓴 글 같습니다. */
function 을를(말: string): string {
  const 끝 = 말.trim().slice(-1);
  const c = 끝.charCodeAt(0);
  if (c < 0xac00 || c > 0xd7a3) return `${말}을`;
  return (c - 0xac00) % 28 === 0 ? `${말}를` : `${말}을`;
}

const 날글 = (d: Date) =>
  `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}-` +
  `${String(d.getUTCDate()).padStart(2, "0")}`;

/**
 * ★ **그 구간에 그 요일이 몇 번 오나** — 달력을 그대로 셉니다.
 *
 * 「주 3회 × 4.35주」 같은 평균이 아닙니다. 9월 7일부터 9월 30일까지
 * 월·수·금이 몇 번인지는 **세면 나오는 정수**입니다. 사람은 4.35번
 * 갈 수 없습니다 (2026-09-07 무무).
 */
export function 요일센다(첫날: string, 끝날: string, 요일들: number[]): number {
  if (!요일들.length || 끝날 < 첫날) return 0;
  const 셀것 = new Set(요일들);
  let n = 0;
  const a = new Date(`${첫날}T00:00:00Z`), b = new Date(`${끝날}T00:00:00Z`);
  for (let d = new Date(a); d <= b; d.setUTCDate(d.getUTCDate() + 1))
    if (셀것.has(d.getUTCDay())) n++;
  return n;
}

/** 그 달의 첫날·마지막날. */
function 달범위(달: string): { 첫: string; 끝: string } {
  const [y, m] = 달.split("-").map(Number);
  const 끝일 = new Date(Date.UTC(y, m, 0)).getUTCDate();
  return { 첫: `${달}-01`, 끝: `${달}-${String(끝일).padStart(2, "0")}` };
}

/** 개시일부터 N개월 뒤의 **마지막 날** (개시일 전날까지). */
function 몇개월뒤(개시일: string, 개월: number): string {
  const d = new Date(`${개시일}T00:00:00Z`);
  d.setUTCMonth(d.getUTCMonth() + 개월);
  d.setUTCDate(d.getUTCDate() - 1);
  return 날글(d);
}

/** 두 날 사이의 달 목록 (YYYY-MM). */
function 달목록(첫날: string, 끝날: string): string[] {
  const 것: string[] = [];
  const d = new Date(`${첫날.slice(0, 7)}-01T00:00:00Z`);
  const 끝 = 끝날.slice(0, 7);
  for (let i = 0; i < 48; i++) {
    const m = 날글(d).slice(0, 7);
    것.push(m);
    if (m >= 끝) break;
    d.setUTCMonth(d.getUTCMonth() + 1);
  }
  return 것;
}

/**
 * 이 계획대로 가면 어떻게 되나.
 *
 * @param slots 주간계획 (요일 + 분). 화면에서 지금 고른 것.
 */
export function 계획재기(
  recipientId: string,
  serviceId: number,
  slots: { dow: number; minutes?: number | null }[],
  옵션: { 배정번호?: number | null; from?: string | null; to?: string | null;
          /** 한 달에 몇 번까지. 0 이면 매주 (v34). */ 달몇번?: number } = {}
): 잰것 {
  const sv = db.query<any, [number]>(
    "SELECT * FROM service WHERE id = ?").get(serviceId);
  if (!sv) throw new Error("그 서비스를 찾을 수 없습니다.");

  const rec = db.query<any, [string]>(
    "SELECT * FROM recipient WHERE id = ?").get(recipientId);
  if (!rec) throw new Error("그 대상자를 찾을 수 없습니다.");
  let 사람이름 = "";
  try { 사람이름 = String(JSON.parse(rec.payload || "{}")?.name ?? ""); } catch { }

  const 프로필 = db.query<any, []>(
    `SELECT rp.* FROM region_profile rp JOIN organization o ON o.profile_id = rp.id
      WHERE o.id = 1`).get();
  const 기준: "total" | "claim" =
    String(프로필?.cap_basis ?? "total") === "claim" ? "claim" : "total";
  const tier = rec.copay_tier_id
    ? db.query<any, [number]>("SELECT * FROM copay_tier WHERE id = ?").get(rec.copay_tier_id)
    : null;
  const 부담률 = Number(tier?.rate ?? 0);

  const 오늘 = new Date().toISOString().slice(0, 10);
  const 시간제 = sv.unit === "hour";
  const 단가 = Number(sv.unit_price ?? 0);
  const 하루최대 = 하루최대분() ?? 0;
  const 규칙 = 셈규칙읽기(sv);

  /* ── 한 번에 몇 분 인정되나 ──────────────────────────────── */
  const 요일들 = (slots ?? []).map((s) => Number(s?.dow)).filter((d) => d >= 0 && d <= 6);
  const 적은분 = Number((slots ?? []).find((s) => Number(s?.minutes) > 0)?.minutes ?? 0);
  /*
   * 안 적었으면 **1시간**으로 봅니다 (2026-09-09 무무). 하루 최대(천장)를
   * 쓰면 의뢰 그대로 옮긴 계획이 첫날부터 한도를 넘습니다 — `계획시간.ts`
   * 의 `기본계획분` 에 까닭을 적어 두었습니다.
   *
   * ★ 2026-09-11 부터 그 값은 **서비스마다 설정에서 정합니다**
   *   (설정 · 계산 규칙 → 서비스 → 1회 서비스 시간). 코드에 박힌 60분은
   *   기관이 아직 안 정했을 때만 쓰는 마지막 기본값입니다.
   */
  const 한번분 = 적은분 > 0 ? 적은분 : 서비스1회분(Number(sv.id ?? serviceId));
  const 실제한번 = 하루최대 > 0 ? Math.min(한번분, 하루최대) : 한번분;
  const 한번인정 = 시간제 ? 인정분(실제한번, 규칙) : 0;

  /* ── 언제부터 언제까지 ───────────────────────────────────── */
  const 개시일 = String(옵션.from || 오늘).slice(0, 10);
  const 기간개월 = Math.max(0, Number(sv.period_cap_months ?? 0));
  /*
   * ★ **개시일부터 2개월** (편람 · 2026-09-07 무무 「2개월로 자르기」).
   *   배정 기간이 더 길어도 여기까지만 셉니다. 예전에는 배정의 끝날
   *   (대개 연말)까지 다 간다고 보아 넉 달치가 잡혔습니다.
   */
  const 제한끝 = 기간개월 > 0 ? 몇개월뒤(개시일, 기간개월) : "";
  const 적은끝 = String(옵션.to || "").slice(0, 10);
  const 마지막날 =
    제한끝 && 적은끝 ? (적은끝 < 제한끝 ? 적은끝 : 제한끝)
    : 제한끝 || 적은끝 || `${개시일.slice(0, 4)}-12-31`;

  /* 한 달에 몇 번까지 가나 (v34). 0 이면 매주. */
  const 달번 = Math.max(0, Math.floor(Number(옵션.달몇번 ?? 0)));

  /* ── 달마다 — **정수 횟수**로 ────────────────────────────── */
  const 월분한도 = Number(sv.monthly_cap_minutes ?? 0);
  const 월횟수한도 = Number(sv.monthly_cap_count ?? 0);

  const 달들: 달치[] = [];
  if (요일들.length && 마지막날 >= 개시일) {
    for (const 달 of 달목록(개시일, 마지막날)) {
      const { 첫, 끝 } = 달범위(달);
      const 첫날 = 첫 > 개시일 ? 첫 : 개시일;
      const 끝날 = 끝 < 마지막날 ? 끝 : 마지막날;
      if (끝날 < 첫날) continue;

      /*
       * ★ **지난 달은 안 봅니다.** 이 자리는 「앞으로 이렇게 하면」을
       *   재는 곳입니다. 이미 지난 달의 계획을 지금 와서 경고해 봐야
       *   되돌릴 것이 없고, 그건 제공실적 화면이 실적으로 말해 줍니다.
       */
      if (끝날 < 오늘) continue;

      /*
       * ★ 주기(한 달에 몇 번)까지 넣어 셉니다 — **답하는 곳은 `가는날.ts` 하나**입니다.
       *   여기서 따로 세면 사무실 화면과 현장앱이 다른 날을 말하게 됩니다.
       */
      const 횟수 = 가는날세기(
        { weekly_plan: JSON.stringify(slots ?? []), period_from: 개시일,
          period_to: 마지막날, monthly_times: 달번 },
        첫날, 끝날);
      if (!횟수) continue;
      const 그달인정분 = 시간제 ? 횟수 * 한번인정 : 0;

      /* 그 달에 이미 인정받은 것 — 실적에서 (한도 화면과 같은 셈). */
      let 이미분 = 0, 이미횟수 = 0;
      try {
        const x = 월사용(recipientId, 달).find((r) => r.serviceId === serviceId);
        이미분 = Number(x?.인정분합 ?? 0);
        이미횟수 = Number(x?.쓴횟수 ?? 0);
      } catch { }

      const 넘나 =
        (월분한도 > 0 && 시간제 && 이미분 + 그달인정분 > 월분한도) ||
        (월횟수한도 > 0 && 이미횟수 + 횟수 > 월횟수한도);

      /*
       * ── 앞으로 갈 몫만 (오늘 이후) ──────────────────────────
       * 지난 날은 이미 실적에 있습니다. 또 더하면 두 번 세는 것입니다.
       */
      const 앞첫날 = 첫날 > 오늘 ? 첫날 : 오늘;
      const 앞으로횟수 = 앞첫날 <= 끝날
        ? 가는날세기({ weekly_plan: JSON.stringify(slots ?? []), period_from: 개시일,
                       period_to: 마지막날, monthly_times: 달번 }, 앞첫날, 끝날)
        : 0;
      const 앞으로분 = 시간제 ? 앞으로횟수 * 한번인정 : 0;

      /*
       * ★★ **월 한도까지만 더합니다** (2026-09-07 무무 「월 한도까지만」).
       *
       *   월 한도를 넘긴 몫은 어차피 청구해도 군이 안 줍니다. 그런 돈을
       *   연간 한도에서 또 깎으면 **같은 잘못을 두 번 세는 것**이고,
       *   연간 경고가 거짓이 됩니다.
       */
      let 셀분 = 앞으로분, 셀횟수 = 앞으로횟수;
      if (시간제 && 월분한도 > 0)
        셀분 = Math.max(0, Math.min(앞으로분, 월분한도 - 이미분));
      if (월횟수한도 > 0)
        셀횟수 = Math.max(0, Math.min(앞으로횟수, 월횟수한도 - 이미횟수));
      /* 시간제인데 횟수 한도도 걸리면, 둘 중 작은 쪽이 실제로 갈 수 있는 몫입니다. */
      if (시간제 && 월횟수한도 > 0)
        셀분 = Math.min(셀분, 셀횟수 * 한번인정);

      const 앞으로돈 = 시간제
        ? Math.round(단가 * (셀분 / 60))
        : Math.round(단가 * 셀횟수);

      달들.push({
        달, 첫날, 끝날, 횟수, 인정분: 그달인정분, 이미분, 이미횟수,
        넘나, 앞으로횟수, 앞으로분, 앞으로돈,
      });
    }
  }

  const 앞으로돈 = 달들.reduce((s, m) => s + m.앞으로돈, 0);
  const 계획대로돈 = 달들.reduce((s, m) =>
    s + (시간제 ? Math.round(단가 * (m.앞으로분 / 60)) : Math.round(단가 * m.앞으로횟수)), 0);

  const 한도로셀돈 = (총액: number) =>
    기준 === "claim" ? Math.round(총액 * (1 - 부담률)) : Math.round(총액);

  const 칸들: 잰칸[] = [];

  /* ── ① 월 한도 — 시간. **가장 많이 가는 달**로 봅니다 ────── */
  if (월분한도 > 0 && 시간제 && 달들.length) {
    const 최악 = 달들.reduce((a, b) =>
      (b.이미분 + b.인정분) > (a.이미분 + a.인정분) ? b : a);
    const 합 = 최악.이미분 + 최악.인정분;
    const 넘긴분 = Math.max(0, 합 - 월분한도);
    칸들.push({
      이름: `${sv.name} 월 한도(시간)`,
      한도: 월분한도, 쓴것: 최악.이미분, 더쓸것: 최악.인정분, 합,
      비율: 합 / 월분한도, 넘나: 합 > 월분한도, 단위: "분",
      말: `${달말(최악.달)} ${최악.횟수}번 × ${시간말(한번인정)} = ` +
          (최악.이미분 ? `${시간말(최악.인정분)} + 이미 ${시간말(최악.이미분)} = ` : "") +
          `${시간말(합)} / ${시간말(월분한도)}`,
      설명: 넘긴분 > 0
        ? `${달말(최악.달)}에 ${시간말(넘긴분)}을 넘깁니다. ` +
          `넘긴 몫 ${원(Math.round(단가 * (넘긴분 / 60)))}원은 청구해도 군이 안 줍니다 — ` +
          `기관이 떠안습니다. ` + 줄이는법(월분한도 - 최악.이미분, 최악.횟수, 한번인정, 규칙)
        : "",
    });
  }

  /* ── ② 월 한도 — 횟수 ─────────────────────────────────── */
  if (월횟수한도 > 0 && 달들.length) {
    const 최악 = 달들.reduce((a, b) =>
      (b.이미횟수 + b.횟수) > (a.이미횟수 + a.횟수) ? b : a);
    const 합 = 최악.이미횟수 + 최악.횟수;
    const 넘긴횟수 = Math.max(0, 합 - 월횟수한도);
    칸들.push({
      이름: `${sv.name} 월 한도(횟수)`,
      한도: 월횟수한도, 쓴것: 최악.이미횟수, 더쓸것: 최악.횟수, 합,
      비율: 합 / 월횟수한도, 넘나: 합 > 월횟수한도, 단위: "회",
      말: `${달말(최악.달)} ${최악.횟수}번` +
          (최악.이미횟수 ? ` + 이미 ${최악.이미횟수}번` : "") +
          ` = ${합}번 / ${월횟수한도}번`,
      설명: 넘긴횟수 > 0
        ? `${달말(최악.달)}에 ${넘긴횟수}번을 넘깁니다. ` +
          `${월횟수한도}번까지만 청구할 수 있고, 나머지 ${넘긴횟수}번은 기관이 떠안습니다. ` +
          `가는 요일을 줄이거나 격주로 잡으면 한도 안에 듭니다.`
        : "",
    });
  }

  /* ── ③ 연간 한도 — **일상생활돌봄 전체 합산** ──────────── */
  const 설정 = 한도설정();
  const 바깥 = Number(sv.outside_annual_cap ?? 0) === 1;
  if (설정.연간 > 0 && !바깥) {
    const 해 = Number(개시일.slice(0, 4));
    /* `연간쓴돈` 이 이미 기준(총액/군 부담)대로 셈해 옵니다 — 여기서 또 빼면 두 번 뺍니다. */
    let 이미 = 0;
    try { 이미 = 연간쓴돈(recipientId, 해).일상.쓴돈; } catch { }
    const 앞으로 = 한도로셀돈(앞으로돈);
    const 합 = 이미 + 앞으로;
    const 넘긴돈 = Math.max(0, 합 - 설정.연간);
    칸들.push({
      이름: `${해}년 연간 지원한도 (일상생활돌봄 전체)`,
      한도: 설정.연간, 쓴것: 이미, 더쓸것: 앞으로, 합,
      비율: 합 / 설정.연간, 넘나: 합 > 설정.연간, 단위: "원",
      말: `이미 ${원(이미)}원 + 앞으로 ${원(앞으로)}원 = ${원(합)}원 / ${원(설정.연간)}원`,
      설명: 넘긴돈 > 0
        ? `${원(넘긴돈)}원을 넘깁니다. 이 칸은 이 서비스 하나가 아니라 ` +
          `**이 분이 올해 받는 일상생활돌봄 전부**를 합한 것입니다 ` +
          `(안전생활환경개선은 따로 셉니다). 넘긴 몫은 군이 안 주므로, ` +
          `기간을 줄이거나 다른 서비스를 조정해야 합니다.`
        : `앞으로 갈 것은 **월 한도까지만** 셈했습니다` +
          (계획대로돈 > 앞으로돈
            ? ` — 계획대로 다 가면 ${원(한도로셀돈(계획대로돈))}원입니다만, ` +
              `월 한도를 넘긴 몫은 군이 안 주므로 연간 한도에서도 안 깎습니다.`
            : `.`),
    });
  }

  /* ── ④ 생애 1회 서비스 ────────────────────────────────── */
  if (sv.lifetime_cap != null && Number(sv.lifetime_cap) > 0) {
    const 받은적 = Number((db.query<any, [string, number]>(
      `SELECT COUNT(*) AS n FROM delivery
        WHERE recipient_id = ? AND service_id = ? AND outcome = '제공'`
    ).get(recipientId, serviceId) as any)?.n ?? 0);
    if (받은적 > 0)
      칸들.push({
        이름: `${sv.name} — 생애 1회`,
        한도: 1, 쓴것: 받은적, 더쓸것: 0, 합: 받은적,
        비율: 받은적, 넘나: true, 단위: "회",
        말: `이미 ${받은적}번 받으셨습니다. 생애 1회 서비스입니다`,
        설명: `안전생활환경개선은 **생애 한 번**뿐입니다. 한도가 남아 있어도 ` +
              `다시 받으실 수 없습니다. 군에 확인하지 않고 진행하면 ` +
              `공사비 전부를 기관이 떠안습니다.`,
      });
  }

  /* ── ★ 지금 이 분이 받고 있는 것 ─────────────────────────── */
  const 이번달 = 오늘.slice(0, 7);
  const 현황줄들: 현황줄[] = [];
  try {
    for (const x of 월사용(recipientId, 이번달)) {
      const s2 = db.query<any, [number]>(
        "SELECT unit, monthly_cap_minutes, monthly_cap_count FROM service WHERE id = ?"
      ).get(x.serviceId);
      const 시 = s2?.unit === "hour";
      const 월분 = Number(s2?.monthly_cap_minutes ?? 0);
      const 월횟 = Number(s2?.monthly_cap_count ?? 0);
      const 남분 = 월분 > 0 ? Math.max(0, 월분 - x.인정분합) : 0;
      const 남횟 = 월횟 > 0 ? Math.max(0, 월횟 - x.쓴횟수) : 0;
      const 조각: string[] = [];
      if (시 && 월분 > 0)
        조각.push(`${시간말(x.인정분합)} / ${시간말(월분)} · 남음 ${시간말(남분)}`);
      else if (시) 조각.push(`${시간말(x.인정분합)}`);
      if (월횟 > 0) 조각.push(`${x.쓴횟수}번 / ${월횟}번 · 남음 ${남횟}번`);
      else if (!시) 조각.push(`${x.쓴횟수}번`);
      현황줄들.push({
        serviceId: x.serviceId, 이름: x.name, 시간제: 시,
        이번달분: x.인정분합, 이번달횟수: x.쓴횟수,
        월한도분: 월분, 월한도횟수: 월횟, 남은분: 남분, 남은횟수: 남횟,
        올해돈: 0,
        말: 조각.join(" · "),
      });
    }
  } catch { }

  let 연간현황 = { 한도: 0, 쓴돈: 0, 남은돈: 0, 비율: 0, 봄: false };
  try {
    const h = 연간쓴돈(recipientId, Number(오늘.slice(0, 4)));
    연간현황 = {
      한도: h.일상.한도, 쓴돈: h.일상.쓴돈,
      남은돈: Math.max(0, h.일상.한도 - h.일상.쓴돈),
      비율: h.일상.비율, 봄: h.일상.봄,
    };
    for (const 줄 of 현황줄들) {
      const g = h.줄.find((y: any) => y.serviceId === 줄.serviceId);
      줄.올해돈 = Number(g?.금액 ?? 0);
    }
  } catch { }

  const 기간끝났나 = 마지막날 < 오늘;

  const 넘나 = 칸들.some((x) => x.넘나);
  const 넘은것 = 칸들.filter((x) => x.넘나);
  const 모두횟수 = 달들.reduce((s, m) => s + m.횟수, 0);

  const 한줄 = 넘나
    ? `★ ${을를(넘은것.map((x) => x.이름).join(" · "))} 넘습니다`
    : 기간끝났나
      /*
       * ★ **「재의뢰하시면 됩니다」라고 하면 안 됩니다** (2026-09-07 무무 —
       *   「생애한도이기 때문에 기간을 다 받은 후엔 재의뢰는 현재
       *    사업안내 및 편람 상 **불가능** 한 것으로 알고있어」).
       *
       *   할 수 없는 길을 알려 주면 기관이 그 길을 알아보느라 시간을
       *   쓰고, 군에 물어보고 나서야 안 된다는 것을 압니다.
       *   **안 되는 것은 안 된다고 적습니다.**
       */
      ? `이 서비스의 제공 기간이 ${마지막날} 로 끝났습니다` +
        (기간개월 > 0 ? ` (편람 「개시일부터 ${기간개월}개월」).` : ".") +
        ` 지금 지침·편람으로는 **다시 받으실 수 없습니다** — ` +
        `한도가 남아 있어도 마찬가지입니다.`
    : 모두횟수
      ? `${개시일} ~ ${마지막날} · 모두 ${모두횟수}번 · ${원(앞으로돈)}원 — 한도 안입니다`
      : "가는 요일을 고르면 여기서 재 드립니다.";

  return {
    대상자: 사람이름, 서비스: String(sv.name ?? ""), 단위: String(sv.unit ?? ""),
    시간제, 기간개월, 개시일, 마지막날, 달들,
    앞으로돈, 계획대로돈,
    기준, 기준말: 기준 === "claim" ? "군 부담액 (본인부담 뺀 것)" : "총 서비스 비용",
    부담률, 칸들, 넘나, 한줄, 기간끝났나,
    현황: { 달: 이번달, 줄들: 현황줄들, 연간: 연간현황 },
  };
}

/**
 * ★ **어떻게 줄이면 한도 안에 드는지** 알려 줍니다.
 *
 * 「넘었습니다」로만 끝나면 관리자는 요일을 하나씩 눌러 보며 맞춰야
 * 합니다. 몇 번까지 갈 수 있는지, 한 번에 몇 분까지 되는지는
 * **프로그램이 세면 바로 나오는 숫자**입니다.
 */
function 줄이는법(
  쓸수있는분: number, 횟수: number, 한번인정: number, 규칙: any
): string {
  if (쓸수있는분 <= 0) return "이 달은 한도를 이미 다 쓰셨습니다.";
  const 갈수있는횟수 = Math.floor(쓸수있는분 / Math.max(1, 한번인정));
  const 한번줄이면 = 횟수 > 0 ? Math.floor(쓸수있는분 / 횟수) : 0;
  /* 30분 규칙에서 실제로 나올 수 있는 값으로 내려 맞춥니다. */
  const 단위 = 규칙?.단위 === 60 ? 60 : 30;
  const 쓸수있는한번 = Math.floor(한번줄이면 / 단위) * 단위;

  const 길: string[] = [];
  if (갈수있는횟수 > 0) 길.push(`이대로면 ${갈수있는횟수}번까지`);
  if (쓸수있는한번 > 0 && 쓸수있는한번 < 한번인정)
    길.push(`횟수를 그대로 두려면 한 번에 ${시간말(쓸수있는한번)}까지`);
  return 길.length ? `한도 안에 들려면 — ${길.join(" · ")}.` : "";
}

/** "2026-09" → "9월" */
function 달말(달: string): string {
  return `${Number(달.slice(5, 7))}월`;
}
