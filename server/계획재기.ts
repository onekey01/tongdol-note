/**
 * 계획을 **미리 재 봅니다** — 저장하기 전에.
 *
 * ═══════════════════════════════════════════════════════════
 *  왜 있나
 * ═══════════════════════════════════════════════════════════
 *
 * (2026-09-07 무무 — 계획 수립 시 100%가 넘어가는 계획이 수립되면
 *  경고창을 띄우자 / 「단계적으로 막음… **한도가 넘어갈 경우 지자체
 *  예산의 문제가 발생할 수 있습니다. 정말로 계획 할까요?** 라고 한번만
 *  더 묻는거지」)
 *
 * 한도 경고가 전부 **사후**였습니다. 다녀온 기록이 쌓여 넘고 나서야
 * 홈에 떴는데, 그때는 **이미 나간 돈**입니다. 넘긴 몫을 지자체가
 * 안 주면 기관이 떠안습니다.
 *
 * ═══════════════════════════════════════════════════════════
 *  ★★★ 2026-09-07 다시 짰습니다 ★★★
 * ═══════════════════════════════════════════════════════════
 *
 * 처음 버전은 **「주 3회 × 4.35주」**로 밀어서 셌습니다. 그랬더니
 * 화면에 「한 달 **13.05회**」·「**26시간 6분**」이 떴습니다.
 *
 *   (무무 — 「실제로 실행되었다고 인정되는 **횟수(소수점은 말도
 *    안되지) × 시간**으로 계산이 되어야 해. **6분 자체가 말이 안되는
 *    거야.**」)
 *
 * 맞는 말씀입니다. 월 한도 12시간은 **제공인력이 실행했다고 인정되는
 * 시간**이지, 기간으로 미뤄 짐작한 평균이 아닙니다. 사람은 4.35번
 * 갈 수 없습니다.
 *
 * ── 그래서 세 가지를 바꿨습니다 ────────────────────────────
 *
 *  ① **달력을 실제로 셉니다.** 그 달에 월·수·금이 몇 번 있는지
 *     세어 **정수**로 잡습니다. 9월은 13번, 10월은 14번 — 달마다
 *     다르고 그게 사실입니다. 소수점도 「6분」도 안 나옵니다.
 *
 *  ② **개시일부터 2개월까지만** 셉니다 (편람). 예전에는 배정
 *     기간의 끝날(대개 연말)까지 다 간다고 보아 넉 달치가 잡혔습니다.
 *
 *  ③ **연간 한도에는 월 한도까지만 더합니다.** 월 한도를 넘긴 몫은
 *     어차피 청구해도 군이 안 줍니다. 그런 돈을 연간에서 또 깎으면
 *     **같은 잘못을 두 번 세는 것**이고, 연간 경고가 거짓이 됩니다.
 *     (예전 버전은 계획대로 134만원을 더해 「90% 찼다」고 했는데,
 *      월 한도를 지키면 72만원 · 48% 였습니다.)
 *
 * ── ★ 막지 않습니다 ★ ──────────────────────────────────────
 *
 * 지자체가 승인한 계획이 한도를 넘을 수 있습니다. 기계가 앞서 막으면
 * 현장이 프로그램과 싸우게 되고, 결국 프로그램을 안 씁니다.
 * **두 번 묻고 지나가게 합니다** — 화면이 그 일을 합니다.
 *
 * ── ★ 셈은 빌려 씁니다 ★ ───────────────────────────────────
 *
 * 시간 환산은 `money.인정분()`, 하루 최대는 `계획시간.하루최대분()`,
 * 이미 쓴 것은 `한도.연간쓴돈()` 과 `한도.월사용()`.
 * **여기서 다시 세지 않습니다.** 같은 셈을 두 곳에 적으면 언젠가
 * 한쪽만 고쳐지고, 그러면 미리 잰 값과 청구서가 다른 말을 합니다 —
 * 그건 안 재느니만 못합니다.
 */
