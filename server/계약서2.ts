/**
 * ── 서비스 제공·이용 계약서 = **편람 서식2** ──────────────────
 *
 * 지금까지 `contract.ts` 가 PDF 로 **직접 그렸습니다.** 조항 글자는 맞아도
 * 글꼴·선 굵기·여백이 우리가 정한 값이라 **같은 서식이 아닙니다.**
 * 지자체에 내는 서류는 **서식이 완전히 같아야 하고 확장자만 달라야** 합니다.
 * 그래서 편람 원본(`서식/서비스 제공·이용 계약서(서식2).hwpx`)을 채웁니다.
 *
 * ── 채우는 곳과 비우는 곳 ────────────────────────────────────
 *
 * 채웁니다 — 이용자 인적사항, 서비스 종류와 계약기간, 기관 정보, 담당자,
 *            맨 아래 날짜와 이름.
 *
 * **「□ 확인」은 「☑ 확인」으로 바꿉니다** (2026-09-02, 무무 님 지시).
 * 조항 열일곱 개를 하나씩 읽어 드리고 표시하는 것이 현장 절차인데,
 * 종이에 미리 찍혀 나오는 편이 실제와 맞다고 하셨습니다.
 * **서식이 적어 둔 말은 그대로 두고 표시만** 바꿉니다 — 기록지에서
 * 「○ 를 ☑ 로」 바꾼 것과 같습니다. 두 글자 다 한 자리라 길이도 그대로입니다.
 *
 * (제 걱정은 적어 둡니다 — 맨 아래 서명이 동의의 증거이긴 하나, 미리 찍힌
 *  표시는 「읽어 드렸다」를 종이가 먼저 말하는 것이 됩니다. 군이 문제 삼으면
 *  설정으로 빼는 것이 어렵지 않습니다.)
 *
 * **비웁니다** —
 *   · **「(서명 또는 인)」 세 군데.** 본인·대리인·제공인력의 **자필**입니다.
 *     영수증과 달리 여기엔 기관 직인 자리가 없습니다 —
 *     셋 다 사람이 손으로 하는 자리라 **직인을 안 찍습니다.**
 *   · **대리인·비상연락처는 통째로 비웁니다** (위 표와 아래 서명란 둘 다).
 *     계약 자리에서 **얼굴을 보고 확인하며 손으로 적는 자리**입니다.
 *     자료함에 적힌 대리인이 낡았을 수 있고, 그날 실제로 서명하는 사람이
 *     누구인지는 그 자리에서 정해집니다. 우리가 미리 찍어 두면
 *     **틀린 이름 위에 남이 서명하는 종이**가 됩니다.
 *
 * ── 계약기간 칸의 「2025」 ────────────────────────────────────
 *
 * 이 칸만 2025 로 인쇄돼 있습니다(군의 오타로 보입니다). 실제 해로 고칠지는
 * **설정 · 계산 규칙**에서 기관이 정합니다 — 서식에 인쇄된 글자를 고치는
 * 일이라 우리가 몰래 정하지 않습니다. 기본은 켬입니다.
 */
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { Hwpx } from "./hwpx";
import { 기간얹기 } from "./서식채우기";
import { db } from "./db";
import { today } from "./util";
import { 서식폴더 } from "./서식자리";
import { gather } from "./contract";

const 서식이름 = "서비스 제공·이용 계약서(서식2).hwpx";

/** 사람 정보 표(표1)에서 우리가 채우는 자리. 나머지는 손도 안 댑니다. */
const 자리 = {
  성명: [1, 1], 생년월일: [1, 3], 성별: [1, 5],
  주소: [2, 1],
  전화: [3, 1],
  // 대리인1: [3, 3], 대리인2: [3, 5] — **일부러 안 채웁니다** (머리말 참고)
  서비스: [6, 1], 기간: [6, 3],
  기관명: [7, 1], 대표자: [7, 3], 기관전화: [7, 5],
  담당자: [8, 1], 담당자연락처: [8, 2],
} as const;

export type 계약서값 = ReturnType<typeof 모으기>;

export function templatePath(): string {
  const p = join(서식폴더(), 서식이름);
  if (!existsSync(p)) throw new Error(`서식을 찾을 수 없습니다 — ${서식이름}`);
  return p;
}

const ymd = (s: string) => {
  const [y, m, d] = String(s ?? "").split("-").map(Number);
  return { 해: y || 0, 달: m || 0, 날: d || 0 };
};

/**
 * ── 계약기간 칸의 묵은 해는 **늘 고칩니다** ─────────────────
 *
 * 서식2 의 계약기간 칸만 「2025.   .     .」로 인쇄돼 있습니다. 맨 아래
 * 서명란은 「2026년」이라 **군의 오타**로 보입니다.
 *
 * 처음에는 설정 스위치로 두었습니다 — 제출 서식에 인쇄된 글자를 고치는
 * 일이라 기관이 정하게 하려던 것입니다. 그런데 **끄면 2026년에 맺은
 * 계약서에 2025 가 찍혀 나갑니다.** 그건 고를 일이 아니라 틀린 것이라,
 * **선택이 아니라 필수**로 바꿨습니다 (2026-09-04 무무 님 지시).
 *
 * 자료함의 `region_profile.form_fix_year` 칸은 **지우지 않고 둡니다** —
 * 칸을 지우면 옛 버전이 그 자료함을 못 엽니다(내림 막이). 아무도 안 봅니다.
 */
export function 해고침켜졌나(): boolean {
  return true;
}

/**
 * 계약서에 담을 값을 모읍니다.
 *
 * 사람·의뢰·기관은 `contract.ts` 의 `gather` 가 이미 모으고 있어 그대로 씁니다 —
 * PDF 와 hwpx 가 **같은 값**을 보아야 두 종이가 어긋나지 않습니다.
 */
export function 모으기(recipientId: string, opt: {
  계약일?: string; 담당자?: string; 담당자연락처?: string; 제공인력?: string;
} = {}) {
  const g = gather(recipientId);

  /*
   * ── 제공인력은 **배정에서 꺼내 옵니다** ────────────────────
   *
   * 계약서 서명란의 「제공인력 (성명)」은 실제로 가는 사람입니다.
   * 그 사람은 자료함에 있습니다 — 살아 있는 배정의 담당입니다.
   *
   * **여럿이면 비웁니다.** 서식에는 그 자리가 하나뿐인데 가사는 최돌봄,
   * 식사는 김배달이면 누구를 적어도 반쪽이 됩니다. 그럴 땐 계약 자리에서
   * 손으로 적는 것이 맞습니다.
   */
  const 배정된이 = opt.제공인력 ? [String(opt.제공인력)] : [...new Set(
    db.query<any, [string, string]>(
      `SELECT DISTINCT u.name
         FROM assignment a
         JOIN worker w  ON w.id = a.worker_id
         JOIN app_user u ON u.id = w.user_id
        WHERE a.recipient_id = ?
          AND (a.period_to IS NULL OR a.period_to >= ?)`
    ).all(recipientId, today()).map((r) => String(r.name ?? "")).filter(Boolean),
  )];
  /*
   * **대리인은 일부러 안 가져옵니다.** 계약서에 안 찍기 때문입니다 —
   * 값을 들고 다니면 언젠가 누가 「있는데 왜 안 쓰지」 하고 찍습니다.
   */
  return {
    이용자: g.recipient,
    서비스: g.서비스.join(" · "),
    시작: g.시작, 끝: g.끝,
    기관: {
      이름: String(g.org?.name ?? ""),
      대표: String(g.org?.ceo_name ?? ""),
      전화: String(g.org?.phone ?? ""),
    },
    담당자: String(opt.담당자 ?? ""),
    담당자연락처: String(opt.담당자연락처 ?? ""),
    제공인력: 배정된이.length === 1 ? 배정된이[0] : "",
    계약일: String(opt.계약일 || today()),
  };
}

/**
 * 서식2 를 채운 hwpx 를 만듭니다.
 *
 * **이름표를 못 찾으면 터뜨립니다.** 서식이 개정되어 글자가 바뀌면
 * 조용히 빈 계약서가 나가는 것이 가장 나쁩니다 — 그 자리에서 알아야 합니다.
 */
export function build(v: 계약서값): Buffer {
  const d = new Hwpx(readFileSync(templatePath()));
  const tbl = d.tables()[1];
  if (!tbl) throw new Error("서식2 에서 사람 정보 표를 찾지 못했습니다.");

  const 받: string[] = [];
  const 칸 = (n: keyof typeof 자리) => d.cell(tbl, 자리[n][0], 자리[n][1]);
  /** 빈 칸에 값을 넣습니다 (지킬 글자가 없는 칸입니다). */
  const 넣 = (n: keyof typeof 자리, 값: string) => d.setCell(칸(n), 값);
  /** 이름표 뒤에 값을 얹습니다 (서식 글자를 지키는 칸입니다). */
  const 얹 = (n: keyof typeof 자리, 이름표: string, 값: string) => {
    if (!값) return;                       // 빈 값이면 이름표만 남깁니다
    if (!d.얹기(칸(n), 이름표, 값)) 받.push(`${n} 의 ${이름표}`);
  };

  // ── 서비스 이용자 ─────────────────────────────────────────
  넣("성명", v.이용자.name);
  넣("생년월일", v.이용자.birth);
  넣("성별", v.이용자.gender);
  넣("주소", v.이용자.address);
  얹("전화", "(집)", v.이용자.phoneHome);
  얹("전화", "(핸드폰)", v.이용자.phone);

  /*
   * **대리인·비상연락처 두 자리는 채우지 않습니다.** 이름표만 남깁니다 —
   * 계약 자리에서 사람이 손으로 적습니다 (머리말 참고).
   */

  // ── 서비스 제공기관 ───────────────────────────────────────
  넣("서비스", v.서비스);
  넣("기관명", v.기관.이름);
  넣("대표자", v.기관.대표);
  넣("기관전화", v.기관.전화);
  얹("담당자", "(성  명)", v.담당자);
  얹("담당자연락처", "(연락처)", v.담당자연락처);

  /*
   * ── 「□ 확인」 → 「☑ 확인」 ────────────────────────────────
   * 서식의 **말은 한 글자도 안 바꾸고 네모 표시만** 바꿉니다.
   * 열일곱 군데가 다 바뀌지 않으면 서식이 달라진 것이므로 터뜨립니다.
   */
  const 친것 = d.글자바꾸기("□ 확인", "☑ 확인");
  if (친것 < 17) 받.push(`확인 표시 (${친것}군데만 바뀜, 17군데여야 합니다)`);

  /*
   * 계약기간 — 「2025.   .     . ~ 2025.   .     .」
   * 인쇄된 해를 실제 해로 고칠지는 설정이 정합니다.
   */
  {
    const tc = 칸("기간");
    const 시 = ymd(v.시작), 종 = ymd(v.끝);
    const 고침 = 해고침켜졌나();
    let 됐나 = false;
    for (const p of d.paras(tc)) {
      if (d.기간얹기칸(p, 시, 종, 고침)) { 됐나 = true; break; }
    }
    if (!됐나) 받.push("계약기간");
  }

  /*
   * ── 맨 아래 서명란 ────────────────────────────────────────
   * 「2026년    월     일」 · 「본 인 (성명) … (서명 또는 인)」 ·
   * 「기 관 명」 · 「제공인력 (성명) … (서명 또는 인)」
   *
   * **(서명 또는 인) 은 비웁니다** — 세 군데 다 사람이 손으로 하는 자리입니다.
   *
   * 날짜는 **표 밖에서만** 찾습니다. 표 안의 **「생년월일」이라는 라벨**도
   * 년·월·일이 다 있어 날짜 틀로 걸립니다 — 그것이 「생2026년월일」이
   * 된 적이 있습니다 (2026-09-02).
   */
  const 계 = ymd(v.계약일);
  if (!d.날짜얹기문서(계.해, 계.달, 계.날, { 표밖만: true })) 받.push("계약일");
  if (!d.얹기문서("본 인  (성명)", v.이용자.name)) 받.push("본인 성명");

  /*
   * 서명란의 **대리인 줄도 비웁니다.** 위 표와 같은 까닭입니다 —
   * 대리인은 그 자리에서 확인하고 자기 손으로 적고 서명합니다.
   */

  /*
   * 서명란의 기관명은 **앞에 빈칸 두 개**가 있습니다(「  기 관 명」).
   * 위 표의 라벨은 「기 관 명」으로 빈칸이 없어, 이것으로 갈립니다.
   */
  if (!d.얹기문서("  기 관 명", v.기관.이름)) 받.push("기관명(서명란)");
  if (v.제공인력 && !d.얹기문서("제공인력   (성명)", v.제공인력))
    받.push("제공인력 성명");

  if (받.length)
    throw new Error(
      `서식2 에서 이름표를 못 찾았습니다 — ${[...new Set(받)].join(" · ")}\n` +
      `서식이 바뀌었을 수 있습니다. 「서식/${서식이름}」을 확인해 주세요.`
    );

  /*
   * ── 표의 **「글자처럼 취급」을 끕니다** (2026-09-04 무무 님 지시) ──
   *
   * 서식2 의 표들도 `treatAsChar="1"` — 글자 한 개처럼 문단 줄 안에
   * 들어앉아 있습니다. 그러면 표가 한 쪽에 안 들어가는 순간 글자가
   * 줄바꿈되듯 **통째로 다음 쪽으로** 넘어가, 앞쪽이 텅 빈 채 나옵니다.
   *
   * 끄면 이미 켜져 있는 `pageBreak="CELL"` 이 살아나 쪽을 넘어가며
   * 이어집니다. 편람의 서식9·서식4 가 이미 그렇게 되어 있습니다.
   * 자세한 것은 `hwpx.ts` 의 `글자처럼취급끄기` 머리말에 있습니다.
   */
  for (const t of d.tables()) d.글자처럼취급끄기(t);

  const 흠 = d.audit();
  if (흠.length) throw new Error(`서식2 자체 점검에 걸렸습니다 — ${흠.join(" · ")}`);
  return d.save();
}

/** 파일 이름 — 사람이 폴더에서 알아볼 수 있게. */
export function 파일이름(v: 계약서값): string {
  const 성함 = (v.이용자.name || "이용자").replace(/[\\/:*?"<>|]/g, "");
  return `서비스 제공·이용 계약서_${성함}_${v.계약일}.hwpx`;
}
