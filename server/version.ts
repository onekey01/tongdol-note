import pkg from "../package.json";
import { SCHEMA_VERSION } from "./schema";

/**
 * 프로그램 버전 번호 — **한 줄로 다 말하게** 만듭니다.
 *
 *      v 1 . 2 . 15
 *        │   │   └─ 자료함 구조 번호 (SCHEMA_VERSION)
 *        │   └───── 내보낼 때마다 올리는 번호
 *        └───────── 크게 달라질 때 올리는 번호
 *
 * ── 왜 구조 번호를 버전 번호 안에 넣는가 ────────────────────
 * 예전에는 「버전」과 「자료함 구조」가 **따로** 있었습니다. 원격으로 도와드릴 때
 * 두 숫자를 각각 물어야 했고, 기관은 그 둘이 왜 다른지도 몰랐습니다.
 * 한 줄로 붙이면 **한 번만 물으면 됩니다.** 그리고 두 값이 서로 어긋날 일이
 * 아예 없어집니다 — 뒷자리는 손으로 적는 것이 아니라 코드에서 따 옵니다.
 *
 * ── 그래서 생기는 규칙 하나 ───────────────────────────────
 * **내보낼 때마다 앞 두 자리를 올려야 합니다.** 뒷자리는 자료 칸이 바뀔 때만
 * 움직이므로, 앞을 안 올리면 **다른 프로그램이 같은 번호**를 갖게 됩니다.
 * 「통돌Note 만들기.bat」이 물어보는 것이 바로 그 앞 두 자리입니다.
 *
 * 버전 번호를 손으로 적는 자리는 `package.json` **하나**뿐이고,
 * 하나짜리 실행 파일로 묶을 때도 그 값이 함께 들어갑니다
 * (`bun build --compile` 이 JSON 을 끌어안습니다).
 */
const 적힌것 = String((pkg as any).version ?? "0.0.0");
const [큰, 작은] = 적힌것.split(".");

/** 내보내는 쪽에서 정하는 앞 두 자리. 예: "1.2" */
export const 앞자리 = `${Number(큰) || 0}.${Number(작은) || 0}`;

/** 화면·자료함·갱신이 함께 쓰는 **하나뿐인 버전 번호.** 예: "1.2.15" */
export const 버전 = `${앞자리}.${SCHEMA_VERSION}`;

/**
 * 버전 번호를 견줍니다. 앞이 크면 1, 뒤가 크면 -1, 같으면 0.
 *
 * 숫자로 자릅니다 — 글자로 견주면 **「0.10」이 「0.9」보다 작다**고 나옵니다.
 * 갱신은 열 번을 훌쩍 넘길 것이라 그 자리에서 반드시 어긋납니다.
 */
export function 버전견주기(a: string, b: string): number {
  const 자르기 = (v: string) =>
    String(v ?? "").split(".").map((x) => Number(String(x).replace(/\D.*$/, "")) || 0);
  const A = 자르기(a), B = 자르기(b);
  for (let i = 0; i < Math.max(A.length, B.length); i++) {
    const x = A[i] ?? 0, y = B[i] ?? 0;
    if (x !== y) return x > y ? 1 : -1;
  }
  return 0;
}
