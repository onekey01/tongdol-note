type 처리결과 = { 본것: number; 들인수: number; 막은수: number };

/**
 * 우편함에 온 로그인 요청을 처리합니다.
 *
 * 사람이 폰 앞에서 **기다리고 있는** 일이라 자주 돌아야 합니다.
 * 그래서 보고 받기(20초)보다 빠른 5초입니다.
 */
/*
 * 우편함과 기관 열쇠를 **밖에서 넣을 수 있게** 해 둡니다.
 * 시험이 진짜 Supabase 없이 이 길을 통째로 돌려 볼 수 있어야 하기
 * 때문입니다 — 비밀번호를 맞춰 보는 자리를 시험 못 하면 안 됩니다.
 */
export async function 요청살피기(넣은함?: 우편함, 넣은열쇠?: string): Promise<처리결과> {
  const 설정 = 넣은함 ? null : 우편함.설정읽기();
  if (!넣은함 && !설정) return { 본것: 0, 들인수: 0, 막은수: 0 };

  const 함 = 넣은함 ?? new 우편함(설정!);
  const 기관열쇠 = 넣은열쇠 ?? 설정!.기관열쇠;
  const 쌍 = 열쇠쌍();
  if (!쌍) {
    // 아직 쌍이 없으면 만들고 올리기만 합니다. 지금 온 요청은 못 풉니다.
    await 열쇠쌍챙기기(함);
    return { 본것: 0, 들인수: 0, 막은수: 0 };
  }

  const 온것들 = await 함.기다리는요청();

  /*
   * 볼 것이 없을 때만 공개쪽을 맞춰 봅니다 — 바쁜 때를 피합니다.
   */
  if (!온것들.length) await 공개쪽맞추기(함);

  let 들인수 = 0, 막은수 = 0;

  for (const 요청 of 온것들) {
    try {
      const 결과 = await 하나처리(함, 쌍.개인, 기관열쇠, 요청);
      if (결과) 들인수++; else 막은수++;
    } catch (e) {
      /*
       * 하나가 잘못돼도 나머지는 처리합니다. 다만 **답은 꼭 답니다** —
       * 답이 없으면 폰은 「기다리는 중」에 15분을 갇혀 있습니다.
       *
       * ★ 다만 **이미 들여보낸 뒤**라면 거절하면 안 됩니다 (2026-09-05).
       *
       *   열쇠를 다 내주고 기기까지 갈아 끼운 다음 마지막 한 걸음에서
       *   신호가 끊기면, 옛 코드는 「아이디나 비밀번호가 맞지 않습니다」를
       *   답했습니다. 비밀번호는 맞았는데요. 게다가 그 사이 **앞 브라우저의
       *   등록은 이미 지워져** 있어서, 돌아가 보면 그것도 사라져 있습니다.
       *   현장에서는 「내 비밀번호가 바뀌었나」로 사무실에 전화가 옵니다.
       *
       *   그런 때는 답을 안 답니다. 다음 차례(5초 뒤)에 다시 시도하고,
       *   그때는 표식이 같으므로 조용히 끝납니다.
       */
      const 들인뒤 = (e as any)?.들인뒤 === true;
      console.error(`계정 로그인: 요청 ${요청.id} 처리 실패 —`, (e as Error).message);
      if (!들인뒤) {
        try {
          await 함.요청답하기(요청.id, { status: "거절", reason: 안맞음 });
        } catch { /* 이것마저 안 되면 기한이 지나 스스로 사라집니다 */ }
      }
      막은수++;
    }
  }
  return { 본것: 온것들.length, 들인수, 막은수 };
}

async function 하나처리(
  함: 우편함, 개인쪽: string, 기관열쇠: string,
  요청: { id: string; device_user_id: string; asked_enc: string },
): Promise<boolean> {
  let 온것: 온것;
  try {
    온것 = JSON.parse(await 싼것풀기(개인쪽, 요청.asked_enc)) as 온것;
  } catch {
    /*
     * 못 풉니다 — 우리 공개쪽이 아닌 것으로 쌌거나 내용이 바뀌었습니다.
     * 왜 못 푸는지는 **말해 주지 않습니다.**
     */
    await 함.요청답하기(요청.id, { status: "거절", reason: 안맞음 });
    return false;
  }

  const 아이디 = (온것.아이디 ?? "").trim();
  const 비밀번호 = 온것.비밀번호 ?? "";
  const 공개쪽 = (온것.공개쪽 ?? "").trim();
  const 표식 = (온것.표식 && typeof 온것.표식 === "object") ? 온것.표식 : null;

  if (!아이디 || !비밀번호 || 공개쪽.length < 40) {
    await 함.요청답하기(요청.id, { status: "거절", reason: 안맞음 });
    return false;
  }

  /*
   * ★ 열 번 틀린 아이디는 **맞춰 보지도 않습니다.**
   *   비밀번호 대조는 일부러 무겁게(argon2) 되어 있어서, 이것을 안 막으면
   *   맞혀 보는 쪽이 사무실 PC 를 붙잡아 두는 셈이 되기도 합니다.
   */
  if (잠겼나(아이디)) {
    await 함.요청답하기(요청.id, { status: "거절", reason: 안맞음 });
    console.log(`계정 로그인: ${아이디} — 여러 번 틀려 잠시 막습니다`);
    return false;
  }

  const 사람 = db
    .query<{
      id: number; name: string; pw_hash: string;
      status: string; role: string; roles: string | null;
    }, [string]>(
      "SELECT id, name, pw_hash, status, role, roles FROM app_user WHERE login_id = ?")
    .get(아이디);

  /*
   * ★ 제공인력이 아니면 **비밀번호를 맞춰 보기 전에** 물러납니다.
   *
   *   처음에는 비밀번호를 먼저 맞춰 보고, 그다음 「현장앱은 제공인력만
   *   씁니다」라고 답했습니다. 그런데 그 말이 곧 **「비밀번호가 맞았다」는
   *   확인 응답**입니다. 관리자 계정으로 정답을 넣어 본 사람이 그 말을
   *   들으면, 사무실 화면에 들어갈 비밀번호를 손에 쥔 것입니다.
   *   여태 이 PC 안에만 있던 관리자 계정이 그 한 줄 때문에
   *   인터넷에서 대조 가능해졌습니다. (2026-09-05 에 막음)
   *
   *   그래서 제공인력이 아닌 계정은 **아이디가 없는 것과 똑같이** 답합니다.
   *   현장앱을 쓸 사람이 아니니 안내할 것도 없습니다.
   */
  const 역할들 = 사람
    ? (사람.roles ? (JSON.parse(사람.roles) as string[]) : [사람.role])
    : [];
  const 현장사람 = !!사람 && 역할들.includes("worker");

  /*
   * ★ 아이디가 없어도 **비밀번호를 맞춰 보는 시늉을 합니다.**
   *   없는 아이디는 바로 돌아가고 있는 아이디는 잠깐 걸리면, 그 시간
   *   차이만으로 「이 아이디는 있다」를 알아낼 수 있습니다.
   *   제공인력이 아닌 계정도 같은 까닭으로 시늉을 합니다.
   */
  const 가짜해시 = "$argon2id$v=19$m=65536,t=2,p=1$YWFhYWFhYWFhYWFhYWFhYQ$" +
                   "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
  const 맞나 = await verifyPassword(비밀번호, 현장사람 ? 사람!.pw_hash : 가짜해시);

  if (!현장사람 || !맞나) {
    실패셈(아이디);
    await 함.요청답하기(요청.id, { status: "거절", reason: 안맞음 });
    return false;
  }

  /*
   * 여기서부터는 **제공인력 본인인 것이 확인된 뒤**입니다.
   * 계약이 끝난 것은 알려 줘야 합니다 — 안 알려 주면 맞는 비밀번호를
   * 몇 번씩 고쳐 치다 사무실에 전화가 옵니다. 그리고 이 사실은
   * 본인이 이미 아는 것이라 새로 새는 것이 없습니다.
   */
  if (사람!.status !== "active") {
    await 함.요청답하기(요청.id, {
      status: "거절", reason: "계약이 끝난 분입니다. 사무실에 문의해 주세요.",
    });
    return false;
  }
  실패지우기(아이디);

  // ── 들입니다 ──
  const 인력번호 = 우편함번호(사람!.id);
  await 함.인력올리기(인력번호, true);   // 아직 한 번도 등록 안 한 분일 수 있습니다

  /*
   * ── 알릴 것인가, 조용히 넘길 것인가 ──────────────────────
   *
   * 앞 기기의 표식과 **같으면** 브라우저만 바꿔 여신 것입니다.
   * 그때는 홈에 안 띄웁니다 — 거짓 알림이 잦으면 사무실이 알림
   * 자체를 안 읽게 되고, 그러면 정작 남이 들어왔을 때 넘어갑니다.
   *
   * ★ 확실할 때만 조용합니다. 앞 표식이 없거나(옛 앱에서 들어옴)
   *   이번 표식이 비어 있으면 **알립니다.** 모르면 알리는 쪽입니다.
   *
   * ★ 첫 기기(끊은 것이 없음)도 안 띄웁니다. 「바뀐」 것이 아니고,
   *   사무실이 아이디·비밀번호를 알려 주며 시킨 일입니다.
   */
  const 앞표식 = 표식들()[인력번호];
  const 같은폰 = 같은폰인가(앞표식, 표식);

  const 싼열쇠 = await 싸기(공개쪽, 기관열쇠);
  const { 끊은수 } = await 함.기기바꾸기(인력번호, 요청.device_user_id, 공개쪽, 싼열쇠);

  /*
   * 여기서부터 터지면 「거절」로 답하면 안 됩니다 — 위 catch 가 봅니다.
   */
  try {
    await 함.요청답하기(요청.id, {
      status: "됨", answer_enc: 싼열쇠, worker_id: 인력번호,
    });
  } catch (e) {
    (e as any).들인뒤 = true;
    /* 표식만은 남겨 둡니다 — 다음 차례에 같은 폰으로 알아보게 */
    if (표식) 표식적기(인력번호, 표식);
    throw e;
  }

  if (표식) 표식적기(인력번호, 표식);

  // 기록은 **늘** 남깁니다. 알림을 안 띄운 것까지 나중에 볼 수 있어야 합니다.
  기록적기({
    때: new Date().toISOString(),
    이름: 사람!.name, 인력번호, 표식: 표식글(표식), 같은폰, 끊은수,
  });

  /*
   * ★ 「끊은 기기가 있을 때만 알린다」는 틀렸습니다 (2026-09-05 에 고침) ★
   *
   *   폰을 잃어버려 사무실이 「이 기기 끊기」를 누르면 그 인력의
   *   worker_device 가 0줄이 됩니다. 비밀번호를 쥔 사람이 **바로 뒤에**
   *   들어오면 끊을 것이 없으니 `끊은수 = 0` — 조용히 통과했습니다.
   *   **끊는 행위가 다음 침입을 안 보이게 만들고 있었습니다.**
   *
   *   그래서 앞 표식이 남아 있으면 기기가 0줄이어도 견줍니다.
   *   진짜 조용한 것은 **이 사람에 대해 아무것도 모를 때**뿐입니다.
   */
  const 처음보는사람 = !앞표식 && 끊은수 === 0;
  const 알릴까 = !같은폰 && !처음보는사람;
  if (알릴까) {
    바뀜적기({
      때: new Date().toISOString(),
      이름: 사람!.name, 인력id: 사람!.id, 인력번호, 끊은수,
    });
  }

  console.log(`계정 로그인: ${사람!.name} 님이 들어왔습니다` +
              (같은폰 ? " (같은 휴대폰 · 브라우저만 바뀜)"
                      : 끊은수 ? ` (앞 기기 ${끊은수}대 끊음 — 홈에 알림)` : " (첫 휴대폰)"));
  return true;
}

/**
 * 5초. 보고 받기(20초)보다 빠릅니다.
 *
 * 사람이 폰 화면을 보며 **서서 기다리는** 일이기 때문입니다. 20초는
 * 현장에서 「안 되나 보다」 하고 다시 누르게 되는 길이입니다.
 * 오가는 것은 요청 목록 한 줄이라 가볍습니다.
 */
export const 살피는주기 = 5 * 1000;

export function 로그인받기시작(): void {
  if (!우편함.설정읽기()) return;

  let 조용히 = 0;
  /*
   * ★ 앞 차례가 아직 안 끝났으면 **건너뜁니다** (2026-09-05 에 막은 구멍) ★
   *
   *   `setInterval` 은 앞 실행이 끝났는지 안 봅니다. 로그인 한 건에
   *   비밀번호 대조 한 번과 우편함 왕복 대여섯 번이 들어가므로,
   *   요청이 몰리면 5초를 넘기고 실행이 **겹칩니다.**
   *
   *   겹치면 같은 요청을 두 번 꺼냅니다(상태는 맨 끝에서야 바뀝니다).
   *   그러면 `기기바꾸기` 가 둘 다 「지울 옛 기기」를 같은 것으로 읽고,
   *   결국 **한 사람에게 폰 두 대가 살아남습니다.** 이 파일이 있는
   *   까닭인 「한 사람 한 대」가 바로 그 자리에서 깨집니다.
   */
  let 도는중 = false;
  const 한번 = async () => {
    if (도는중) return;
    도는중 = true;
    try {
      const r = await 요청살피기();
      if (r.본것) {
        console.log(`계정 로그인: 요청 ${r.본것}건 — 들임 ${r.들인수}, 막음 ${r.막은수}`);
      }
      조용히 = 0;
    } catch (e) {
      /*
       * 5초마다 도는 일이라 실패하면 화면이 오류로 뒤덮입니다.
       * 처음 한 번만 알리고, 그 뒤로는 조용히 다시 시도합니다.
       * (같은 까닭으로 현장앱도 세 번 실패해야 사람에게 알립니다.)
       */
      if (조용히 === 0)
        console.error("계정 로그인: 우편함을 못 봤습니다 —", (e as Error).message);
      조용히++;
      if (조용히 >= 60) 조용히 = 0;              // 5분마다 한 번은 다시 알립니다
    } finally {
      도는중 = false;
    }
  };

  setTimeout(한번, 9000);                        // 보내기(3초)·받기(6초) 다음에
  setInterval(한번, 살피는주기);
}

// ── 홈의 「이 기기 끊기」 ───────────────────────────────────

/** 그 인력의 기기를 전부 뗍니다. 본인이 다시 로그인하면 됩니다. */
export async function 기기끊기(인력번호: string): Promise<number> {
  const 설정 = 우편함.설정읽기();
  if (!설정) return 0;
  return new 우편함(설정).그인력기기전부끊기(인력번호);
}
