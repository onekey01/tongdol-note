/** 사람이 읽을 한 줄. 기록 화면에 그대로 나갑니다. */
export function 표식글(표?: 표식 | null): string {
  if (!표) return "(표식 없음)";
  const 쪽: string[] = [];
  if (표.바탕) 쪽.push(표.바탕 + (표.버전 ? " " + 표.버전 : ""));
  if (표.모델) 쪽.push(표.모델);
  if (표.화면) 쪽.push(표.화면 + (표.배율 ? ` · x${표.배율}` : ""));
  if (표.코어) 쪽.push(`${표.코어}코어`);
  return 쪽.length ? 쪽.join(" · ") : "(표식 없음)";
}

/**
 * ── 같은 폰인가 ─────────────────────────────────────────────
 *
 * 두 층으로 봅니다.
 *
 *   **강한 쪽** — 양쪽 다 모델을 내주었을 때. 크로미움 계열은
 *   브라우저가 달라도 같은 모델명을 내주므로 이때가 가장 믿을 만합니다.
 *
 *   **약한 쪽** — 한쪽이라도 모델이 없을 때(사파리·파이어폭스).
 *   바탕·화면·배율·코어만 봅니다. 같은 기종 두 대는 못 가립니다 —
 *   그건 넘어가기로 했습니다 (2026-09-05 무무).
 *
 * ★ 비교할 거리가 없으면 **다르다고 봅니다.** 모르면 알리는 쪽입니다.
 *   여기서 "모르니까 같은 걸로 치자"고 하면 알림이 통째로 죽습니다.
 */
export function 같은폰인가(앞?: 표식 | null, 이번?: 표식 | null): boolean {
  if (!앞 || !이번) return false;

  // 바탕이 다르면 볼 것도 없습니다 (안드로이드 → 아이폰).
  if (!앞.바탕 || !이번.바탕 || 앞.바탕 !== 이번.바탕) return false;

  if (앞.모델 && 이번.모델) {
    // 강한 쪽. 버전은 폰이 업데이트되면 바뀌므로 **안 봅니다.**
    return 앞.모델 === 이번.모델
        && (!앞.화면 || !이번.화면 || 앞.화면 === 이번.화면);
  }

  // 약한 쪽 — 화면이 없으면 가릴 힘이 없습니다.
  if (!앞.화면 || !이번.화면) return false;
  return 앞.화면 === 이번.화면
      && 앞.배율 === 이번.배율
      && 앞.코어 === 이번.코어;
}

