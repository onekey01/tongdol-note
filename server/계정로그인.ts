/*
 * ★ 왜 세야 하나 (2026-09-05 에 막은 구멍) ★
 *
 *   기관 공개열쇠는 **누구에게나** 열려 있습니다(폰이 기관을 골라야
 *   하니까요). 그래서 인터넷 아무나 {아이디, 비밀번호} 를 싸서 넣을 수
 *   있고, 이 PC 는 5초마다 성실하게 맞춰 봅니다.
 *
 *   횟수 제한이 없으면 이것은 **무제한 비밀번호 대조기**입니다.
 *   그것도 이 PC 안에만 있던 `app_user` 전체 — **관리자 계정까지** —
 *   를 상대로요.
 *
 *   그래서 아이디마다 세고, 열 번 틀리면 15분 동안 아예 안 맞춰 봅니다.
 *   현장에서 진짜로 헷갈리는 분도 열 번을 넘기지는 않습니다.
 */
const 참을횟수 = 10;
const 잠글시간 = 15 * 60_000;

type 실패기록 = Record<string, { 수: number; 마지막: number }>;

function 실패들(): 실패기록 {
  try { return JSON.parse(metaGet(실패칸) || "{}") as 실패기록; }
  catch { return {}; }
}
function 실패쓰기(것: 실패기록) { metaSet(실패칸, JSON.stringify(것)); }

/** 지금 이 아이디가 잠겨 있나. 잠긴 시간이 지났으면 스스로 풀립니다. */
function 잠겼나(아이디: string): boolean {
  const 것 = 실패들()[아이디];
  if (!것) return false;
  if (Date.now() - 것.마지막 > 잠글시간) return false;
  return 것.수 >= 참을횟수;
}

function 실패셈(아이디: string) {
  const 전부 = 실패들();
  const 것 = 전부[아이디];
  const 지났나 = !것 || Date.now() - 것.마지막 > 잠글시간;
  전부[아이디] = { 수: 지났나 ? 1 : 것.수 + 1, 마지막: Date.now() };

  /*
   * 아이디를 바꿔 가며 두드리면 이 표가 한없이 커집니다.
   * 오래된 것은 버립니다 — 어차피 잠글시간이 지나면 뜻이 없습니다.
   */
  const 기준 = Date.now() - 잠글시간;
  for (const k of Object.keys(전부))
    if (전부[k].마지막 < 기준) delete 전부[k];
  실패쓰기(전부);
}

function 실패지우기(아이디: string) {
  const 전부 = 실패들();
  if (전부[아이디]) { delete 전부[아이디]; 실패쓰기(전부); }
}

