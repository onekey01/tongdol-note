let 마지막확인 = 0;
const 확인주기 = 5 * 60_000;

async function 공개쪽맞추기(함: 우편함): Promise<void> {
  if (Date.now() - 마지막확인 < 확인주기) return;
  마지막확인 = Date.now();
  await 열쇠쌍챙기기(함);
}

