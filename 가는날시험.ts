/**
 * **「이 날에 가나?」** — 답하는 곳이 하나인지 지킵니다 (v34).
 *
 *   bun 가는날시험.ts
 *
 * (2026-09-08 무무 — 한도를 넘는 계획은 막기로 했는데, 막고 보니
 *  **동행지원(월 2회)·이미용(월 1회)은 배정 자체가 안 됐습니다.**
 *  「가!로 하자」 = 배정에 주기를 넣을 것.)
 *
 * 여기서 보는 것:
 *   1) 매주(0)는 지금까지와 **한 글자도 안 다르다** ← 이미 쓰는 기관 보호
 *   2) 「한 달에 N번」은 그 달의 해당 요일 중 **앞에서 N개**
 *   3) **다섯 주짜리 달에도 정확히 N번** ← 격주로 안 만든 까닭
 *   4) 달이 바뀌면 다시 N번부터
 *   5) 배정 기간 밖은 안 센다
 *   6) 요일이 여럿이어도 **날짜 순서로** 앞에서 N개
 *   7) 구간에 걸쳐 세면 **달마다 따로** 센다
 *   8) 그날가나 와 그달가는날 이 **같은 답**을 한다 ← 두 길이 갈리면 안 됩니다
 */
import { 그달가는날, 그날가나, 가는날세기, 달몇번, 주기말 } from "./server/가는날";

let 통과수 = 0, 실패수 = 0;
function 통과해야(무엇: string, 참: unknown, 덧말 = "") {
  if (참) { 통과수++; console.log(`  통과  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
}
const 배정 = (요일들: number[], n: number, from = "2026-01-01", to = "2026-12-31") => ({
  weekly_plan: JSON.stringify(요일들.map((d) => ({ dow: d, minutes: 60 }))),
  period_from: from, period_to: to, monthly_times: n,
});

try {
  // ── 1. 매주는 예전 그대로 ────────────────────────────────
  console.log("\n── 1. 매주(0)는 지금까지 그대로 ─────────────────────────\n");
  /* 2026년 9월 수요일: 2·9·16·23·30 — 다섯 번 */
  const 매주 = 그달가는날(배정([3], 0), "2026-09");
  통과해야("9월 수요일 다섯 번을 다 갑니다", 매주.length === 5, 매주.join(" "));
  통과해야("첫 날은 9월 2일", 매주[0] === "2026-09-02");
  통과해야("끝 날은 9월 30일", 매주[4] === "2026-09-30");

  // ── 2·3. 한 달에 N번 ────────────────────────────────────
  console.log("\n── 2. 한 달에 몇 번 ─────────────────────────────────────\n");
  const 두번 = 그달가는날(배정([3], 2), "2026-09");
  통과해야("「한 달에 2번」은 **앞의 두 번**", 두번.length === 2, 두번.join(" "));
  통과해야("9월 2일과 9월 9일", 두번[0] === "2026-09-02" && 두번[1] === "2026-09-09");
  const 한번 = 그달가는날(배정([3], 1), "2026-09");
  통과해야("「한 달에 1번」은 첫 번만", 한번.length === 1 && 한번[0] === "2026-09-02");

  console.log("\n── 3. ★ 다섯 주짜리 달에도 정확히 N번 ───────────────────\n");
  /*
   * 이것이 **격주로 안 만든 까닭**입니다. 격주였다면 수요일이 다섯 번
   * 오는 달에 2일·16일·30일 — **세 번**이 되어 월 2회 한도를 넘습니다.
   */
  통과해야("9월(수요일 5번)에도 두 번뿐", 그달가는날(배정([3], 2), "2026-09").length === 2);
  const 열두달 = Array.from({ length: 12 }, (_, i) =>
    그달가는날(배정([3], 2), `2026-${String(i + 1).padStart(2, "0")}`).length);
  통과해야("열두 달 **모두** 두 번 (격주였다면 어떤 달은 세 번)",
    열두달.every((n) => n === 2), 열두달.join(","));

  // ── 4. 달이 바뀌면 다시 ─────────────────────────────────
  console.log("\n── 4. 달이 바뀌면 다시 셉니다 ───────────────────────────\n");
  const 시월 = 그달가는날(배정([3], 2), "2026-10");
  통과해야("10월도 앞의 두 번부터", 시월.length === 2, 시월.join(" "));
  통과해야("9월 것을 이어 세지 않습니다", 시월[0].startsWith("2026-10"));

  // ── 5. 배정 기간 밖 ─────────────────────────────────────
  console.log("\n── 5. 배정 기간 밖은 안 셉니다 ──────────────────────────\n");
  const 늦게 = 그달가는날(배정([3], 2, "2026-09-15", "2026-12-31"), "2026-09");
  통과해야("9월 15일부터면 16일·23일", 늦게.join(" ") === "2026-09-16 2026-09-23", 늦게.join(" "));
  const 일찍끝 = 그달가는날(배정([3], 0, "2026-01-01", "2026-09-10"), "2026-09");
  통과해야("9월 10일에 끝나면 2일·9일뿐", 일찍끝.join(" ") === "2026-09-02 2026-09-09");

  // ── 6. 요일이 여럿 ──────────────────────────────────────
  console.log("\n── 6. 요일이 여럿이면 날짜 순서로 ───────────────────────\n");
  /* 월·수: 9/2(수) 9/7(월) 9/9(수) … 앞의 두 개 */
  const 월수 = 그달가는날(배정([1, 3], 2), "2026-09");
  통과해야("월·수 중 **날짜가 빠른 두 개**",
    월수.join(" ") === "2026-09-02 2026-09-07", 월수.join(" "));

  // ── 7. 구간에 걸쳐 세기 ─────────────────────────────────
  console.log("\n── 7. 구간을 세면 달마다 따로 ───────────────────────────\n");
  통과해야("9~10월 두 달이면 4번",
    가는날세기(배정([3], 2), "2026-09-01", "2026-10-31") === 4);
  통과해야("매주였다면 9번",
    가는날세기(배정([3], 0), "2026-09-01", "2026-10-31") === 9,
    String(가는날세기(배정([3], 0), "2026-09-01", "2026-10-31")));
  통과해야("반쪽 달도 그 달 기준으로 셉니다",
    가는날세기(배정([3], 2), "2026-09-10", "2026-09-30") === 0,
    "9월의 앞 두 번은 2일·9일이라 10일 뒤에는 없습니다");

  // ── 8. 두 길이 같은 답을 하나 ★ ─────────────────────────
  console.log("\n── 8. ★ 두 길이 같은 답을 합니다 ────────────────────────\n");
  let 어긋남 = 0, 본날 = 0;
  for (const n of [0, 1, 2, 3]) {
    const a = 배정([1, 3, 5], n);
    for (const 달 of ["2026-09", "2026-10", "2026-11"]) {
      const 목록 = new Set(그달가는날(a, 달));
      const [y, m] = 달.split("-").map(Number);
      const 끝일 = new Date(Date.UTC(y, m, 0)).getUTCDate();
      for (let d = 1; d <= 끝일; d++) {
        const ymd = `${달}-${String(d).padStart(2, "0")}`;
        본날++;
        if (그날가나(a, ymd) !== 목록.has(ymd)) 어긋남++;
      }
    }
  }
  통과해야("그날가나 와 그달가는날 이 **한 날도 안 어긋납니다**",
    어긋남 === 0, `${본날}날 확인, 어긋남 ${어긋남}`);

  // ── 9. 사람이 읽는 말 ───────────────────────────────────
  console.log("\n── 9. 값 다루기 ─────────────────────────────────────────\n");
  통과해야("0 은 매주", 달몇번({ monthly_times: 0 }) === 0 && 주기말(0) === "매주");
  통과해야("2 는 「한 달에 2번」", 주기말(2) === "한 달에 2번");
  통과해야("음수·빈값은 매주로", 달몇번({ monthly_times: -3 }) === 0
    && 달몇번({}) === 0 && 달몇번({ monthly_times: null }) === 0);
  통과해야("요일이 없으면 아무 날도 안 갑니다",
    그달가는날({ weekly_plan: "[]", monthly_times: 2 }, "2026-09").length === 0);
} catch (e: any) {
  실패수++;
  console.log(`\n✗ 시험 도중 터졌습니다 — ${e?.message ?? e}`);
  if (e?.stack) console.log(String(e.stack).split("\n").slice(1, 4).join("\n"));
} finally {
  console.log(`\n${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
  process.exit(실패수 ? 1 : 0);
}
