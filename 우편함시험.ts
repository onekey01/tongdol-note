/**
 * 우편함 자물쇠 시험 —  bun 우편함시험.ts
 *
 * 여기서 보는 것 —
 *   1. 잠갔다 풀면 그대로인가 (한글·긴 글·빈 글)
 *   2. 열쇠가 다르면 못 여는가
 *   3. 한 글자만 건드려도 못 여는가
 *   4. **덩어리 안에 원문이 비치지 않는가**  ← 이게 핵심입니다
 *   5. 같은 글을 두 번 잠그면 다른 덩어리인가
 *   6. 등록표 해시가 SQL 쪽과 같은 값인가
 */
import {
  새열쇠, 잠그기, 풀기, 짐싸기, 짐풀기, 새등록표, 표해시,
  키쌍만들기, 싸기, 싼것풀기,
} from "./server/우편함자물쇠";

let 통과수 = 0, 실패수 = 0;
function 같아야(무엇: string, 실제: unknown, 바람: unknown) {
  if (실제 === 바람) { 통과수++; console.log(`  통과  ${무엇}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}\n          나온 것 ${JSON.stringify(실제)}\n          바란 것 ${JSON.stringify(바람)}`); }
}
async function 던져야(무엇: string, f: () => Promise<unknown>) {
  try { await f(); 실패수++; console.log(`✗ 실패  ${무엇} — 안 던졌습니다`); }
  catch { 통과수++; console.log(`  통과  ${무엇}`); }
}

const 열쇠 = 새열쇠();

console.log("\n── 1. 잠갔다 풀면 그대로 ────────────────────────────\n");
for (const 글 of [
  "김복순",
  "해남군 해남읍 성내리 12-3 행복아파트 101동 502호",
  "010-1234-5678",
  "",
  "줄이\n바뀌어도\t탭이 있어도",
  "가".repeat(5000),
  '따옴표 " 와 백슬래시 \\ 와 이모지 🌱',
]) {
  const c = await 잠그기(열쇠, 글);
  같아야(`「${글.slice(0, 18) || "빈 글"}${글.length > 18 ? "…" : ""}」`, await 풀기(열쇠, c), 글);
}

console.log("\n── 2. 열쇠가 다르면 ────────────────────────────────\n");
{
  const c = await 잠그기(열쇠, "비밀");
  await 던져야("남의 열쇠로는 못 엽니다", () => 풀기(새열쇠(), c));
  await 던져야("길이가 틀린 열쇠는 막힙니다", () => 풀기("짧다", c));
}

console.log("\n── 3. 한 글자만 건드려도 ───────────────────────────\n");
{
  const c = await 잠그기(열쇠, "김복순 · 010-1234-5678");
  const [v, 소금, 몸] = c.split(".");
  const 바꾸기 = (s: string) => (s[0] === "A" ? "B" : "A") + s.slice(1);
  await 던져야("잠긴 글을 건드리면",   () => 풀기(열쇠, `${v}.${소금}.${바꾸기(몸)}`));
  await 던져야("소금을 건드리면",      () => 풀기(열쇠, `${v}.${바꾸기(소금)}.${몸}`));
  await 던져야("모양이 다르면",        () => 풀기(열쇠, "그냥 글자"));
  await 던져야("버전이 다르면",          () => 풀기(열쇠, `v9.${소금}.${몸}`));
}

console.log("\n── 4. 덩어리에 원문이 비치나 ★ ─────────────────────\n");
{
  const 사람 = {
    이름: "김복순", 생년월일: "1938-04-12",
    주소: "전라남도 해남군 해남읍 성내리 12-3",
    연락처: "010-1234-5678", 서비스: "가사지원",
  };
  const 덩어리 = await 짐싸기(열쇠, 사람);
  for (const [칸, 값] of Object.entries(사람)) {
    같아야(`덩어리에 ${칸}(${값}) 이 안 보임`, 덩어리.includes(값), false);
  }
  // 조각으로도 안 보여야 합니다
  for (const 조각 of ["김복순", "해남", "1938", "1234", "가사"]) {
    같아야(`조각 「${조각}」 도 안 보임`, 덩어리.includes(조각), false);
  }
  같아야("풀면 되돌아옴", JSON.stringify(await 짐풀기(열쇠, 덩어리)), JSON.stringify(사람));
}

console.log("\n── 5. 같은 글도 매번 다르게 ────────────────────────\n");
{
  const a = await 잠그기(열쇠, "같은 글");
  const b = await 잠그기(열쇠, "같은 글");
  같아야("두 번 잠그면 다른 덩어리", a === b, false);
  같아야("그래도 둘 다 풀림", await 풀기(열쇠, a), await 풀기(열쇠, b));
}

console.log("\n── 6. 등록표 ───────────────────────────────────────\n");
{
  const 표 = 새등록표();
  같아야("표가 매번 다름", 표 === 새등록표(), false);
  const h = await 표해시(표);
  같아야("해시는 64자리 16진수", /^[0-9a-f]{64}$/.test(h), true);
  같아야("같은 표는 같은 해시", h, await 표해시(표));
  /*
   * SQL 쪽과 **같은 값**이어야 합니다.
   * 아래 값은 Postgres 에서 직접 뽑은 것입니다 —
   *   select encode(digest('표-1234','sha256'),'hex');
   * 여기가 어긋나면 폰이 만든 등록표를 우편함이 못 알아봅니다.
   */
  같아야("SQL 의 digest() 와 같은 값", await 표해시("표-1234"),
    "09eb233b09bb72422f90dcb303f20c0e3fcd914e3d8c9e56955be59b377bda06");
}

console.log("\n── 7. 열쇠 싸서 건네기 ★ ───────────────────────────\n");
{
  /*
   * QR 에서 기관 열쇠를 뺀 자리입니다.
   * 휴대폰이 만든 공개쪽으로 기관 열쇠를 싸서 우편함에 두고,
   * 그 폰의 개인쪽으로만 풀리는지 봅니다.
   */
  const 기관열쇠 = 새열쇠();
  const 폰 = await 키쌍만들기();
  const 싼것 = await 싸기(폰.공개, 기관열쇠);

  같아야("그 폰은 품", await 싼것풀기(폰.개인, 싼것), 기관열쇠);
  같아야("싼 것에 기관 열쇠가 안 비침", 싼것.includes(기관열쇠), false);
  같아야("싼 것이 w1 모양", 싼것.startsWith("w1."), true);

  const 남의폰 = await 키쌍만들기();
  await 던져야("남의 폰은 못 품", () => 싼것풀기(남의폰.개인, 싼것));

  // 같은 열쇠를 두 번 싸도 매번 달라야 합니다 (쌀 때마다 새 쌍을 씁니다)
  같아야("두 번 싸면 다른 덩어리", (await 싸기(폰.공개, 기관열쇠)) === 싼것, false);
  같아야("그래도 둘 다 풀림",
    await 싼것풀기(폰.개인, await 싸기(폰.공개, 기관열쇠)), 기관열쇠);

  // 한 글자만 건드려도 안 풀려야 합니다
  const [w, 공, 소, 몸] = 싼것.split(".");
  const 바꾸기 = (x: string) => (x[0] === "A" ? "B" : "A") + x.slice(1);
  await 던져야("싼 글을 건드리면", () => 싼것풀기(폰.개인, `${w}.${공}.${소}.${바꾸기(몸)}`));
  await 던져야("보낸이 공개쪽을 건드리면", () => 싼것풀기(폰.개인, `${w}.${바꾸기(공)}.${소}.${몸}`));
  await 던져야("모양이 다르면", () => 싼것풀기(폰.개인, "아무거나"));

  // 공개쪽은 새어도 되는 값입니다 — 그것만으로는 못 풉니다
  같아야("공개쪽에 개인쪽이 안 비침", 폰.공개.includes(폰.개인.slice(0, 24)), false);
}

console.log(`\n${"─".repeat(56)}\n  ${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
if (실패수) process.exit(1);
