/**
 * 30분 단위 환산 — A-1 (7-바).
 *
 *   bun 환산시험.ts
 *
 * **함수보다 이 시험이 먼저 나왔습니다.** 돈이 걸린 셈은 「어떻게 만들까」보다
 * 「무엇이 맞나」를 먼저 못박아야 합니다.
 *
 * 편람이 정한 것 —
 *
 *   | 실제 제공 시간 | 인정   |
 *   | 15분 미만      | 0 (미산정) |
 *   | 15분 ~ 45분 미만 | 30분  |
 *   | 45분 이상      | 1시간  |
 *
 * 세 줄뿐이라 **1시간을 넘으면 어떻게 되는지**는 안 적혀 있습니다.
 * 그래서 이 규칙을 **30분마다 되풀이되는 것**으로 읽습니다 —
 * 1시간 15분은 1시간 30분, 1시간 45분은 2시간.
 *
 * **이 해석이 맞습니다** (2026-09-03 무무 님 확인) — 「30분 단위로 계산.
 * 30분 / 1시간 / 1시간30분 / 2시간 / 2시간30분 / 3시간」.
 *
 * 3시간에서 멈추는 것은 편람의 다른 줄 때문입니다 —
 * 「○ (제 공 기 준) **1일 최대 3시간**(평일 오전 9시 ~오후 6시)」.
 * 그 상한은 `billing.실적줄들` 이 걸고, 여기(`money.인정분`)는 **환산만**
 * 합니다. 두 규칙을 한 함수에 섞으면 나중에 어느 쪽이 걸렸는지 못 봅니다.
 * (하루상한시험.ts 가 그쪽을 봅니다.)
 */
import { 인정분, 인정시간 } from "./server/money";

let 통과수 = 0, 실패수 = 0;
function 같아야(무엇: string, 실제: unknown, 바람: unknown) {
  const ok = 실제 === 바람;
  if (ok) { 통과수++; console.log(`  통과  ${무엇}   — ${실제}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}   — ${실제} (${바람} 이어야 함)`); }
}
function 참이어야(무엇: string, 참: unknown, 덧말 = "") {
  if (참) { 통과수++; console.log(`  통과  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
}

console.log("\n── 1. 편람이 적어 둔 세 줄 ──────────────────────────────\n");

같아야("14분 → 미산정", 인정분(14), 0);
같아야("**15분 → 30분** (여기서 처음 돈이 생깁니다)", 인정분(15), 30);
같아야("30분 → 30분", 인정분(30), 30);
같아야("44분 → 30분", 인정분(44), 30);
같아야("**45분 → 1시간**", 인정분(45), 60);
같아야("50분 → 1시간", 인정분(50), 60);
같아야("60분 → 1시간", 인정분(60), 60);

console.log("\n── 2. 경계 — 여기가 틀리면 돈이 틀립니다 ────────────────\n");

같아야("0분", 인정분(0), 0);
같아야("1분", 인정분(1), 0);
같아야("14분 (경계 바로 앞)", 인정분(14), 0);
같아야("15분 (경계)", 인정분(15), 30);
같아야("44분 (경계 바로 앞)", 인정분(44), 30);
같아야("45분 (경계)", 인정분(45), 60);
같아야("74분 (경계 바로 앞)", 인정분(74), 60);
같아야("75분 (경계)", 인정분(75), 90);
같아야("104분 (경계 바로 앞)", 인정분(104), 90);
같아야("105분 (경계)", 인정분(105), 120);

console.log("\n── 3. 1시간을 넘으면 — 30분마다 되풀이 ──────────────────\n");

같아야("70분 → 1시간", 인정분(70), 60);
같아야("90분 → 1시간 30분", 인정분(90), 90);
같아야("120분 → 2시간", 인정분(120), 120);
같아야("135분 → 2시간 30분", 인정분(135), 150);
같아야("180분 → 3시간", 인정분(180), 180);

console.log("\n── 4. **지금 틀리게 셈하던 그것** ───────────────────────\n");

참이어야("**40분을 1시간으로 치지 않는다** — 30분입니다", 인정분(40) === 30,
  `40분 → ${인정분(40)}분`);
참이어야("**10분 다녀오고 1시간을 청구하지 않는다** — 0원입니다", 인정분(10) === 0,
  `10분 → ${인정분(10)}분`);

console.log("\n── 5. 이상한 값이 들어와도 안 터진다 ───────────────────\n");

같아야("음수는 0", 인정분(-5), 0);
같아야("비어 있으면 0", 인정분(null as any), 0);
같아야("숫자가 아니면 0", 인정분("가" as any), 0);
같아야("소수점은 내림 (30.9분은 30분으로 보고 셉니다)", 인정분(30.9), 30);

console.log("\n── 6. 시간으로도 꺼낼 수 있다 (단가 곱하는 자리에서) ────\n");

같아야("30분은 0.5시간", 인정시간(30), 0.5);
