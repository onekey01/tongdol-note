참이어야("**24,000원짜리 가사지원을 40분 하면 12,000원**",
  Math.round(인정시간(40) * 24000) === 12000,
  `${Math.round(인정시간(40) * 24000).toLocaleString("ko-KR")}원`);
참이어야("**10분이면 0원** (안 간 것과 같은 금액입니다)",
  Math.round(인정시간(10) * 24000) === 0);

/* ─────────────────────────────────────────────────────────────
 * 7. **청구서까지 이어져 나오는가**
 *
 * 함수가 맞는 것과 돈이 맞는 것은 다른 이야기입니다.
 * 실제 실적을 넣고 `linesOf` 가 뽑는 금액을 봅니다.
 * ───────────────────────────────────────────────────────────── */
console.log("\n── 7. 실적을 넣고 청구 금액을 봅니다 ────────────────────\n");

const { randomUUID } = await import("node:crypto");
const { db, initDb } = await import("./server/db");
initDb();
const { linesOf } = await import("./server/billing");

const 사람 = randomUUID();
const 프로필: any = db.query(
  `SELECT rp.* FROM region_profile rp JOIN organization o ON o.profile_id = rp.id WHERE o.id = 1`
).get();

function 서비스(name: string, unit: string, 단가: number) {
  const i = db.run(
    `INSERT INTO service (profile_id, code, cat_l, cat_m, cat_s, name, unit, unit_price,
                          holiday_price, record_type, lifetime_cap, sort_order, active, custom)
     VALUES (?,?,'시험','시험','시험',?,?,?,NULL,'time',NULL,900,1,1)`,
    [프로필.id, `CONV-${randomUUID().slice(0, 8)}`, name, unit, 단가]);
  return Number(i.lastInsertRowid);
}
function 실적(svc: number, 날: string, 분: number | null) {
  db.run(
    `INSERT INTO delivery (recipient_id, service_id, served_on, outcome, is_holiday, minutes, created_at)
     VALUES (?,?,?,'제공',0,?,'x')`, [사람, svc, 날, 분]);
}

const 가사 = 서비스("시험가사", "hour", 24000);
const 식사 = 서비스("시험식사", "meal", 11000);
try {
  db.run(
    `INSERT INTO recipient (id, payload, dong, status, created_at, updated_at)
     VALUES (?,?,?,?,?,?)`,
    [사람, JSON.stringify({ name: "환산시험" }), "해남읍", "이용", "2026-09-01", "x"]);

  실적(가사, "2026-09-02", 40);     // 30분 인정 → 12,000
  실적(가사, "2026-09-03", 60);     // 1시간     → 24,000
  실적(가사, "2026-09-04", 10);     // 미산정    →      0
  const 줄 = linesOf(사람, "2026-09");
  const 가사줄: any = 줄.find((x: any) => x.serviceId === 가사);

  참이어야("**40분 + 60분 + 10분 = 36,000원**", 가사줄?.amount === 36_000,
    `${(가사줄?.amount ?? 0).toLocaleString("ko-KR")}원`);
  참이어야("전에 셈하던 방식이면 72,000원이었습니다 (세 번 × 1시간)",
    가사줄?.amount !== 72_000, "그렇게 안 나옵니다");
  같아야("진행시간은 110분 (실제로 있었던 시간)", 가사줄?.진행분, 110);
  같아야("제공시간은 90분 (인정된 시간)", 가사줄?.인정분합, 90);
  같아야("**15분을 못 넘긴 방문이 1건** — 서식8 에 적을 것입니다",
    가사줄?.미산정건수, 1);
  같아야("간 횟수는 그대로 3번", 가사줄?.count, 3);

  // 분을 안 적은 옛 실적
  실적(가사, "2026-09-05", null);
  const 줄2: any = linesOf(사람, "2026-09").find((x: any) => x.serviceId === 가사);
  참이어야("**분을 안 적었으면 예전처럼 한 번 = 한 시간**",
    줄2.amount === 36_000 + 24_000,
    `${줄2.amount.toLocaleString("ko-KR")}원 (지난 청구서가 안 흔들립니다)`);

  // 식사는 끼라서 분을 안 봅니다
  실적(식사, "2026-09-02", 5);      // 5분이어도 한 끼는 한 끼
  const 식사줄: any = linesOf(사람, "2026-09").find((x: any) => x.serviceId === 식사);
  참이어야("**식사는 분을 안 봅니다** — 5분이어도 한 끼는 11,000원",
    식사줄.amount === 11_000, `${식사줄.amount.toLocaleString("ko-KR")}원`);
  같아야("식사는 진행시간도 안 셉니다", 식사줄.진행분, 0);
} finally {
  db.run("DELETE FROM delivery WHERE recipient_id = ?", [사람]);
  db.run("DELETE FROM recipient WHERE id = ?", [사람]);
  db.run("DELETE FROM service WHERE id IN (?,?)", [가사, 식사]);
}

console.log(`\n${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
process.exit(실패수 ? 1 : 0);
