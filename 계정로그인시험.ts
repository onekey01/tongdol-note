/*
 * ★ 진짜만큼 깐깐하게 만듭니다 ★
 *   특히 `기기바꾸기` 는 진짜처럼 **그 인력의 다른 기기를 지웁니다.**
 *   여기서 무르게 하면 「한 사람 한 대」 시험이 헛통과합니다.
 */
type 기기 = { user_id: string; worker_id: string; pub_key: string; wrapped_key: string };
