async function 사람넣기(
  login: string, 이름: string, 비번: string,
  역할: string[], 상태 = "active",
): Promise<number> {
  db.run("DELETE FROM app_user WHERE login_id = ?", [login]);
  db.run(
    "INSERT INTO app_user (login_id, pw_hash, name, role, roles, status, created_at) " +
    "VALUES (?, ?, ?, ?, ?, ?, ?)",
    [login, await hashPassword(비번), 이름, 역할[0], JSON.stringify(역할),
     상태, new Date().toISOString()]);
  return db.query<{ id: number }, [string]>(
    "SELECT id FROM app_user WHERE login_id = ?").get(login)!.id;
}

