const 흉내 = {
  올라간공개쪽: async () => 올린공개쪽,
  기관공개쪽올리기: async (p: string) => { 올린공개쪽 = p; },
  기다리는요청: async () =>
    [...요청들.values()].filter((r) => r.status === "기다림"),
  요청답하기: async (id: string, 답: any) => {
    const r = 요청들.get(id);
    if (!r) throw new Error("그런 요청이 없습니다");
    Object.assign(r, 답);
  },
  인력올리기: async () => {},
  그인력기기들: async (w: string) => 기기들.filter((d) => d.worker_id === w),
  기기바꾸기: async (w: string, 새user: string, pub: string, wrapped: string) => {
    const 옛것 = 기기들.filter((d) => d.worker_id === w && d.user_id !== 새user);
    기기들.push({ user_id: 새user, worker_id: w, pub_key: pub, wrapped_key: wrapped });
    for (const o of 옛것) 기기들.splice(기기들.indexOf(o), 1);
    return { 끊은수: 옛것.length };
  },
  그인력기기전부끊기: async (w: string) => {
    const 것 = 기기들.filter((d) => d.worker_id === w);
    for (const o of 것) 기기들.splice(기기들.indexOf(o), 1);
    return 것.length;
  },
};

