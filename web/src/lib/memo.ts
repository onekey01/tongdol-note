/**
 * 「지금 이 사람 메모를 열어 달라」고 보드에 알리는 한 줄.
 *
 * ── 왜 이런 것이 필요한가 ──────────────────────────────────
 * 메모 보드는 보통 **주소**를 보고 어느 보드를 열지 정합니다.
 * 대상자 화면(/recipients/…)에 들어가면 그 사람 보드가 열립니다.
 *
 * 그런데 기록지에서 이름을 누르는 것은 주소가 바뀌지 않습니다.
 * 같은 화면에서 그 사람 칸이 아래로 펼쳐질 뿐입니다.
 * 상태변화 상세내용과 비고를 적는 그 자리에서 **그 어르신 메모가 옆에 떠 있어야**
 * 보고 적습니다. 종이로 일할 때 서류철에서 쪽지를 꺼내 옆에 두는 것과 같습니다.
 *
 * 그래서 화면이 보드에게 직접 말을 겁니다.
 */

/** 그 대상자 보드를 열어 둡니다. 빈 값을 주면 기관 보드로 돌아갑니다. */
export function 메모보드열기(recipientId: string, name = '') {
  try {
    window.dispatchEvent(new CustomEvent('memo:board', {
      detail: { id: recipientId || '', name },
    }))
  } catch { /* 아주 오래된 브라우저 — 메모가 안 열릴 뿐 하던 일은 그대로 됩니다 */ }
}
