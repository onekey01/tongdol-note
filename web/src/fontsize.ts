/**
 * 글자 크기.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────
 * 이 프로그램은 **하루 종일 보는 화면**입니다. 그리고 사무실에는
 * 나이가 있는 직원이 함께 앉아 있습니다. 만든 사람 눈에 알맞은 크기가
 * 그분들께는 **읽히지 않는 크기**입니다. 안 보이면 잘못 읽고,
 * 잘못 읽은 것이 청구서로 나갑니다.
 *
 * 윈도우 배율(125%·150%)을 올리면 되긴 하지만 **컴퓨터 전체가 커집니다.**
 * 남의 프로그램까지 다 바뀌는 것을 공용 PC 에서 하기는 어렵습니다.
 * 그래서 **이 프로그램만** 크게 볼 수 있게 합니다.
 *
 * ── 어떻게 ─────────────────────────────────────────────────
 * 화면 크기는 전부 `rem` 으로 적혀 있습니다(px 는 한 군데도 없습니다).
 * `rem` 은 **뿌리 글자 크기의 배수**라, 뿌리 하나만 바꾸면 글자도 칸도
 * 여백도 함께 커집니다. 글자만 키우면 칸이 안 커져서 글이 잘립니다.
 *
 * ── 어디에 저장하는가 ──────────────────────────────────────
 * **그 사람의 브라우저에만** 둡니다(테마와 같은 자리). 자료함에 넣으면
 * 눈이 좋은 직원이 키운 크기를 남이 물려받습니다. 이건 **기관의 설정이
 * 아니라 그 사람 눈의 문제**입니다.
 */
export type 글자크기 = '보통' | '크게' | '아주 크게'

const KEY = 'fontSize'

/*
 * 뿌리 글자 크기(px). 브라우저 기본이 16px 이라 「보통」이 그 값입니다.
 *
 * **셋만 둡니다.** 넷으로 하면 단추가 한 줄에 안 들어가 줄이 접히고,
 * 무엇보다 「크게」와 「더 크게」의 차이가 눈에 잘 안 띄어 고르기가 어렵습니다.
 * 눈이 어두우신 분께 필요한 것은 **눈에 띄게 큰 것**이지 미세 조정이 아닙니다.
 */
export const 크기들: { value: 글자크기; px: number; 곁말: string }[] = [
  { value: '보통', px: 16, 곁말: '기본' },
  { value: '크게', px: 19, 곁말: '약 1.2배' },
  { value: '아주 크게', px: 22, 곁말: '약 1.4배' },
]

export function 글자크기읽기(): 글자크기 {
  const v = localStorage.getItem(KEY)
  return 크기들.some((x) => x.value === v) ? (v as 글자크기) : '보통'
}

export function 글자크기정하기(고른것: 글자크기) {
  localStorage.setItem(KEY, 고른것)
  글자크기붙이기(고른것)
}

export function 글자크기붙이기(고른것: 글자크기 = 글자크기읽기()) {
  const px = 크기들.find((x) => x.value === 고른것)?.px ?? 16
  document.documentElement.style.fontSize = `${px}px`
}
