/**
 * 인쇄 단추 — **한 곳에서 만들어 모든 화면이 씁니다.**
 *
 * ═══════════════════════════════════════════════════════════
 *  왜 화면마다 따로 안 만드나
 * ═══════════════════════════════════════════════════════════
 *
 * `인쇄목록.md` 에 적어 둔 원칙 그대로입니다 —
 *
 * > 화면마다 따로 붙이면 **어떤 건 A4에 맞고 어떤 건 잘리는 일이 반드시
 * > 생깁니다.** 머리글에 기관명·뽑은 날짜·뽑은 사람. **종이가 돌아다니다
 * > 출처를 잃습니다.**
 *
 * 기관명·뽑은 때·뽑은 사람은 `Layout` 이 한 곳에서 붙입니다.
 * 여기는 그 아래 한 줄 — **「무엇을, 어떤 조건으로 뽑았나」**입니다.
 *
 * ═══════════════════════════════════════════════════════════
 *  ★★★ 거른 조건을 종이에 적는 것이 이 부품의 핵심입니다 ★★★
 * ═══════════════════════════════════════════════════════════
 *
 * 대상자 명단은 **지금 화면의 거르기·정렬 그대로** 나갑니다. 그런데
 * 거르개는 화면에만 있고 종이에는 안 찍힙니다. 그러면 「이용 중인 분만」
 * 걸러 뽑은 12명짜리 종이가 **전체 명단처럼** 보입니다.
 *
 * 회의 탁자에 놓인 그 장을 보고 「우리 기관 대상자가 12명이구나」 하면,
 * 실제 40명 중 28명이 없는 채로 이야기가 굴러갑니다. 종이는 스스로를
 * 설명할 수 없으므로 **뽑을 때 적어 두어야** 합니다.
 *
 * 그래서 `조건` 을 받습니다. 화면에는 안 보이고 **종이에만** 나옵니다.
 */
import type { ReactNode } from 'react'

export default function 인쇄단추({
  무엇, 조건 = [], 수, 덧말, children,
}: {
  /** 무엇을 뽑는가. 「대상자 명단」·「종사자 명부」 */
  무엇: string
  /** 지금 걸린 거르기·정렬. 빈 것은 알아서 빠집니다. */
  조건?: (string | false | null | undefined)[]
  /** 몇 줄짜리인가. 한 장 빠진 것을 나중에 알아채는 유일한 실마리입니다. */
  수?: number
  /** 그 밖에 종이에 남길 말. */
  덧말?: string
  /** 단추 옆에 더 둘 것 (다른 인쇄 단추 등). */
  children?: ReactNode
}) {
  const 걸린것 = 조건.filter(Boolean) as string[]
  return (
    <>
      {/*
        ── 종이에만 나오는 줄 ────────────────────────────────
        `.print-when` 은 화면에서 `display:none`, 인쇄에서만 보입니다.
      */}
      <div className="print-when">
        {무엇}
        {걸린것.length > 0 && <> — {걸린것.join(' · ')}</>}
        {수 != null && <> · 모두 {수}건</>}
        {덧말 && <> · {덧말}</>}
      </div>

      <div className="btns 인쇄단추">
        <button onClick={() => window.print()} title="브라우저 인쇄 창이 열립니다. 「PDF 로 저장」도 여기서 됩니다.">
          인쇄 · PDF
        </button>
        {children}
      </div>
    </>
  )
}
