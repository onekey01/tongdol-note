/**
 * 노쇼와 사전취소 가르기 — A-3 (7-아).
 *
 *   bun 노쇼시험.ts
 *
 * **함수보다 이 시험이 먼저 나왔습니다.** A-1·A-2 와 같은 차례입니다.
 *
 * 계약서(서식2) 4조가 선을 그어 놓았습니다 —
 *
 *   「이용자가 **사전 취소 없이** … 서비스를 이용하지 않으셨더라도
 *    비용이 지출되며, 1인당 연간 지원한도액에서 차감됩니다.」
 *
 * 여기서 보는 것:
 *   1) 갈래 네 가지 중 **노쇼만** 돈이 든다
 *   2) 갈래를 안 적은 **옛 미제공은 「기타」** — 지난 청구서가 안 흔들린다
 *   3) 계약서의 선은 **예정일 하루 전**
 *   4) 노쇼가 **청구서에 오른다**
 *   5) 노쇼가 **연간 한도를 깎는다**
 *   6) 노쇼가 **월 한도에도 든다** (두 화면이 다른 말을 하면 안 됩니다)
 *   7) 실적을 적고 되돌리면 갈래도 따라온다
 */
import { randomUUID } from "node:crypto";
import { db, initDb } from "./server/db";
initDb();
import {
  갈래읽기, 돈이드나, 사전취소선, 늦게알렸나, 기본갈래, 갈래들,
} from "./server/미제공";
import { 한도에드나, 연간쓴돈, 월사용 } from "./server/한도";
