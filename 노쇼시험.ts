import { setCell, month as recordMonth } from "./server/record";
import { today } from "./server/util";

let 통과수 = 0, 실패수 = 0;
function 같아야(무엇: string, 실제: unknown, 바람: unknown) {
  if (실제 === 바람) { 통과수++; console.log(`  통과  ${무엇}   — ${실제}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}   — ${실제} (${바람} 이어야 함)`); }
}
function 참이어야(무엇: string, 참: unknown, 덧말 = "") {
  if (참) { 통과수++; console.log(`  통과  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
  else { 실패수++; console.log(`✗ 실패  ${무엇}${덧말 ? "   — " + 덧말 : ""}`); }
}

const 사람 = randomUUID();
const 프로필: any = db.query(
  `SELECT rp.* FROM region_profile rp JOIN organization o ON o.profile_id = rp.id WHERE o.id = 1`
).get();
const 만든서비스: number[] = [];
const 만든배정: number[] = [];

function 서비스(name: string, unit: string, 단가: number, 한도분 = 0, 한도횟수 = 0) {
  const i = db.run(
    `INSERT INTO service (profile_id, code, cat_l, cat_m, cat_s, name, unit, unit_price,
                          holiday_price, record_type, lifetime_cap, outside_annual_cap,
                          monthly_cap_minutes, monthly_cap_count, noshow_billable,
                          sort_order, active, custom)
     VALUES (?,?,'시험','시험','시험',?,?,?,NULL,'time',NULL,0,?,?,1,900,1,1)`,
    [프로필.id, `NOSHOW-${randomUUID().slice(0, 8)}`, name, unit, 단가, 한도분, 한도횟수]);
  const id = Number(i.lastInsertRowid); 만든서비스.push(id); return id;
}
function 실적(svc: number, 날: string, o: {
  분?: number | null; outcome?: string; 갈래?: string | null; 알린날?: string | null;
} = {}) {
  db.run(
    `INSERT INTO delivery (recipient_id, service_id, served_on, outcome, is_holiday,
                           minutes, reason, miss_kind, notified_on, created_at)
     VALUES (?,?,?,?,0,?,?,?,?,'x')`,
    [사람, svc, 날, o.outcome ?? "미제공", o.분 ?? null,
     o.outcome === "제공" ? "" : "부재", o.갈래 ?? null, o.알린날 ?? null]);
}

try {
  db.run(
    `INSERT INTO recipient (id, payload, dong, status, created_at, updated_at)
     VALUES (?,?,?,?,?,?)`,
    [사람, JSON.stringify({ name: "노쇼시험" }), "해남읍", "이용", "2026-09-01", "x"]);

  // ── 1. 갈래 읽기 ──────────────────────────────────────────
  console.log("\n── 1. 갈래는 네 가지, 모르는 값은 「기타」 ──────────────\n");

  같아야("갈래는 네 가지", 갈래들.length, 4);
  같아야("「노쇼」", 갈래읽기("노쇼"), "노쇼");
  같아야("「사전취소」", 갈래읽기("사전취소"), "사전취소");
  같아야("**비어 있으면 기타** (옛 미제공)", 갈래읽기(null), "기타");
  같아야("빈 글자도 기타", 갈래읽기(""), "기타");
  같아야("모르는 값도 기타", 갈래읽기("아무거나"), "기타");

  // ── 2. 돈이 드는 갈래는 하나뿐 ────────────────────────────
  console.log("\n── 2. **노쇼만** 돈이 듭니다 ───────────────────────────\n");

  참이어야("노쇼는 돈이 든다", 돈이드나("노쇼"));
  참이어야("**사전취소는 안 든다**", !돈이드나("사전취소"));
  참이어야("기관사정은 안 든다 (이용자 잘못이 아닙니다)", !돈이드나("기관사정"));
  참이어야("기타는 안 든다", !돈이드나("기타"));

  // ── 3. 한도에드나 — 온 프로그램이 보는 한 곳 ───────────────
  console.log("\n── 3. 한도에 드나 (온 프로그램이 보는 한 곳) ───────────\n");

  참이어야("제공은 당연히 든다", 한도에드나("제공", null));
  참이어야("**미제공 + 노쇼 → 든다** (계약서 4조)", 한도에드나("미제공", "노쇼"));
  참이어야("미제공 + 사전취소 → 안 든다", !한도에드나("미제공", "사전취소"));
  참이어야("미제공 + 기관사정 → 안 든다", !한도에드나("미제공", "기관사정"));
  참이어야("**갈래 없는 옛 미제공 → 안 든다**", !한도에드나("미제공", null),
    "지난 청구서가 안 흔들립니다");

  // ── 4. 계약서가 그은 선 — 예정일 하루 전 ──────────────────
  console.log("\n── 4. 선은 **예정일 하루 전** ──────────────────────────\n");

  같아야("9월 10일의 선은 9월 9일", 사전취소선("2026-09-10"), "2026-09-09");
  같아야("달을 넘어가도 맞는다", 사전취소선("2026-09-01"), "2026-08-31");
  같아야("해를 넘어가도 맞는다", 사전취소선("2026-01-01"), "2025-12-31");
  같아야("윤달 다음날", 사전취소선("2028-03-01"), "2028-02-29");

  참이어야("**하루 전에 알렸으면 늦지 않다**", !늦게알렸나("2026-09-10", "2026-09-09"));
  참이어야("사흘 전도 늦지 않다", !늦게알렸나("2026-09-10", "2026-09-07"));
  참이어야("**당일에 알렸으면 늦었다**", 늦게알렸나("2026-09-10", "2026-09-10"));
  참이어야("**아무 말이 없었으면 늦었다**", 늦게알렸나("2026-09-10", null));

  // ── 5. 사유가 갈래를 미리 골라 줍니다 ─────────────────────
  console.log("\n── 5. 사유가 갈래를 **미리 골라 줍니다** (고칠 수 있음) ─\n");

  console.log("   (노쇼를 **켠** 지자체 기준입니다. 기본은 꺼짐 — 아래 6번)\n");
  같아야("부재 → 노쇼", 기본갈래("부재", true), "노쇼");
  같아야("거부 → 노쇼", 기본갈래("거부", true), "노쇼");
  같아야("입원 → 사전취소", 기본갈래("입원", true), "사전취소");
  같아야("본인요청 → 사전취소", 기본갈래("본인요청", true), "사전취소");
  같아야("기관사정 → 기관사정", 기본갈래("기관사정", true), "기관사정");
  같아야("기상·재해 → 기타", 기본갈래("기상·재해", true), "기타");
  같아야("사유가 없으면 기타", 기본갈래(null, true), "기타");

  /*
   * ── 기본은 꺼져 있습니다 (2026-09-01) ──────────────────────
   * 해남 현장은 노쇼를 안 씁니다 — 가사·동행·이미용은 **일정을 사전 조율**해
   * 다시 잡고, 식사는 「대면/비대면」이 그 자리입니다(`대면배달시험`).
   * 그래도 계약서 4조가 **어르신께 인쇄되어 나가는 종이**에 적혀 있어서
   * 기능은 남겨 둡니다 — 켠 지자체에서는 위 그대로 돕니다.
   */
  같아야("**끈 곳에서는 부재도 노쇼가 아닙니다** (이것이 기본)",
    기본갈래("부재"), "기타");
  같아야("끈 곳에서도 사전취소는 그대로", 기본갈래("입원"), "사전취소");

  // ── 6. 청구서에 오르는가 ──────────────────────────────────
  console.log("\n── 6. **노쇼가 청구서에 오릅니다** ─────────────────────\n");

  const 가사 = 서비스("시험가사", "hour", 24000, 720, 0);
  실적(가사, "2026-09-01", { outcome: "제공", 분: 60 });     // 24,000
  실적(가사, "2026-09-02", { 갈래: "노쇼" });                 // 24,000 (안 갔지만 나갑니다)
  실적(가사, "2026-09-03", { 갈래: "사전취소", 알린날: "2026-09-02" });
  실적(가사, "2026-09-04", { 갈래: "기관사정" });
  실적(가사, "2026-09-05", { 갈래: null });                   // 옛 미제공

  let 줄: any = linesOf(사람, "2026-09").find((x: any) => x.serviceId === 가사);
  같아야("**제공 1회 + 노쇼 1회 = 48,000원**", 줄?.amount, 48_000);
  같아야("노쇼가 몇 건인지 따로 셉니다 (서식·화면에 밝힙니다)", 줄?.노쇼건수, 1);
  같아야("건수는 2건 (사전취소·기관사정·옛것은 안 셉니다)", 줄?.count, 2);
  참이어야("**사전취소는 한 푼도 안 나간다**",
    줄.amount !== 72_000, "셋 다 셌으면 72,000원이었습니다");

  console.log("\n   노쇼는 **안 간 것**이라 분이 없습니다 — 한 번 = 한 시간입니다.\n");
  같아야("진행시간은 제공한 60분뿐", 줄?.진행분, 60);

  // ── 7. 연간 한도를 깎는가 ─────────────────────────────────
  console.log("\n── 7. **노쇼가 연간 한도를 깎습니다** (계약서 4조) ─────\n");

  const h = 연간쓴돈(사람, 2026);
  같아야("올해 쓴 돈도 48,000원", h.일상.쓴돈, 48_000);
  const 가사줄 = h.줄.find((x) => x.serviceId === 가사)!;
  같아야("한도 줄에도 2건", 가사줄.건수, 2);
  참이어야("**청구서와 한도가 같은 말을 합니다**", h.일상.쓴돈 === 줄.amount,
    `${h.일상.쓴돈.toLocaleString("ko-KR")}원`);

  // ── 8. 월 한도에도 드는가 ─────────────────────────────────
  console.log("\n── 8. **노쇼가 월 한도에도 듭니다** ────────────────────\n");

  const m: any = 월사용(사람, "2026-09").find((x) => x.serviceId === 가사);
  같아야("제공 1회 + 노쇼 1회 = 2회", m?.쓴횟수, 2);
  같아야("**노쇼는 분이 없으니 한 시간** — 합쳐서 2시간", m?.인정분합, 120);
  참이어야("사전취소는 월 한도도 안 깎는다", m?.쓴횟수 === 2, "5건 중 2건만");

  // ── 9. 옛 자료가 안 흔들리는가 ────────────────────────────
  console.log("\n── 9. **갈래 없는 옛 미제공은 지금까지 그대로** ────────\n");

  const 옛것 = 서비스("시험옛것", "hour", 24000);
  실적(옛것, "2026-10-01", { outcome: "제공", 분: 60 });
  실적(옛것, "2026-10-02", { 갈래: null });
  실적(옛것, "2026-10-03", { 갈래: null });
  const 옛줄: any = linesOf(사람, "2026-10").find((x: any) => x.serviceId === 옛것);
  같아야("**미제공 두 건은 한 푼도 안 붙는다**", 옛줄?.amount, 24_000);
  같아야("노쇼도 0건", 옛줄?.노쇼건수, 0);

  // ── 10. 실적을 적어 보고 되돌려 보기 ──────────────────────
  console.log("\n── 10. 실적을 적고 되돌리면 갈래도 따라옵니다 ──────────\n");

  /*
   * setCell 은 **아직 오지 않은 날**을 막습니다. 그래서 날짜를 못박지 않고
   * 오늘에서 되짚어 잡습니다 — 달이 바뀌어도 이 시험이 그대로 돌아야 합니다.
   */
  const 오늘 = today();
  const 달 = Number(오늘.slice(8)) >= 3
    ? 오늘.slice(0, 7)
    : 사전취소선(`${오늘.slice(0, 7)}-01`).slice(0, 7);
  const 날A = `${달}-01`, 날B = `${달}-02`;

  const 배정 = Number(db.run(
    `INSERT INTO assignment (recipient_id, service_id, weekly_plan, period_from, period_to,
                             created_at)
     VALUES (?,?,?,?,?,'x')`,
    [사람, 가사, "1,3", 날A, `${달}-31`]).lastInsertRowid);
  만든배정.push(배정);

  let r: any = setCell({
    assignId: 배정, on: 날A, state: "미제공", reason: "부재",
  });
  같아야("**갈래를 안 보내면 사유가 골라 준 것**이 들어갑니다", r.missKind, "노쇼");

  r = setCell({
    assignId: 배정, on: 날A, state: "미제공", reason: "입원",
    missKind: "사전취소", notifiedOn: 사전취소선(날A),
  });
  같아야("사람이 고른 갈래가 이깁니다", r.missKind, "사전취소");
  같아야("알린 날도 남습니다", r.notifiedOn, 사전취소선(날A));
  참이어야("하루 전에 알렸으니 안 늦었습니다", !r.늦음);

  r = setCell({
    assignId: 배정, on: 날A, state: "미제공", reason: "입원",
    missKind: "사전취소", notifiedOn: 날A,
  });
  참이어야("**당일에 알린 것은 늦었다고 알려 줍니다** (막지는 않습니다)", r.늦음,
    "계약서 4조 — 예정일 하루 전");

  r = setCell({ assignId: 배정, on: 날A, state: "제공", minutes: 40 });
  같아야("**제공으로 되돌리면 갈래가 지워집니다**", r.missKind, null);
  같아야("알린 날도 지워집니다", r.notifiedOn, null);
  같아야("분은 살아 있습니다 (A-1)", r.minutes, 40);

  // 화면이 갈래를 볼 수 있는가
  setCell({
    assignId: 배정, on: 날B, state: "미제공", reason: "부재", missKind: "노쇼",
  });
  const 화면 = recordMonth(달);
  const 그줄: any = 화면.items.find((x: any) => x.assignId === 배정);
  const 그칸: any = 그줄?.cells.find((c: any) => c.on === 날B);
  같아야("실적 화면이 갈래를 봅니다", 그칸?.missKind, "노쇼");
  같아야("줄에 노쇼가 몇 건인지 셉니다", 그줄?.노쇼, 1);
  참이어야("한 달 합계에도 노쇼가 있습니다", (화면.tally as any).노쇼 >= 1,
    `${(화면.tally as any).노쇼}건`);
} catch (e: any) {
  실패수++;
  console.log(`\n✗ 시험 도중 터졌습니다 — ${e?.message ?? e}`);
  if (e?.stack) console.log(String(e.stack).split("\n").slice(1, 4).join("\n"));
} finally {
  db.run("DELETE FROM delivery WHERE recipient_id = ?", [사람]);
  for (const a of 만든배정) db.run("DELETE FROM assignment WHERE id = ?", [a]);
  db.run("DELETE FROM recipient WHERE id = ?", [사람]);
  for (const s of 만든서비스) db.run("DELETE FROM service WHERE id = ?", [s]);
  console.log(`\n${통과수 + 실패수}가지 중 ${통과수}가지 통과, ${실패수}가지 실패\n`);
  process.exit(실패수 ? 1 : 0);
}
