--  통돌 Note — 우편함 010 : 로그인 요청을 조입니다
--
--  008 을 넣고 코드를 다시 읽다가 찾은 것입니다.
--
--  ── 무엇이 헐거웠나 ────────────────────────────────────────
--
--    008 의 폰 정책이 이랬습니다 —
--
--        for all using (device_user_id = auth.uid())
--
--    `for all` 은 **읽기·넣기·고치기·지우기 전부**입니다. 그래서 폰이
--    자기 줄을 **마음대로 고칠 수 있었습니다.**
--
--    ① 답이 달린 줄의 `asked_enc` 를 갈아 끼우고 `status` 를 다시
--       `'기다림'` 으로 되돌리면, **줄 하나로 비밀번호를 무한히**
--       맞춰 볼 수 있습니다. 줄 수를 세는 것으로는 못 잡습니다.
--
--    ② `expires_at` 을 몇 년 뒤로 넣으면 **비밀번호가 든 덩어리**가
--       우편함에 영영 눌러앉습니다. 쓸어내기가 못 지웁니다.
--
--    ③ 넣을 때 `status = '됨'` 과 `answer_enc` 를 제가 채워 넣을 수도
--       있었습니다. 열쇠를 못 만드니 들어가지는 못하지만, 사무실
--       처리 대기 줄을 어지럽히기에는 충분합니다.
--
--  ── 어떻게 조이나 ──────────────────────────────────────────
--
--    폰이 정말 해야 하는 일은 **둘뿐**입니다 —
--      · 자기 요청을 **넣는다**
--      · 자기 요청의 답을 **읽는다**
--
--    고치기·지우기는 필요 없습니다. 그래서 뺍니다. 그리고 넣을 때
--    **사무실이 채울 칸은 비워서** 내게 합니다.
--
--  008 을 이미 실행하셨다면 이 파일만 더 붙여넣으시면 됩니다.
--  여러 번 실행해도 안전합니다.
-- ============================================================

drop policy if exists device_request_폰 on public.device_request;

-- ── 넣기 — 자기 이름으로, 빈 칸은 빈 채로 ──────────────────
--
--  ★ `status`·`answer_enc`·`worker_id` 는 **사무실이 채우는 칸**입니다.
--    폰이 미리 채워 넣지 못하게 막습니다.
--  ★ `expires_at` 은 20분 안쪽만 받습니다. 기본값은 15분이라 그냥
--    두면 통과하고, 멀리 잡아 넣으려는 것만 걸립니다.
create policy device_request_폰넣기 on public.device_request
  for insert to authenticated
  with check (
    device_user_id = auth.uid()
    and status = '기다림'
    and answer_enc is null
    and worker_id is null
    and expires_at <= now() + interval '20 minutes'
  );

-- ── 읽기 — 자기가 낸 것만 ──────────────────────────────────
--
--  남이 낸 요청은 여전히 한 줄도 안 보입니다. 답(기관 열쇠를 싼 것)을
--  엉뚱한 폰이 집어 가면 그 기관의 모든 어르신 자료가 열립니다.
create policy device_request_폰읽기 on public.device_request
  for select to authenticated
  using (device_user_id = auth.uid());

-- 고치기·지우기 정책은 **일부러 안 만듭니다.**
-- RLS 는 정책이 없으면 막는 쪽이라, 이것으로 폰은 못 고칩니다.

