const 원본 = new Hwpx(readFileSync(templatePath()));
const 표 = (d: Hwpx) => d.tables()[1];
const 칸글 = (d: Hwpx, r: number, c: number) => d.cellText(d.cell(표(d), r, c));

/** 줄마다 칸의 너비·붙임 — 생김새가 그대로인지 보는 잣대. */
const 생김새 = (d: Hwpx) =>
  d.rows(표(d)).map((r) =>
    d.cells(r).map((c) => {
      const sz = kids(c, "cellSz")[0], sp = kids(c, "cellSpan")[0];
      return `${attr(sz!, "width")}/${attr(sp!, "colSpan")}/${attr(sp!, "rowSpan")}`;
    }).join(" ")
  );

/** 실적 줄들의 테두리 차례. 굵은 아래선(165)은 맨 밑에 하나여야 합니다. */
const 테두리 = (d: Hwpx) =>
  d.rows(표(d)).slice(10).map((tr) => attr(d.cells(tr)[0], "borderFillIDRef")).join(" ");

