  const c = new Hwpx(build(여덟 as 비용총괄값));
  같아야("표가 19행 (16 + 3)", c.rows(표(c)).length, 19);
  같아야("rowCnt 도 19", attr(표(c), "rowCnt"), "19");
  같아야("여덟째 줄 연번", 칸글(c, 17, 0), "8");
