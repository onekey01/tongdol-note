  같아야("보고 연월 (빈칸 수를 지켜 「월」 앞에 붙임)", 날짜줄.trim(), "2026년   9월");
  참이어야("시설장 성명", (줄들.find((t) => t.includes("시설장")) ?? "").includes("박병섭"));
