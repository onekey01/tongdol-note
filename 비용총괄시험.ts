  const t = 테두리(c);
  같아야("테두리 차례", t, "53 51 51 51 51 51 51 165 61");

  // rowAddr 가 처음부터 다시 매겨졌는지
  let 어긋남 = 0;
  c.rows(표(c)).forEach((tr, ri) => {
    for (const tc of c.cells(tr))
      for (const a of kids(tc, "cellAddr"))
        if (attr(a, "rowAddr") !== String(ri)) 어긋남++;
  });
  같아야("rowAddr 어긋남", 어긋남, 0);

  // 늘어난 줄의 **칸 너비**가 원본 줄과 같은가
